#ifndef XLS_PASSES_TO_ZERO_EXT_PASS_H_
#define XLS_PASSES_TO_ZERO_EXT_PASS_H_

#include <string_view>

#include "absl/status/statusor.h"
#include "xls/ir/function_base.h"
#include "xls/passes/optimization_pass.h"
#include "xls/passes/pass_base.h"

namespace xls {

// Converts any canonicalized zero-exts back from concat(zero, ...) to zero_ext
// since it generally makes for easier to read/visualize graphs. This pass
// is not meant to be used as an optimization pass at all.
//
// Note: What follows was generated by the Gemini LLM. Not human verified.
//
// `ToZeroExtPass` (`to_zero_ext`) is a debugging and visualization pass that
// converts `concat` operations with leading zero operands back into explicit
// `zero_ext` operations.
//
// During standard XLS optimization pipelines, passes such as narrowing or bit
// slicing often canonicalize or decompose a `zero_ext` into a `concat` of a
// zero literal and the narrower value. While convenient for bit-level
// transformations, these extra zero literals and `concat` nodes can clutter IR
// graphs in visualizers and debugging dumps. `ToZeroExtPass` restores them to
// single-operand `zero_ext` nodes.
//
// ### How It Works
//
// 1. **Query Engine Setup**:
//    Acquires a shared `PartialInfoQueryEngine` for the `FunctionBase` and
//    iterates over nodes in topological order (`context.TopoSort(f)`).
//
// 2. **Matching Zero-Extension-Like Concats (`ZeroExtLike::Make`)**:
//    For each `Concat` node `n`, the pass checks `ZeroExtLike::Make(n, *qe)`.
//    A `Concat` matches if:
//    * Its total bit width is greater than zero, and
//    * Every operand except the last (least-significant) operand is proven to
//      be all zeros (`qe.IsAllZeros(op)`).
//
// 3. **Replacement**:
//    Replaces the matching `Concat` node with a `zero_ext` (`ExtendOp` with
//    `Op::kZeroExt`) that extends the last operand (`ext_like->to_extend()`) to
//    the full bit width of the `Concat` (`n->BitCountOrDie()`).
//
// ### Example
//
// ```
// // Before
// fn extend_val(x: bits[8]) -> bits[16] {
//   zeros: bits[8] = literal(value=0)
//   ret ext: bits[16] = concat(zeros, x)
// }
// ```
//
// After `ToZeroExtPass`:
//
// ```
// // After
// fn extend_val(x: bits[8]) -> bits[16] {
//   ret ext: bits[16] = zero_ext(x, new_bit_count=16)
// }
// ```
class ToZeroExtPass : public OptimizationFunctionBasePass {
 public:
  static constexpr std::string_view kName = "to_zero_ext";
  ToZeroExtPass()
      : OptimizationFunctionBasePass(kName, "DebugPass: To ZeroExt Pass") {}
  ~ToZeroExtPass() override = default;

 protected:
  absl::StatusOr<bool> RunOnFunctionBaseInternal(
      FunctionBase* f, const OptimizationPassOptions& options,
      PassResults* results, OptimizationContext& context) const override;
};
}  // namespace xls

#endif  // XLS_PASSES_TO_ZERO_EXT_PASS_H_
