namespace xls {

// A pass version of 'remove_identifers_main'. Running this pass will rewrite
// the package to remove the names of all functions, procs, nodes, channels,
// etc.
//
// This should only be used while investigating optimizer behavior using the
// ir-visualizer or other tools.
//
// Warning: This pass does not preserve externally visible names. Once run on a
// design the various io-constraint and other configs which rely on naming
// pieces of the design will not work. This pass is only for dev/ investigatory
// purposes.
//
// Note: This pass **does not** preserve the id number of nodes.
//
// Note: What follows was generated by the Gemini LLM. Not human verified.
//
// `RemoveIdentifiersPass` (`remove_identifiers_unsafe`) anonymizes an XLS
// `Package` in-place by stripping human-readable names and source location
// information from functions, procs, blocks, channels, state elements,
// registers, and IR nodes. It provides an optimization-pass interface to the
// `StripPackage` utility (`remove_identifiers_main`).
//
// ### How It Works
//
// 1. **Constructing a Stripped Clone (`StripPackage`)**:
//    The pass calls `StripPackage(p, options_)` (where default `StripOptions`
//    set `new_package_name = "subrosa"` and enable `strip_location_info`,
//    `strip_node_names`, `strip_function_names`, `strip_chan_names`, and
//    `strip_reg_names`):
//    * **Source Locations**: File-number mappings (`fileno_to_name`) are
//      omitted and every node's `SourceInfo` is reset to an empty
//      `SourceInfo()` when `strip_location_info` is true.
//    * **Channels**: Package-scoped and proc-scoped channels are renamed
//      sequentially to `chan_0`, `chan_1`, etc. when `strip_chan_names` is
//      true.
//    * **Functions, Procs, and Blocks**: Cloned in post-order
//      (`FunctionsInPostOrder`) and renamed sequentially to `function_<N>`,
//      `proc_<N>`, or `block_<N>` using a shared counter when
//      `strip_function_names` is true.
//    * **State Elements and Registers**: Within each proc, state elements are
//      renamed to `state_0`, `state_1`, etc. when `strip_node_names` is true.
//      Within each block, registers are renamed to `register_0`, `register_1`,
//      etc. and the clock port is renamed to `"clock"` when `strip_reg_names`
//      is true.
//    * **Nodes**: When `strip_node_names` is true, `Param` nodes are renamed to
//      `"param"` (auto-uniquified by XLS as `param`, `param__1`, etc.),
//      `PortNode`s are renamed to `"port"`, and all other nodes have their
//      explicit names cleared via `ClearName()` so they print using their
//      opcode and newly assigned node ID (e.g., `add.3`).
//
// 2. **In-Place Package Replacement (`RunInternal`)**:
//    The pass clears the original package `p` (clearing `Top`, removing all
//    existing `FunctionBase`s and `Channel`s, and calling `ClearFiles()`),
//    imports the anonymized contents from the temporary stripped package via
//    `p->ImportFromPackage(new_p.get())`, restores the renamed `Top` entity via
//    `p->SetTopByName(...)`, and rebuilds side tables on every `FunctionBase`.
//    Its redundancy guard is `RedundancyGuard::Never()`.
//
// ### Example
//
// ```
// // Before
// fn compute_checksum(header: bits[16], payload: bits[16]) -> bits[16] {
//   xor_val: bits[16] = xor(header, payload, id=10, pos=[(0,1,5)])
//   ret inverted: bits[16] = not(xor_val, id=11, pos=[(0,2,5)])
// }
// ```
//
// After `RemoveIdentifiersPass`:
//
// ```
// // After
// fn function_0(param: bits[16], param__1: bits[16]) -> bits[16] {
//   xor.3: bits[16] = xor(param, param__1, id=3)
//   ret not.4: bits[16] = not(xor.3, id=4)
// }
// ```
class RemoveIdentifiersPass : public OptimizationPass {
 public:
  static constexpr std::string_view kName = "remove_identifiers_unsafe";
  explicit RemoveIdentifiersPass(
      StripOptions options = StripOptions{.new_package_name = "subrosa"})
      : OptimizationPass(kName, "UNSAFE: Remove all identifiers"),
        options_(options) {}
  ~RemoveIdentifiersPass() override = default;

  RedundancyGuard GetRedundancyGuard(
      const OptimizationPassOptions& options,
      OptimizationContext& context) const override {
    return RedundancyGuard::Never();
  }

 protected:
  absl::StatusOr<bool> RunInternal(Package* p,
                                   const OptimizationPassOptions& options,
                                   PassResults* results,
                                   OptimizationContext& context) const override;

 private:
  StripOptions options_;
};

}  // namespace xls

#endif  // XLS_DEV_TOOLS_DEV_PASSES_REMOVE_IDENTIFIERS_PASS_H_
