// Note: What follows was generated by the Gemini LLM. Not human verified.
//
// `AssertAndCoverRemovalPass` (`assert_and_cover_removal`) is a development
// pass that strips all `assert` and `cover` operations from a `FunctionBase`.
//
// During IR debugging, optimization investigation, or area/delay experiments,
// verification operations (`assert` and `cover`) can keep condition cones and
// token chains alive. Removing them allows developers to inspect or synthesize
// the pure datapath and control logic in isolation.
//
// ### How It Works
//
// The pass iterates over all nodes in the `FunctionBase`:
// * **`Assert` nodes (`Op::kAssert`)**: Because an `assert` takes an input
//   `token` as `operand(0)` and produces a `token`, the pass bypasses the
//   assertion in the token graph by replacing all uses of the `assert` node
//   with `n->operand(0)` and then removing the `assert` node.
// * **`Cover` nodes (`Op::kCover`)**: Because a `cover` returns an empty tuple
//   `()` and must have no users (`XLS_RET_CHECK(n->users().empty())`), the pass
//   removes the `cover` node directly.
//
// Any condition logic feeding only the removed `assert` or `cover` nodes
// becomes dead and can be cleaned up by a subsequent `DeadCodeEliminationPass`.
//
// ### Example
//
// ```
// // Before
// fn checked_add(tkn: token, x: bits[8], y: bits[8]) -> (token, bits[8]) {
//   sum: bits[8] = add(x, y)
//   no_ovf: bits[1] = uge(sum, x)
//   assert_tkn: token = assert(tkn, no_ovf, message="overflow", label="ovf")
//   cover_max: () = cover( eq(sum, literal(value=255)), label="max_sum")
//   ret result: (token, bits[8]) = tuple(assert_tkn, sum)
// }
// ```
//
// After `AssertAndCoverRemovalPass`:
//
// ```
// // After
// fn checked_add(tkn: token, x: bits[8], y: bits[8]) -> (token, bits[8]) {
//   sum: bits[8] = add(x, y)
//   no_ovf: bits[1] = uge(sum, x)
//   ret result: (token, bits[8]) = tuple(tkn, sum)
// }
// ```
class AssertAndCoverRemovalPass : public OptimizationFunctionBasePass {
 public:
  static constexpr std::string_view kName = "assert_and_cover_removal";
  AssertAndCoverRemovalPass()
      : OptimizationFunctionBasePass(kName, "Assert and cover removal") {}
  ~AssertAndCoverRemovalPass() override = default;

  RedundancyGuard GetRedundancyGuard(
      const OptimizationPassOptions& options,
      OptimizationContext& context) const override {
    return RedundancyGuard::CanSkip();
  }

 protected:
  absl::StatusOr<bool> RunOnFunctionBaseInternal(
      FunctionBase* f, const OptimizationPassOptions& options,
      PassResults* results, OptimizationContext& context) const override;
};
