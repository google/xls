namespace xls {

// Pass which replaces OneHotSelects with equivalent Selects without regard to
// profitability concerns. This pass is meant for investigation and analysis use
// only and should not be used for normal optimization pipelines.
//
// To avoid extreme proliferation of nodes, we only translate OneHotSelects with
// a selector bitwidth <= 16.
//
// Note: What follows was generated by the Gemini LLM. Not human verified.
//
// `RemoveOneHotSelectPass` (`remove_one_hot_sel`) is a debugging and analysis
// pass (not included in default optimization pipelines, but invokable
// explicitly via `opt_main`) that expands `one_hot_sel` operations into
// exhaustive `sel` operations over all $2^N$ possible selector values,
// regardless of profitability.
//
// Because `one_hot_sel` ORs together the selected cases whenever multiple
// selector bits are high (and produces zero when no selector bits are high),
// converting an $N$-bit `one_hot_sel` without assuming one-hotness requires
// enumerating all $2^N$ bit patterns of the selector.
//
// ### How It Works
//
// The pass visits nodes in topological order (`context.TopoSort(f)`) and
// processes each `OneHotSelect` node `ohs`:
//
// 1. **Width Guard (`kMaxBits = 16`)**:
//    If the selector bitwidth exceeds `kMaxBits` (`16`), the node is skipped to
//    prevent exponential blowup beyond $2^{16} = 65,536$ cases.
//
// 2. **Exhaustive `sel` Construction**:
//    For a selector of width $N \le 16$, the pass replaces `ohs` with a
//    `sel(selector, cases=new_cases)` having no `default_value` (since all
//    $2^N$ selector values are covered), where `new_cases` has $2^N$ entries:
//    * **Case `0` (`selector == 0`)**: Emits a `Literal` of
//      `ZeroOfType(ohs->cases()[0]->GetType())`.
//    * **Cases `1` through $2^N - 1$**: Treats the case index $i$ as an $N$-bit
//      mask (`UBits(i, N)`), collects every `ohs->cases()[idx]` for which bit
//      `idx` of $i$ is `1`, and combines the selected cases with an N-ary
//      bitwise `or` via `NaryOrIfNeeded` (which returns the single case node
//      directly when $i$ is a power of two, or creates an `or` node named
//      `<ohs>_cases_<idx0>_<idx1>...` when multiple bits are set).
//
// ### Example
//
// ```
// // Before
// fn f(s: bits[2], c0: bits[8], c1: bits[8]) -> bits[8] {
//   ret ohs: bits[8] = one_hot_sel(s, cases=[c0, c1])
// }
// ```
//
// After `RemoveOneHotSelectPass` and `DeadCodeEliminationPass`:
//
// ```
// // After
// fn f(s: bits[2], c0: bits[8], c1: bits[8]) -> bits[8] {
//   zero: bits[8] = literal(value=0)
//   ohs_cases_0_1: bits[8] = or(c0, c1)
//   ret res: bits[8] = sel(s, cases=[zero, c0, c1, ohs_cases_0_1])
// }
// ```
class RemoveOneHotSelectPass : public OptimizationFunctionBasePass {
 public:
  static constexpr std::string_view kName = "remove_one_hot_sel";
  static constexpr int64_t kMaxBits = 16;

  RemoveOneHotSelectPass()
      : OptimizationFunctionBasePass(kName, "One Hot Select Removal Pass") {}
  ~RemoveOneHotSelectPass() = default;

 protected:
  absl::StatusOr<bool> RunOnFunctionBaseInternal(
      FunctionBase* f, const OptimizationPassOptions& options,
      PassResults* pass_results, OptimizationContext& context) const override;
};

}  // namespace xls

#endif  // XLS_DEV_TOOLS_DEV_PASSES_REMOVE_ONE_HOT_SELECT_PASS_H_
