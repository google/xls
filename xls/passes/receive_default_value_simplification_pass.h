namespace xls {

// Optimization which removes useless selects between the data value of a
// conditional or non-blocking receive and the default value of the receive (all
// zeros).
//
// Note: What follows was generated by the Gemini LLM. Not human verified.
//
// The `ReceiveDefaultValueSimplificationPass` is a proc-level optimization pass
// (`OptimizationProcPass`) that identifies and eliminates redundant binary
// `select` and `priority_select` operations choosing between the data output of
// a conditional or non-blocking `receive` and an all-zeros value.
//
// In XLS, when a conditional `receive` has a false predicate, or when a
// non-blocking `receive` has no data available (its valid bit is `0`), its data
// output (`tuple_index(receive_node, index=1)`) is already defined to be all
// zeros. Frontends or earlier passes often emit an explicit `select` or
// `priority_select` that forces the value to zero under those same conditions.
//
// **How it Works**:
//
// Using `StatelessQueryEngine`, the pass walks the proc in topological order
// and inspects each two-way `Select` (`cases=[on_false, on_true]`, no default)
// and single-case `PrioritySelect` (`cases=[on_true], default=on_false`). It
// matches `MatchUselessSelectAfterReceive` when:
//
// 1.  `on_true` is `tuple_index(receive, index=1)` (the data payload of a
//     `Receive` node).
// 2.  `on_false` is known to be all zeros
//     (`KnownValue(on_false)->IsAllZeros()`).
// 3.  One of the following selector conditions holds:
//     *   **Conditional `receive`**: `receive` is predicated and its predicate
//         is `selector`.
//     *   **Non-blocking `receive`**: `receive` is non-blocking and `selector`
//         is the valid bit (`tuple_index(..., index=2)`) of a non-blocking
//         `receive`.
//
// When matched, the pass replaces the `select` or `priority_select` directly
// with `on_true` (`tuple_index(receive, index=1)`).
//
// Example (Conditional `receive` with redundant `select`):
//
// ```
// // Original IR snippet
// chan in(bits[32], kind=streaming, ops=receive_only, flow_control=ready_valid)
//
// proc p(pred: bits[1], s: bits[32], init={1, 42}) {
//   tkn: token = literal(value=token)
//   // Data is already 0 if pred is 0
//   receive.1: (token, bits[32]) = receive(tkn, predicate=pred, channel=in)
//   receive_data: bits[32] = tuple_index(receive.1, index=1)
//   zero: bits[32] = literal(value=0)
//   select.2: bits[32] = sel(pred, cases=[zero, receive_data])
//   next (pred, select.2)
// }
//
// // Optimized IR snippet
// chan in(bits[32], kind=streaming, ops=receive_only, flow_control=ready_valid)
//
// proc p(pred: bits[1], s: bits[32], init={1, 42}) {
//   tkn: token = literal(value=token)
//   receive.1: (token, bits[32]) = receive(tkn, predicate=pred, channel=in)
//   receive_data: bits[32] = tuple_index(receive.1, index=1)
//   next (pred, receive_data)
// }
// ```
class ReceiveDefaultValueSimplificationPass : public OptimizationProcPass {
 public:
  static constexpr std::string_view kName = "recv_default";

  ReceiveDefaultValueSimplificationPass()
      : OptimizationProcPass(kName, "Receive default value simplification") {}
  ~ReceiveDefaultValueSimplificationPass() override = default;

  RedundancyGuard GetRedundancyGuard(
      const OptimizationPassOptions& options,
      OptimizationContext& context) const override {
    return RedundancyGuard::CanSkip();
  }

 protected:
  absl::StatusOr<bool> RunOnProcInternal(
      Proc* proc, const OptimizationPassOptions& options, PassResults* results,
      OptimizationContext& context) const override;
};

}  // namespace xls

#endif  // XLS_PASSES_RECEIVE_DEFAULT_VALUE_SIMPLIFICATION_PASS_H_
