namespace xls {

// Pass which transforms Bits-type elements of the proc state into tuples of
// components. Only flattens where it can show that doing so will enable
// dynamic state feedback opportunities later (assuming it's followed by a
// ProcStateTupleFlatteningPass).
//
// Note: What follows was generated by the Gemini LLM. Not human verified.
//
// `ProcStateBitsShatteringPass` splits wide `bits`-typed `StateElement`s in a
// `Proc` into tuples of narrower `bits` components when doing so will expose
// independent conditional state updates for `ProcStateTupleFlatteningPass` and
// `NextValueOptimizationPass`.
//
// ### How It Works
//
// 1. **Analyzing `next_value` Nodes for Split Points**: For each `bits`-typed
//    `StateElement`, the pass inspects all of its `next_value` nodes:
//    * Pass-through updates (`IsNoOpNext`) are ignored because they trivially
//      preserve all sub-slices.
//    * If any non-no-op `next_value` has a `value` operand that is **not** a
//      `concat` node, the state element cannot be split.
//    * For each `concat` `next_value`, candidate split boundaries
//      (`concat_splits`, ordered from LSB to MSB) are computed from the bit
//      widths of the `concat`'s operands (iterated in reverse, since `concat`
//      orders operands MSB-to-LSB).
//    * Splitting is marked beneficial (`could_benefit_from_splitting = true`)
//      if at least one operand of a `concat` is a `priority_sel`, or is a `sel`
//      when `options.split_next_value_selects` (default
//      `kDefaultSplitNextValueSelects = 4`) is set and
//      `sel->cases().size() <= *options.split_next_value_selects`.
//
// 2. **Intersecting Split Points**: When multiple non-no-op `next_value` nodes
//    update the same state element, their candidate boundary sets are
//    intersected (`absl::c_set_intersection`). If
//    `could_benefit_from_splitting` is true and the intersection still defines
//    more than one component (`split_ends.size() > 1`), the state element is
//    shattered.
//
// 3. **State Element Transformation (`TuplifyFlatStateElement`)**: Using
//    `Proc::TransformStateElement`, the `bits[W]` state element is replaced by
//    a tuple `(bits[w_0], bits[w_1], ..., bits[w_{k-1}])` ordered from LSB
//    slice to MSB slice:
//    * **`initial_value`**: Sliced into a tuple of `Bits` values corresponding
//      to `[0, split_ends[0])`, `[split_ends[0], split_ends[1])`, etc.
//    * **Transforming `StateRead`s**: Uses of the old `StateRead` are replaced
//      with `concat(tuple_index(new_read, k-1), ..., tuple_index(new_read, 0))`
//      (reversing the LSB-to-MSB tuple elements to match MSB-to-LSB `concat`
//      order).
//    * **Transforming `Next` Values**: Each `next_value`'s `value` operand is
//      replaced with `tuple(bit_slice(old_val, 0, w_0), ...)`.
//
// ### Example
//
// ```
// // Before
// proc my_proc(x: bits[16], init={0}) {
//   x_read: bits[16] = state_read(state_element=x)
//   x_lo: bits[6] = bit_slice(x_read, start=0, width=6)
//   x_mid: bits[1] = bit_slice(x_read, start=6, width=1)
//   x_hi: bits[9] = bit_slice(x_read, start=7, width=9)
//   cond: bits[1] = or_reduce(x_lo)
//   new_mid: bits[1] = priority_sel(cond, cases=[not(x_mid)], default=x_mid)
//   next_x: bits[16] = concat(x_hi, new_mid, x_lo)
//   next_value(param=x, value=next_x)
// }
// ```
//
// After `ProcStateBitsShatteringPass`:
//
// ```
// // After
// proc my_proc(x: (bits[6], bits[1], bits[9]), init={(0, 0, 0)}) {
//   x_read: (bits[6], bits[1], bits[9]) = state_read(state_element=x)
//   t_lo: bits[6] = tuple_index(x_read, index=0)
//   t_mid: bits[1] = tuple_index(x_read, index=1)
//   t_hi: bits[9] = tuple_index(x_read, index=2)
//   x_reconstructed: bits[16] = concat(t_hi, t_mid, t_lo)
//   // ... next_x computed from x_reconstructed ...
//   s_lo: bits[6] = bit_slice(next_x, start=0, width=6)
//   s_mid: bits[1] = bit_slice(next_x, start=6, width=1)
//   s_hi: bits[9] = bit_slice(next_x, start=7, width=9)
//   next_tuple: (bits[6], bits[1], bits[9]) = tuple(s_lo, s_mid, s_hi)
//   next_value(param=x, value=next_tuple)
// }
// ```
//
// Followed by `ProcStateTupleFlatteningPass`, `BitSliceSimplificationPass`, and
// `NextValueOptimizationPass`, the three components become independent state
// elements where only the 1-bit middle element is conditionally updated.
class ProcStateBitsShatteringPass : public OptimizationProcPass {
 public:
  static constexpr std::string_view kName = "proc_state_bits_shatter";

  ProcStateBitsShatteringPass()
      : OptimizationProcPass(kName, "Proc State Bits Shattering") {}
  ~ProcStateBitsShatteringPass() override = default;

  RedundancyGuard GetRedundancyGuard(
      const OptimizationPassOptions& options,
      OptimizationContext& context) const override;

 protected:
  absl::StatusOr<bool> RunOnProcInternal(
      Proc* proc, const OptimizationPassOptions& options, PassResults* results,
      OptimizationContext& context) const override;
};

}  // namespace xls

#endif  // XLS_PASSES_PROC_STATE_BITS_SHATTERING_PASS_H_
