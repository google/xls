namespace xls {

// Pass which simplifies bitwise operations (AND, OR, XOR) with constant masks
// by transforming them into concats of BitSlices, Literals, and Nots. This
// optimization is only enabled when SplitsEnabled is true.
//
// Note: What follows was generated by the Gemini LLM. Not human verified.
//
// The `BitwiseSimplificationPass` simplifies `and`, `or`, and `xor` operations
// using per-bit ternary knowledge from a `UnionQueryEngine` (combining
// `StatelessQueryEngine` and `PartialInfoQueryEngine`).
//
// **How it Works**:
//
// 1.  **Full Constant Folding and Inversion (All Optimization Levels)**:
//     *   If the query engine determines that all bits of an `and`, `or`, or
//         `xor` node are statically known, the node is replaced with a
//         `literal`.
//     *   When `SplitsEnabled(opt_level)` is false (`opt_level < 3`), if an
//         `xor` has a single non-constant operand and its accumulated constant
//         mask is all ones, it is simplified to `not(x)`.
//
// 2.  **Bitwise Mask Decomposition (when `SplitsEnabled(opt_level)` is true, at
//     `opt_level >= 3`)**:
//     *   **Mask Accumulation**: Across all operands of an `and`, `or`, or
//         `xor` node, the pass accumulates a composite mask of known bits:
//         *   For `and` and `or`, known bits from both fully known and
//             partially known operands are intersected (`and`) or unioned
//             (`or`) into the composite mask (with unknown bits set to the
//             identity value: `1` for `and`, `0` for `or`).
//         *   For `xor`, fully known constant operands are XORed into the
//             composite mask.
//     *   **Contiguous Run Splitting**: If the composite mask is not the
//         identity (all ones for `and`, all zeros for `or`/`xor`), the bit
//         width is partitioned into maximal contiguous runs `[pos, end)` where
//         the mask bit is uniform:
//         *   **Absorbing Runs (`0` in `and`, `1` in `or`)**: Replaced with a
//             constant `0` or `all_ones` `literal` of width `end - pos`.
//         *   **Identity or Inverting Runs (`1` in `and`, `0` in `or`, or any
//             run in `xor`)**: Each non-constant operand whose bits in
//             `[pos, end)` are not already known to be the identity is sliced
//             to `bit_slice(op, pos, end - pos)`. If multiple sliced operands
//             remain, they are combined with a narrower `and`/`or`/`xor`; for
//             `xor` runs where the mask bit is `1`, the slice (or narrower
//             `xor`) is inverted with `not`.
//     *   **Reassembly**: The resulting per-run nodes are joined from MSB to
//         LSB using `concat`, exposing narrower slices and constants to
//         downstream passes such as `BitSliceSimplificationPass`.
//
// **Example**:
//
// ```
// // Original IR
// mask: bits[8] = literal(value=0xf0)
// ret res: bits[8] = and(x, mask)
//
// // Optimized IR (when SplitsEnabled is true)
// hi: bits[4] = bit_slice(x, start=4, width=4)
// lo_zero: bits[4] = literal(value=0)
// ret res: bits[8] = concat(hi, lo_zero)
// ```
class BitwiseSimplificationPass : public OptimizationFunctionBasePass {
 public:
  static constexpr std::string_view kName = "bitwise_simp";
  explicit BitwiseSimplificationPass()
      : OptimizationFunctionBasePass(kName, "bitwise simplification") {}
  ~BitwiseSimplificationPass() override = default;

  RedundancyGuard GetRedundancyGuard(
      const OptimizationPassOptions& options,
      OptimizationContext& context) const override;

 protected:
  absl::StatusOr<bool> RunOnFunctionBaseInternal(
      FunctionBase* f, const OptimizationPassOptions& options,
      PassResults* results, OptimizationContext& context) const override;
};

}  // namespace xls

#endif  // XLS_PASSES_BITWISE_SIMPLIFICATION_PASS_H_
