namespace xls {

// Pass that simplifies token networks. For example, if an AfterAll node has
// operands where one operand is an ancestor of another in the token graph, then
// the ancestor can be omitted. Similarly, duplicate operands can be removed and
// AfterAlls with one operand can be replaced with their operand.
//
// Note: What follows was generated by the Gemini LLM. Not human verified.
//
// The `TokenSimplificationPass` simplifies the token dependency network within
// a function or proc. Token networks enforce ordering constraints between
// side-effecting operations (such as `send`, `receive`, and `assert`). By
// removing redundant token edges and canonicalizing `min_delay` annotations,
// this pass reduces control complexity and simplifies downstream scheduling.
//
// If any node in the `FunctionBase` has a type containing more than one token
// (e.g., a tuple containing multiple tokens), the pass conservatively bails out
// without modifying the IR.
//
// Otherwise, the pass executes a sequence of subpasses on `after_all` and
// `min_delay` operations:
//
// 1.  **Simplifying `min_delay` Operations**:
//     *   **Trivial `min_delay`**: A `min_delay(tok, delay=0)` is replaced with
//         `tok`. Similarly, `min_delay(after_all(), delay=X)` on an empty
//         `after_all()` is replaced with `after_all()`.
//
//         ```
//         // Original IR
//         min_delay.1: token = min_delay(tok, delay=0)
//
//         // Optimized IR
//         // Uses of min_delay.1 are replaced directly with tok.
//         ```
//
//     *   **Collapsing Nested `min_delay`s**: Consecutive `min_delay`
//         operations are merged by summing their delays:
//         `min_delay(min_delay(tok, delay=1), delay=2)` becomes
//         `min_delay(tok, delay=3)`.
//
//         ```
//         // Original IR
//         min_delay.1: token = min_delay(tok, delay=1)
//         min_delay.2: token = min_delay(min_delay.1, delay=2)
//
//         // Optimized IR
//         min_delay.3: token = min_delay(tok, delay=3)
//         ```
//
//     *   **Pushing `min_delay` Down Through `after_all`**: If all operands of
//         a non-empty `after_all` are `min_delay` nodes with positive delays,
//         the minimum common delay `d_min` is factored out after the
//         `after_all`, leaving residual `min_delay(..., delay=d - d_min)` nodes
//         only for operands with `d > d_min`.
//
//         ```
//         // Original IR
//         min_delay.1: token = min_delay(tok_a, delay=1)
//         min_delay.2: token = min_delay(tok_b, delay=3)
//         after_all.3: token = after_all(min_delay.1, min_delay.2)
//
//         // Optimized IR
//         min_delay.4: token = min_delay(tok_b, delay=2)
//         after_all.5: token = after_all(tok_a, min_delay.4)
//         min_delay.6: token = min_delay(after_all.5, delay=1)
//         ```
//
// 2.  **Simplifying `after_all` Operations**:
//     *   **Collapsing Nested `after_all`s**: In reverse topological order, if
//         an `after_all` node has no implicit uses and all of its users are
//         also `after_all` nodes, its operands are flattened directly into each
//         user `after_all`.
//
//         ```
//         // Original IR
//         after_all.1: token = after_all(tok_a, tok_b)
//         after_all.2: token = after_all(after_all.1, tok_c)
//
//         // Optimized IR
//         after_all.3: token = after_all(tok_c, tok_a, tok_b)
//         ```
//
//     *   **Pruning Overlapping (Ancestor) `after_all` Operands**: If an
//         `after_all` has operands `x` and `y` where `x` transitively depends
//         on `y` through token-carrying nodes (conservatively stopping at
//         `invoke` nodes so the pass is safe before function inlining, and
//         bounding traversal by topological index), `y` is redundant and
//         replaced by another operand of the `after_all`.
//     *   **Deduplicating Operands**: Duplicate operands in an `after_all` are
//         removed (with remaining unique operands sorted by node ID).
//     *   **Single-Operand `after_all`**: An `after_all(tok)` with a single
//         operand is replaced directly with `tok`.
//
//         ```
//         // Original IR
//         send.2: token = send(tok, data, channel=ch)
//         send.3: token = send(send.2, data, channel=ch)
//         after_all.4: token = after_all(tok, send.2, send.3)
//
//         // Optimized IR
//         // tok and send.2 are ancestors of send.3; after pruning,
//         // deduplication, and single-operand removal, after_all.4 is
//         // replaced directly with send.3.
//         ```
//
// If any simplification modifies the IR, `CollapseMinDelay` is run one final
// time to merge any `min_delay` operations that became adjacent after
// `after_all` removal.
class TokenSimplificationPass : public OptimizationFunctionBasePass {
 public:
  static constexpr std::string_view kName = "token_simp";
  TokenSimplificationPass()
      : OptimizationFunctionBasePass(kName, "Simplify token networks") {}
  ~TokenSimplificationPass() override = default;

  RedundancyGuard GetRedundancyGuard(
      const OptimizationPassOptions& options,
      OptimizationContext& context) const override {
    return RedundancyGuard::CanSkip();
  }

 protected:
  absl::StatusOr<bool> RunOnFunctionBaseInternal(
      FunctionBase* f, const OptimizationPassOptions& options,
      PassResults* results, OptimizationContext& context) const override;
};

}  // namespace xls

#endif  // XLS_PASSES_TOKEN_SIMPLIFICATION_PASS_H_
