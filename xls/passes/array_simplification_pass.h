namespace xls {

// Pass which simplifies or eliminates some array-type operations such as
// ArrayIndex.
//
// Note: What follows was generated by the Gemini LLM. Not human verified.
//
// The `ArraySimplificationPass` simplifies and eliminates array-related
// operations (`array`, `array_index`, `array_update`, `array_slice`, and
// array-typed `sel`/`priority_sel`/`one_hot_sel`) to reduce multiplexer width
// and eliminate unnecessary array storage. It uses a `UnionQueryEngine`
// combining `StatelessQueryEngine` and `LazyTernaryQueryEngine`.
//
// The pass executes in three stages:
//
// 1.  **Clamping Known Out-of-Bounds `ArrayIndex` Indices**:
//     Scans all `array_index` nodes and clamps any index operand whose minimum
//     unsigned value (`MinUnsignedValue`) is greater than or equal to the
//     dimension size to a literal `size - 1`.
//
// 2.  **Flattening Sequential `ArrayUpdate` Chains**:
//     Walks the graph in reverse topological order to find chains of
//     `array_update` operations sharing a common index prefix. When the chain
//     updates at least half of the subarray's elements (or at least 2 elements
//     when `SplitsEnabled(opt_level)` is true, at `opt_level >= 3`), the chain
//     is collapsed into a single `array` construction where each element uses a
//     `priority_sel` over the update indices.
//
// 3.  **Worklist-Driven Iterative Simplifications**:
//     Seeds a worklist in reverse topological order and repeatedly applies
//     local rewrites until reaching a fixed point:
//
//     *   **`ArrayIndex` Simplifications**:
//         *   **Empty Indices**: `array_index(A, {})` is replaced with `A`.
//         *   **Unit-Size Dimensions**: Any non-literal index into a dimension
//             of size 1 is replaced with `0`.
//         *   **Indexing into `Array`**: If the first index into an `array`
//             node is constant, extracts the selected operand directly
//             (clamping if out of bounds). If the index is dynamic, replaces
//             the `array_index` with a `sel` over the reachable `array`
//             operands (using the last element as `default` for clamping):
//
//             ```
//             // Original IR
//             arr: bits[32][3] = array(a, b, c)
//             ret res: bits[32] = array_index(arr, indices=[idx])
//
//             // Optimized IR (for idx: bits[2])
//             ret res: bits[32] = sel(idx, cases=[a, b], default=c)
//             ```
//
//         *   **Indexing into `ArrayConcat`**: If the first index is a known
//             in-bounds constant, bypasses `array_concat` to index directly
//             into the corresponding concatenated array operand.
//         *   **Consecutive `ArrayIndex` Operations**: Flattens nested
//             `array_index(array_index(A, {i}), {j})` into
//             `array_index(A, {i, j})`.
//         *   **`ArrayIndex` of Select**: Pushes `array_index` into the cases
//             of `sel`, `one_hot_sel`, or `priority_sel` when the select has a
//             single user, or when `SplitsEnabled(opt_level)` is true and
//             either the array is small (`size <= 3`) or every live user of the
//             select is a constant-indexed `array_index`
//             (`ArrayOnlyConstIndexed`).
//         *   **`ArrayIndex` of `ArrayUpdate`**:
//             *   If the update indices match the read indices (or are a prefix
//                 of them) and the access is known in-bounds, bypasses the
//                 array to read directly from `update_value` (preserving
//                 `assumed_in_bounds` when provably in bounds).
//             *   If the update and read indices are provably unequal and the
//                 read is in-bounds, bypasses the `array_update` to read from
//                 the original array.
//             *   For small 1D arrays (`size <= 3`) when
//                 `SplitsEnabled(opt_level)` is true, unwinds
//                 `array_index(array_update(A, v, {u_idx}), {r_idx})` into a
//                 `priority_sel` comparing `u_idx` against the clamped `r_idx`.
//
//     *   **`ArrayUpdate` Simplifications**:
//         *   **Empty or Redundant Updates**: `array_update(A, v, {})` becomes
//             `v`, and `array_update(A, array_index(A, {idx}), {idx})` becomes
//             `A`.
//         *   **Unit-Size Dimensions**: Replaces updates to leading size-1
//             dimensions with a `priority_sel` checking whether the indices are
//             `0` (or directly with the wrapped value if assumed in-bounds).
//         *   **Hoisting `ArrayUpdate` into `Array`**: When updating a
//             single-use `array` node and either the first index is constant or
//             `SplitsEnabled(opt_level)` is true, pushes the update into the
//             compatible elements of the `array` (inserting `priority_sel`s
//             when the index is not fully known), or unpacks a constant array
//             updated at a constant in-bounds index.
//         *   **Nested and Overwritten Updates**: Merges
//             `array_update(A, array_update(array_index(A, {i}), v, {j}), {i})`
//             into `array_update(A, v, {i, j})` (preserving `assumed_in_bounds`
//             when both outer and inner updates are provably in bounds), and
//             removes earlier updates in a single-use chain whose index is
//             overwritten by a later prefix update.
//
//     *   **`Array` and `ArraySlice` Simplifications**:
//         *   **Decompose/Recompose Elimination**: Replaces an `array` built
//             from sequential `array_index(A, {prefix..., 0..N-1})` elements
//             with `A` (or `array_index(A, {prefix...})`).
//         *   **Static `ArraySlice`**: Replaces an `array_slice` with a known
//             constant `start` index with an `array` of static `array_index`
//             operations.
//
//     *   **Array-Typed Select Simplifications**:
//         *   **Conditional Update Hoisting**: Rewrites
//             `sel(p, cases=[A, array_update(A, v, {idx})])` into
//             `array_update(A, sel(p, cases=[array_index(A, {idx}), v]),
//             {idx})` so the mux operates on a single element rather than the
//             entire array.
//         *   **Select of `Array`s to `Array` of Selects**: When all branches
//             (up to 2) of a select are `array` nodes, pushes the select
//             element-wise into a single `array` of narrower selects.
class ArraySimplificationPass : public OptimizationFunctionBasePass {
 public:
  static constexpr std::string_view kName = "array_simp";
  explicit ArraySimplificationPass()
      : OptimizationFunctionBasePass(kName, "Array Simplification") {}

  bool IsIdempotent() const override { return true; }

  RedundancyGuard GetRedundancyGuard(
      const OptimizationPassOptions& options,
      OptimizationContext& context) const override;

 protected:
  absl::StatusOr<bool> RunOnFunctionBaseInternal(
      FunctionBase* f, const OptimizationPassOptions& options,
      PassResults* results, OptimizationContext& context) const override;
};

}  // namespace xls

#endif  // XLS_PASSES_ARRAY_SIMPLIFICATION_PASS_H_
