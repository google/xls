#include <string_view>

#include "xls/passes/optimization_pass.h"

namespace xls {

// Note: What follows was generated by the Gemini LLM. Not human verified.
//
// `NonSynthRemovalPass` is a compound optimization pass that strips all
// non-synthesizable verification and debugging operations (`assert`, `cover`,
// and `trace`) from a package, along with any supporting logic and functions
// that exist solely to feed those operations.
//
// ### How It Works
//
// Rather than simply deleting `assert`, `cover`, and `trace` nodes in place,
// this compound pass sequences four sub-passes to cleanly isolate and prune all
// non-synthesizable logic across functions and procs:
//
// 1. **`NonSynthSeparationPass`**: For every function or proc containing
//    `assert`, `cover`, or `trace` nodes, clones the non-synthesizable logic
//    into a separate function marked `#[non_synth]`, removes the `assert`,
//    `cover`, and `trace` nodes from the original function or proc (replacing
//    `assert` and `trace` with their input token operand and `cover` with an
//    empty tuple `()`), and inserts an `invoke` from the original function or
//    proc to the `#[non_synth]` function.
// 2. **`NonSynthInvokeRemovalPass`**: Scans every `FunctionBase` in the package
//    and removes any `invoke` node whose target function (`to_apply()`) is
//    marked `non_synth()`.
// 3. **`DeadCodeEliminationPass` (DCE)**: Removes intermediate nodes in the
//    original functions and procs (such as comparisons, formatting logic, or
//    duplicated `non_synth` proc state reads) that have become dead after
//    removing the `assert`/`cover`/`trace` nodes and the `#[non_synth]`
//    invokes.
// 4. **`DeadFunctionEliminationPass` (DFE)**: Removes the now-unreferenced
//    `#[non_synth]` functions from the package.
//
// ### Example
//
// ```
// // Before
// fn checked_double(x: bits[32]) -> bits[32] {
//   tok: token = literal(value=token)
//   limit: bits[32] = literal(value=100)
//   in_bounds: bits[1] = ult(x, limit)
//   assert.1: token = assert(tok, in_bounds, message="x out of bounds")
//   one: bits[32] = literal(value=1)
//   ret result: bits[32] = shll(x, one)
// }
// ```
//
// After `NonSynthRemovalPass` runs:
//
// ```
// // After
// fn checked_double(x: bits[32]) -> bits[32] {
//   one: bits[32] = literal(value=1)
//   ret result: bits[32] = shll(x, one)
// }
// ```
//
// Both the `assert` operation and its exclusive dependencies (`tok`, `limit`,
// and `in_bounds`) are completely eliminated.
class NonSynthRemovalPass : public OptimizationCompoundPass {
 public:
  static constexpr std::string_view kName = "non_synth_removal";

  explicit NonSynthRemovalPass();
  ~NonSynthRemovalPass() override = default;
};

}  // namespace xls

