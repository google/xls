// A pass which reduces the width of operations eliminating redundant or unused
// bits.
//
// Note: What follows was generated by the Gemini LLM. Not human verified.
//
// The `NarrowingPass` reduces the bit width of operations and replaces
// statically determined values with constants across a `FunctionBase`. Reducing
// bit widths directly shrinks synthesized hardware area and critical-path delay
// (fewer wires, smaller adders, multipliers, comparators, and multiplexers).
//
// **Analysis Modes (`AnalysisType`) and Query Engines**:
//
// The pass is parameterized by `AnalysisType`, which selects the query engine
// stack (wrapped in an `AliasingQueryEngine` so newly created replacement nodes
// can alias replaced nodes during a single topological walk):
//
// *   **`kTernary` (`"narrow(Ternary)"`)**: Combines `StatelessQueryEngine`,
//     shared `BitCountQueryEngine`, and `CachedStateElementQueryEngine`
//     wrapping `LazyTernaryQueryEngine`. Tracks per-bit known `0`, `1`, or `X`.
// *   **`kRange` (`"narrow(Range)"`, default for `"narrow"`)**: Combines
//     `StatelessQueryEngine`, shared `BitCountQueryEngine`,
//     `ProcStateRangeQueryEngine` (when the target is a `Proc` whose state
//     evolution can be analyzed), and `CachedStateElementQueryEngine` wrapping
//     `PartialInfoQueryEngine` for interval/range and ternary tracking.
// *   **`kRangeWithContext` (`"narrow(Context)"`)**: Extends `kRange` with
//     `ContextSensitiveRangeQueryEngine` and `PredicateDominatorAnalysis`.
//     Uses `SpecializedQueryEngines` to specialize range and ternary queries
//     under the nearest dominating `select` arm predicate (`PredicateState`) of
//     a node or a `(node, user)` edge.
// *   **`kRangeWithOptionalContext` (`"narrow(OptionalContext)"`)**: Resolves
//     to `kRangeWithContext` when `options.use_context_narrowing_analysis` is
//     true, and `kRange` otherwise.
//
// **How it Works**:
//
// The pass walks nodes in topological order (`context.TopoSort(f)`), skipping
// dead nodes and side-effecting ops other than `gate`, and applies:
//
// 1.  **Constant Folding (`MaybeReplacePreciseWithLiteral`)**:
//     *   **Global Constant Replacement**: Before visiting a node's op-specific
//         handler, if the query engine proves all leaf bits of a non-literal,
//         non-param, token-free node are known (including `gate` nodes), all
//         uses of the node are replaced with a `Literal`.
//     *   **Select Arm Replacement (`HandleSel`)**: In `kRangeWithContext`
//         mode, each case arm (and default arm) of a `Select` is queried under
//         its own `PredicateState`; if the arm's value is constant in that
//         branch, that operand of the `Select` is replaced with a `Literal`.
//     *   **Context-Sensitive Input Edge Replacement**: After visiting a node
//         in `kRangeWithContext` mode, any operand whose value is constant
//         under the node's dominating predicate is replaced on that input edge
//         with a `Literal`.
//
// 2.  **Narrowing Comparisons (`MaybeNarrowCompare`)**:
//     *   **Matched Leading and Trailing Bits**: For `eq`, `ne`, `ult`, `ule`,
//         `ugt`, `uge`, `slt`, `sle`, `sgt`, and `sge` on `bits` operands,
//         consecutive leading and trailing bit positions where the two operands
//         are provably equal (`query_engine.KnownEquals`) are sliced off. If
//         at least one leading bit (including the MSB) matches on a signed
//         ordered comparison, the narrowed comparison is converted to its
//         unsigned counterpart (`slt -> ult`, etc.).
//
//         ```
//         // Leading `0110` and trailing `0011` match on both operands:
//         // Original: ugt(0b0110_XXXX_0011, 0b0110_YYYY_0011)
//         // Narrowed: ugt(bit_slice(lhs, 4, 4), bit_slice(rhs, 4, 4))
//         ```
//
//     *   **Redundant Sign-Extension Bits**: If both operands have repeated
//         MSBs (via `KnownEquals` with the MSB or explicit `sign_ext` /
//         `zero_ext` nodes), the redundant upper sign bits are sliced off while
//         preserving one sign bit.
//
// 3.  **Narrowing `neg` (`HandleNeg`)**:
//     *   **Trailing Zeros**: If the input has `Z > 0` known trailing zeros,
//         slices the upper `W - Z` bits, negates that narrower slice, and
//         concatenates `Z` zero bits on the LSB.
//     *   **`neg(sign_ext(x))`**: If range analysis shows `x` (width `n`)
//         cannot equal `MinSigned(n)`, rewrites to `sign_ext(neg(x), W)`.
//         Otherwise, in `kRangeWithContext` mode when `W > n + 1`, rewrites to
//         `sign_ext(neg(sign_ext(x, n + 1)), W)`.
//     *   **Leading Zeros**: If the input has `L >= 2` known leading zeros,
//         slices the low `W - L + 1` bits, negates (or directly sign-extends if
//         only 1 unknown LSB remains), and `sign_ext`s to `W`.
//
// 4.  **Narrowing Shifts and Dynamic Bit Slices**:
//     *   **Left Shift (`HandleShll`)**: Replaces with `shift_value` if
//         `shift_amnt` is zero. Strips known leading zeros from `shift_amnt`.
//         If `shift_value` has `Z > 0` trailing zeros, shifts the upper
//         `W - Z` bits and appends `Z` zero bits. If `shift_value` has leading
//         sign bits and `max(shift_amnt) + unknown_bits < W`, slices
//         `shift_value` to `max(shift_amnt) + unknown_bits`, shifts, and
//         restores the upper bits via `concat` (when MSB is known) or
//         `sign_ext`.
//     *   **Right Shifts (`HandleShrl`, `HandleShra`)**: Replaces with
//         `shift_value` if `shift_amnt` is zero or all bits of `shift_value`
//         equal the fill bit. If `min(shift_amnt)` shifts out all non-fill
//         bits, replaces with `0` (`shrl`) or `sign_ext(msb)` (`shra`).
//         Otherwise, strips leading zeros from `shift_amnt` and strips known
//         leading zeros (`shrl`) or redundant sign bits (`shra`) from
//         `shift_value`, followed by `zero_ext` or `sign_ext`.
//     *   **`dynamic_bit_slice` (`HandleDynamicBitSlice`)**: Converts a known
//         constant `start` into a static `bit_slice` (plus `zero_ext` or `0` if
//         out of bounds). Otherwise, strips leading zeros from `start`, trims
//         `to_slice` bits that are known zero or beyond `max(start) + width`,
//         and zero-extends if the narrowed slice is smaller than `width`.
//
// 5.  **Narrowing `decode` (`HandleDecode`)**:
//     Replaces `decode(0)` with literal `1`. If the index has leading zeros,
//     slices them off, shrinks the `decode` output width to
//     `min(result_width, 1 << narrowed_index_width)`, and `zero_ext`s if
//     needed.
//
// 6.  **Narrowing `add` and `sub` (`HandleAdd`, `HandleSub`)**:
//     *   For `sub`, if the result itself has known leading zeros (or `> 1`
//         leading ones), slices both operands to strip the known upper bits and
//         `zero_ext`s (or `sign_ext`s) the narrower `sub`. Otherwise, if both
//         operands share leading sign bits, narrows them keeping one sign bit
//         plus an overflow bit (omitted when both operands have the same known
//         MSB) and `sign_ext`s.
//     *   For `add`, if both operands share `Z > 1` known leading zeros,
//         narrows both operands to `W - Z + 1` bits and `zero_ext`s the sum.
//         If both operands share `S > 1` leading sign bits, narrows them to
//         `W - S + 1 + overflow_bit` bits (where `overflow_bit = 0` when
//         operands have known opposite MSBs, else `1`) and `sign_ext`s.
//
// 7.  **Narrowing Multiplies (`HandleUMul`, `HandleSMul`, `HandleUMulp`,
//     `HandleSMulp`)**:
//     *   Narrows the result width to `lhs_width + rhs_width` (and extends)
//         when the multiply width exceeds the sum of operand widths (for
//         `umulp`/`smulp`, when the two partial-product tuple elements are
//         immediately summed by a single `add`).
//     *   Truncates operands that are wider than the multiply result width.
//     *   Strips known leading zeros (unsigned) or redundant leading sign bits
//         (signed) from operands; for sign-agnostic multiplies
//         (`result_width == lhs_width == rhs_width`), chooses whichever of
//         unsigned or signed narrowing yields the smaller product of operand
//         widths.
//     *   For `umul`/`smul`, strips known trailing zeros from both operands,
//         performs a narrower multiply, and concatenates the combined trailing
//         zeros onto the LSB.
//
// 8.  **Narrowing Array Literals and Array Ops (`HandleLiteral`,
//     `HandleArrayIndex`, `HandleArrayUpdate`, `HandleArraySlice`)**:
//     *   **Constant Bit Extraction from Array Literals**: For an array literal
//         of `bits[W]` elements accessed by `array_index`, computes the common
//         ternary bit pattern across all elements. If all elements are
//         identical, replaces each `array_index` with a constant `Literal`.
//         Otherwise, when `options.splits_enabled()` is true and some bits are
//         constant across all elements, creates a narrower array literal
//         holding only the variable bits and reconstructs each `array_index`
//         via bit-slicing and concatenation (`FillPattern`).
//     *   **`array_index` to `select` Chain**: In `kRange` mode, when
//         `options.convert_array_index_to_select` is set to a threshold `T` and
//         the product of possible index interval sizes is in `(1, T]`, rewrites
//         the `array_index` into a chain of `select`s over literal-indexed
//         `array_index` operations.
//     *   **Bounds Proven & Index Narrowing**: Marks `array_index` and
//         `array_update` nodes as `assumed_in_bounds` when range analysis
//         proves all indices are strictly in bounds, clamps known out-of-bounds
//         constant indices to `array_size`, and strips known leading zeros from
//         index operands (including `array_slice` `start`).
class NarrowingPass : public OptimizationFunctionBasePass {
 public:
  enum class AnalysisType : uint8_t {
    kTernary,
    kRange,
    // Use the select context of instructions when calculating ranges.
    kRangeWithContext,
    // Use the select context controlled by the optimization options.
    kRangeWithOptionalContext,
  };
  template <typename Sink>
  void AbslStringify(Sink& sink, AnalysisType e) {
    switch (e) {
      case AnalysisType::kTernary:
        sink.Append("Ternary");
        break;
      case AnalysisType::kRange:
        sink.Append("Range");
        break;
      case AnalysisType::kRangeWithContext:
        sink.Append("Context");
        break;
      case AnalysisType::kRangeWithOptionalContext:
        sink.Append("OptionalContext");
        break;
    }
  }

  static constexpr std::string_view kName = "narrow";
  explicit NarrowingPass(AnalysisType analysis = AnalysisType::kRange)
      : OptimizationFunctionBasePass(ConfiguredName(analysis), "Narrowing"),
        analysis_(analysis) {}
  ~NarrowingPass() override = default;

  RedundancyGuard GetRedundancyGuard(
      const OptimizationPassOptions& options,
      OptimizationContext& context) const override;

 protected:
  AnalysisType analysis_;

  AnalysisType RealAnalysis(const OptimizationPassOptions& options) const;
  absl::StatusOr<bool> RunOnFunctionBaseInternal(
      FunctionBase* f, const OptimizationPassOptions& options,
      PassResults* results, OptimizationContext& context) const override;

 private:
  static std::string_view ConfiguredName(AnalysisType analysis) {
    switch (analysis) {
      case AnalysisType::kTernary:
        return "narrow(Ternary)";
      case AnalysisType::kRange:
        return "narrow(Range)";
      case AnalysisType::kRangeWithContext:
        return "narrow(Context)";
      case AnalysisType::kRangeWithOptionalContext:
        return "narrow(OptionalContext)";
    }
  }
};

std::ostream& operator<<(std::ostream& os, NarrowingPass::AnalysisType a);

