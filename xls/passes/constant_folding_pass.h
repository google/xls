#ifndef XLS_PASSES_CONSTANT_FOLDING_PASS_H_
#define XLS_PASSES_CONSTANT_FOLDING_PASS_H_

#include <string_view>

#include "absl/status/statusor.h"
#include "xls/ir/function_base.h"
#include "xls/passes/optimization_pass.h"
#include "xls/passes/pass_base.h"

namespace xls {

// Pass which performs constant folding. Every op with only literal operands is
// replaced by an equivalent literal.
//
// Note: What follows was generated by the Gemini LLM. Not human verified.
//
// The `ConstantFoldingPass` evaluates operations whose operands are all known
// compile-time constants and replaces their uses with a new `literal` node
// containing the computed result.
//
// **How it Works**:
//
// The pass traverses the nodes of a `FunctionBase` in topological order
// (`context.TopoSort(f)`) using a `StatelessQueryEngine`. Because nodes are
// visited in topological order, replacing an operation with a `literal`
// immediately exposes that constant to downstream users during the same pass,
// folding entire constant subgraphs in a single traversal.
//
// A node is eligible for constant folding (`NodeIsConstantFoldable`) if all of
// the following hold:
//
// 1.  **Has Users or Implicit Use**: The node has at least one user or is
//     implicitly used by the `FunctionBase` (such as a function return value).
// 2.  **Not Already a Literal**: The node is not already a `literal`.
// 3.  **No Token Types**: The node's type does not contain a `token`
//     (`!TypeHasToken(node->GetType())`).
// 4.  **Not Side-Effecting (Except `gate`)**: Side-effecting operations cannot
//     be folded, with the exception of `gate`, which can be folded when its
//     condition and data operands are constant.
// 5.  **All Operands Are Known Constants**: Every operand is fully known
//     according to `StatelessQueryEngine::IsFullyKnown`.
//
// For each eligible node, the pass extracts the constant `Value` of each
// operand, evaluates the node via `InterpretNode`, and replaces its uses with
// a newly created `literal` node (`ReplaceUsesWithNew<Literal>`). The pass
// does not delete the replaced nodes itself; they are cleaned up by subsequent
// `DeadCodeEliminationPass` runs.
//
// Example:
//
// ```
// fn IdenticalLiterals() -> bits[8] {
//   literal.1: bits[8] = literal(value=42)
//   literal.2: bits[8] = literal(value=123)
//   ret add.3: bits[8] = add(literal.1, literal.2)
// }
// ```
//
// After `ConstantFoldingPass` (and subsequent dead code elimination):
//
// ```
// fn IdenticalLiterals() -> bits[8] {
//   ret literal.4: bits[8] = literal(value=165)
// }
// ```
class ConstantFoldingPass : public OptimizationFunctionBasePass {
 public:
  static constexpr std::string_view kName = "const_fold";
  ConstantFoldingPass()
      : OptimizationFunctionBasePass(kName, "Constant folding") {}

  RedundancyGuard GetRedundancyGuard(
      const OptimizationPassOptions& options,
      OptimizationContext& context) const override {
    return RedundancyGuard::CanSkip();
  }

 protected:
  absl::StatusOr<bool> RunOnFunctionBaseInternal(
      FunctionBase* f, const OptimizationPassOptions& options,
      PassResults* results, OptimizationContext& context) const override;
};

}  // namespace xls

#endif  // XLS_PASSES_CONSTANT_FOLDING_PASS_H_
