namespace xls {

// Pass which tries to minimize the size and total number of elements of the
// proc state. This pass works by examining the provenance of the bits making
// up the next value to determine which (if any) bits are never actually
// modified.
//
// NB This is a separate pass from ProcStateNarrowing for simplicity of
// implementation. That pass mostly assumes we'll have a range-analysis which
// this does not need.
//
// Note: What follows was generated by the Gemini LLM. Not human verified.
//
// `ProcStateProvenanceNarrowingPass` reduces the bit width of `bits`-typed
// `StateElement`s in a `Proc` by identifying individual bit positions
// (leading, internal, or trailing) that never change from their `initial_value`
// across any `next_value` update. Unlike `ProcStateNarrowingPass`, which uses
// inter-cycle range analysis to strip leading bits, this pass uses single-cycle
// bit provenance and ternary analysis to excise unchanging bit segments at any
// offset within the bit vector.
//
// ### How It Works
//
// 1. **Identifying Unchanged Bits (`UnchangedBits`)**: For each `bits`-typed
//    `StateElement` with initial value `initial_bits`, the pass starts with an
//    all-ones mask `unchanged_bits` and intersects it across every non-no-op
//    `Next` node (`!IsNoOpNext(next)`):
//    * **Ternary Match (`LazyTernaryQueryEngine`)**: Computes
//      `ternary_known_unchanged`, marking bits in `next->value()` that are
//      known constants equal to the corresponding bits in `initial_bits`.
//    * **Provenance Match (`BitProvenanceAnalysis`)**: Queries
//      `provenance.GetBitSources(next->value())` (`TreeBitSources`) and marks
//      any bit range whose source is a `StateRead` of the *same*
//      `state_element` at the exact same bit positions
//      (`source_bit_index_low == dest_bit_index_low` and
//      `source_bit_index_high == dest_bit_index_high`).
//    * A bit remains set in `unchanged_bits` if, for every `Next` node, it is
//      preserved via either provenance or ternary equivalence.
//
// 2. **Extracting Bit Segments (`ExtractBitSegments`)**: If `unchanged_bits`
//    is non-zero, the state element's bit range is partitioned into contiguous
//    `BitSegment`s ordered from MSB to LSB. Each segment is either a constant
//    segment (holding the corresponding slice of `initial_bits`) or a variable
//    segment (`value == std::nullopt`).
//
// 3. **State Element Transformation (`NarrowTransform`)**: Using
//    `Proc::TransformStateElement`, the state element is narrowed to the
//    concatenation of its variable segments (`NarrowValue`):
//    * **Transforming `StateRead`s**: Reconstructs the original width by
//      concatenating (from MSB to LSB) `Literal` nodes for constant segments
//      and `BitSlice` nodes (or `new_state_read` directly if there is only a
//      single variable segment) for variable segments.
//    * **Transforming `Next` Values**: Slices only the variable segments from
//      `old_next->value()` (`BitSlice`) and concatenates them to form the
//      narrowed `next_value`.
//
// ### Example
//
// Consider a 96-bit state element `foo` whose middle 32 bits (`[32:64]`) are
// initialized to `0xFFFF_0000` and are always either copied from `foo` or
// overwritten with `0xFFFF_0000`:
//
// ```
// // Before
// proc my_proc(foo: bits[96], init={0x0000_0000_ffff_0000_0000_0000}) {
//   foo_read: bits[96] = state_read(state_element=foo)
//   lo: bits[32] = add(bit_slice(foo_read, start=0, width=32),
//                      literal(value=1, bits=32))
//   mid: bits[32] = bit_slice(foo_read, start=32, width=32)
//   hi: bits[32] = add(bit_slice(foo_read, start=64, width=32),
//                      literal(value=2, bits=32))
//   next_foo: bits[96] = concat(hi, mid, lo)
//   next_value(param=foo, value=next_foo)
// }
// ```
//
// `ProcStateProvenanceNarrowingPass` removes the unchanging middle 32 bits,
// narrowing `foo` from 96 bits to 64 bits:
//
// ```
// // After
// proc my_proc(foo: bits[64], init={0x0000_0000_0000_0000}) {
//   foo_read: bits[64] = state_read(state_element=foo)
//   var_hi: bits[32] = bit_slice(foo_read, start=32, width=32)
//   const_mid: bits[32] = literal(value=0xffff_0000)
//   var_lo: bits[32] = bit_slice(foo_read, start=0, width=32)
//   foo_reconstructed: bits[96] = concat(var_hi, const_mid, var_lo)
//   // ... next_foo computed from foo_reconstructed ...
//   next_hi: bits[32] = bit_slice(next_foo, start=64, width=32)
//   next_lo: bits[32] = bit_slice(next_foo, start=0, width=32)
//   next_foo_slice_reduced: bits[64] = concat(next_hi, next_lo)
//   next_value(param=foo, value=next_foo_slice_reduced)
// }
// ```
class ProcStateProvenanceNarrowingPass : public OptimizationProcPass {
 public:
  static constexpr std::string_view kName = "proc_state_provenance_narrow";
  ProcStateProvenanceNarrowingPass()
      : OptimizationProcPass(kName, "Proc State Provenance Narrowing") {}
  ~ProcStateProvenanceNarrowingPass() override = default;

  RedundancyGuard GetRedundancyGuard(
      const OptimizationPassOptions& options,
      OptimizationContext& context) const override {
    return RedundancyGuard::CanSkip();
  }

 protected:
  absl::StatusOr<bool> RunOnProcInternal(
      Proc* proc, const OptimizationPassOptions& options, PassResults* results,
      OptimizationContext& context) const override;
};

}  // namespace xls

#endif  // XLS_PASSES_PROC_STATE_PROVENANCE_NARROWING_PASS_H_
