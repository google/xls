namespace xls {

// Pass which replace the pattern
//   v = sel (c, array[i], array[j], ...)
// where all cases of the select reference the same array, to the code
//   z = sel (c, i, j, ...)
//   v = array[z]
//
// Note: What follows was generated by the Gemini LLM. Not human verified.
//
// The `SelectLiftingPass` restructures `select`, `priority_select`, and
// `one_hot_select` operations (wrapped via `GenericSelect`) to improve hardware
// efficiency. It identifies scenarios where all cases of a select are derived
// from a common operation (either a 1D `array_index` on the same array or a
// binary operation sharing a common operand) and lifts that shared operation
// out of the select. This moves the multiplexing from the output of the shared
// operation to its input, reducing duplicated hardware and narrowing the
// multiplexer when inputs are narrower than outputs.
//
// This pass handles two main scenarios:
//
// 1.  **Lifting `ArrayIndex` Operations**:
//     When all cases (and the default value, if present) of a select are 1D
//     `array_index` operations referencing the same `array` with identical
//     index bit-widths, the pass lifts the `array_index` out of the select. It
//     creates a new select that chooses among the index operands, feeding a
//     single shared `array_index`.
//
//     ```
//     // Original IR snippet
//     elem0: bits[32] = array_index(arr, indices=[i])
//     elem1: bits[32] = array_index(arr, indices=[j])
//     v: bits[32] = sel(c, cases=[elem0, elem1])
//
//     // Optimized IR (after lifting and dead code elimination)
//     idx: bits[4] = sel(c, cases=[i, j])
//     v: bits[32] = array_index(arr, indices=[idx])
//     ```
//
// 2.  **Lifting Binary Operations**:
//     When all cases of a select are binary operations of the same opcode
//     (`add`, `sub`, `and`, `or`, `xor`, `umul`, `smul`, `shll`, `shrl`,
//     `shra`, `eq`, `ne`, `ule`, `uge`, `ult`, `ugt`) that share a common
//     operand (`shared_node`) in a compatible operand position (identical
//     position, or either position for commutative ops), the binary operation
//     can be lifted out of the select. A new select chooses between the
//     non-shared operands, feeding a single shared binary operation. Cases
//     that are directly equal to `shared_node` are also supported as "identity
//     cases" when the opcode has a right-identity literal
//     (`GetIdentityLiteral`: `0` for `add`/`sub`/`or`/`xor`/shifts, all-ones
//     for `and`, and `1` for `umul`/`smul`).
//
//     ```
//     // Original IR snippet
//     sum0: bits[32] = add(x, a)
//     sum1: bits[32] = add(x, b)
//     v: bits[32] = sel(c, cases=[sum0, sum1])
//
//     // Optimized IR (after lifting and dead code elimination)
//     rhs: bits[32] = sel(c, cases=[a, b])
//     v: bits[32] = add(x, rhs)
//     ```
//
// **Query Engines and `OneHotSelect` Soundness**:
//
// At `opt_level < 3`, the pass uses a `UnionQueryEngine` combining
// `StatelessQueryEngine` and `LazyTernaryQueryEngine`; at `opt_level >= 3`, it
// uses `StatelessQueryEngine`, `PartialInfoQueryEngine`, and `BddQueryEngine`.
// Because `one_hot_select` outputs zero when no selector bits are set and
// bitwise-ORs active cases when multiple selector bits are set, lifting out of
// a `OneHotSelect` requires additional soundness checks:
//
// *   **`ArrayIndex` on `OneHotSelect`**: Requires either
//     `ExactlyOneBitTrue(selector)`, or `AtMostOneBitTrue(selector)` together
//     with proving that element `0` of the shared array is all zeros
//     (`IsFirstElementZero`).
// *   **Binary Operation on `OneHotSelect`**: Requires that either the
//     operation preserves zero (`OpPreservesZero`: `and`, `umul`, `smul`,
//     shifts where the select is the shifted LHS, or comparisons that evaluate
//     to `0` when the select outputs `0`—such as `eq`/`ule`/`uge` against a
//     known non-zero `shared_node`, `ne` against zero, `ult` as the RHS or
//     against zero, or `ugt` as the LHS or against zero) or
//     `AtLeastOneBitTrue(selector)` holds, AND that either the operation
//     distributes over bitwise OR (`OpDistributesOverOr`: `and` or `or`) or
//     `AtMostOneBitTrue(selector)` holds.
//
// **Applicability and Profitability Guards**:
//
// *   **`CanLiftSelect`**: Checks structural and semantic validity for
//     `ArrayIndex` or binary operation lifting, including verifying that all
//     index or non-shared operands have identical bit-widths across cases.
// *   **`ShouldLiftSelect`**: Evaluates profitability heuristics:
//     *   **Critical-Path Latency (`CheckLatencyIncrease`)**: For both
//         `ArrayIndex` and binary operation lifting, when
//         `options.delay_estimator` is provided, `CriticalPathDelayAnalysis`
//         rejects transformations that increase critical-path latency.
//     *   **For `ArrayIndex`**: Requires all case `array_index` nodes to be
//         single-use, at least one index to be a non-literal, and the index
//         bit-width to be less than or equal to the array element bit-width.
//     *   **For Binary Operations**: Rejects lifting if `selector` depends on
//         `shared_node` (`IsAncestorOf`), which would sequentialize the shared
//         operand and the lifted operation. When `options.delay_estimator` is
//         unavailable, fallback heuristics reject lifting `umul`/`smul` with
//         identity cases and reject turning constant shifts into variable
//         shifts. Finally, a bit-width cost check verifies that the total
//         bit-width of the lifted select and shared operation does not exceed
//         the bit-width of the original select and single-use case operations
//         (accounting for input operand width on comparison operations).
//
// **Worklist Execution**:
//
// The pass collects all `Select`, `PrioritySelect`, and `OneHotSelect` nodes
// into a worklist and iteratively applies `CanLiftSelect`, `ShouldLiftSelect`,
// and `LiftSelect` (`LiftSelectForArrayIndex` or
// `LiftSelectForBinaryOperation`). Select users of the newly lifted operation
// are queued for subsequent passes over the worklist when `opt_level > 1`.
class SelectLiftingPass : public OptimizationFunctionBasePass {
 public:
  static constexpr std::string_view kName = "select_lifting";

  explicit SelectLiftingPass()
      : OptimizationFunctionBasePass(kName, "Select Lifting") {}

  ~SelectLiftingPass() override = default;

  bool IsIdempotent() const override { return true; }

  RedundancyGuard GetRedundancyGuard(
      const OptimizationPassOptions& options,
      OptimizationContext& context) const override;

 protected:
  absl::StatusOr<bool> RunOnFunctionBaseInternal(
      FunctionBase* f, const OptimizationPassOptions& options,
      PassResults* results, OptimizationContext& context) const override;
};

}  // namespace xls

#endif  // XLS_PASSES_SELECT_LIFTING_PASS_H_
