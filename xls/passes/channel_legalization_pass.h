namespace xls {

// Pass that legalizes multiple send/receive operations per channel.
//
// This pass adds cross-activation tokens to guarantee that later activations of
// a proc cannot send or receive on a channel until all previous activations
// have completed working with that channel.
//
// Note: What follows was generated by the Gemini LLM. Not human verified.
//
// The `ChannelLegalizationPass` legalizes streaming channels (`kStreaming`)
// that are accessed by multiple `send` or multiple `receive` operations within
// a `Proc`. All multiple sends (or multiple receives) on a channel must reside
// in the same `Proc`, map uniquely to that channel, and (for receives) be
// blocking.
//
// For each streaming channel with multiple sends or receives, the pass performs
// two steps:
//
// 1.  **Strictness Verification and Mutual Exclusion
//     (`CheckMutualExclusion`)**:
//     The pass builds a projected token dependency DAG (`GetProjectedDAG`) over
//     the channel's operations and enforces the channel's `ChannelStrictness`:
//     *   **`kTotalOrder`**: Verifies (`CheckProjectedDAG`) that the existing
//         token DAG already forms a strict linear chain where the first
//         operation depends only on token `param`(s) and each subsequent
//         operation depends on the previous one.
//     *   **`kRuntimeOrdered`**: Respects existing token dependencies; for any
//         pair of operations not ordered by a token dependency chain, inserts
//         a runtime `assert` checking that their predicates are not
//         simultaneously true (or fails at compile time if both are
//         unconditional).
//     *   **`kProvenMutuallyExclusive`**: Ignores token dependencies and uses a
//         Z3 SMT solver (`solvers::SolverKind::kZ3`) with proc state
//         assumptions (`GetProcStateAssumptions`) to formally prove at compile
//         time that at most one operation on the channel can be active per
//         activation.
//     *   **`kRuntimeMutuallyExclusive`**: Ignores token dependencies and
//         inserts a runtime `assert` checking that no other operation on the
//         channel is active in the same activation.
//     *   **`kArbitraryStaticOrder`**: Imposes a total topological order in the
//         projected DAG so all operations are treated as ordered.
//
// 2.  **Cross-Activation Token Insertion**:
//     To ensure that an activation cannot issue a `send` or `receive` on the
//     channel before all operations on that channel from previous activations
//     have completed:
//     *   For each operation in the group, a `token`-typed state element
//         (`implicit_token__<op_name>`) is appended to the `Proc`.
//     *   A `next_value` node updates that state element with the operation's
//         output token (`tuple_index(recv, index=0)` for `receive`, or `send`
//         itself for `send`), gated by the operation's `predicate`.
//     *   Each operation's input token is replaced with an `after_all`
//         combining its original input token with the `state_read`s of all
//         newly added implicit token state elements for that channel.
//
// Example:
//
// ```
// chan in(bits[32], id=0, kind=streaming, ops=receive_only,
//         flow_control=ready_valid, strictness=proven_mutually_exclusive)
//
// top proc my_proc() {
//   tok: token = literal(value=token)
//   recv0: (token, bits[32]) = receive(tok, predicate=p0, channel=in)
//   recv1: (token, bits[32]) = receive(tok, predicate=p1, channel=in)
// }
// ```
//
// After `ChannelLegalizationPass` (assuming Z3 proves `!(p0 && p1)`):
//
// ```
// top proc my_proc(implicit_token__recv0: token,
//                  implicit_token__recv1: token, init={token, token}) {
//   tok: token = literal(value=token)
//   prev_tok0: token = state_read(state_element=implicit_token__recv0)
//   prev_tok1: token = state_read(state_element=implicit_token__recv1)
//   tok_all0: token = after_all(tok, prev_tok0, prev_tok1)
//   recv0: (token, bits[32]) = receive(tok_all0, predicate=p0, channel=in)
//   recv0_tok: token = tuple_index(recv0, index=0)
//   next_tok0: () = next_value(state_element=implicit_token__recv0,
//                              value=recv0_tok, predicate=p0)
//
//   tok_all1: token = after_all(tok, prev_tok0, prev_tok1)
//   recv1: (token, bits[32]) = receive(tok_all1, predicate=p1, channel=in)
//   recv1_tok: token = tuple_index(recv1, index=0)
//   next_tok1: () = next_value(state_element=implicit_token__recv1,
//                              value=recv1_tok, predicate=p1)
// }
// ```
class ChannelLegalizationPass : public OptimizationPass {
 public:
  static constexpr std::string_view kName = "channel_legalization";
  ChannelLegalizationPass()
      : OptimizationPass(kName, "Legalize multiple send/recvs per channel") {}
  ~ChannelLegalizationPass() override = default;

  RedundancyGuard GetRedundancyGuard(
      const OptimizationPassOptions& options,
      OptimizationContext& context) const override {
    return RedundancyGuard::CanSkip();
  }

 protected:
  absl::StatusOr<bool> RunInternal(Package* p,
                                   const OptimizationPassOptions& options,
                                   PassResults* results,
                                   OptimizationContext& context) const override;
};

}  // namespace xls

#endif  // XLS_PASSES_CHANNEL_LEGALIZATION_PASS_H_
