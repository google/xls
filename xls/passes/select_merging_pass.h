namespace xls {

// Attempts to merge `node` with any single-use matching select operands
// (`PrioritySelect` or `OneHotSelect`). Returns the replacement select node if
// a merge occurred, or nullptr if `node` was not modified.
absl::StatusOr<Node*> MergeSelectNode(Node* node);

// Note: What follows was generated by the Gemini LLM. Not human verified.
//
// The `SelectMergingPass` merges consecutive `OneHotSelect` or `PrioritySelect`
// operations in a `FunctionBase` into a single, larger select operation of the
// same kind. Flattening cascades of single-use selects into a unified select
// simplifies the IR and allows downstream passes (such as select
// simplification) and hardware synthesis tools to optimize across all cases at
// once.
//
// **How it Works**:
//
// The pass traverses the IR in topological order (`TopoSort`) and invokes
// `MergeSelectNode` on each `OneHotSelect` and `PrioritySelect` node:
//
// 1.  **Merging `OneHotSelect` Operations**:
//     *   **Pattern**: An outer `OneHotSelect` where one or more cases are
//         themselves single-use `OneHotSelect` nodes (`users().size() == 1`).
//     *   **Transformation**: Constructs a single merged `OneHotSelect`:
//         *   Contiguous runs of unmerged cases have their corresponding
//             selector slice extracted via `bit_slice`.
//         *   For each case `i` that is a single-use `OneHotSelect`, bit `i` of
//             the outer selector is extracted (`bit_slice`), sign-extended to
//             the bit-width of the inner selector (`sign_ext`), and bitwise
//             `and`-ed with the inner selector. Its cases are spliced directly
//             into the merged case list.
//         *   All selector pieces are concatenated (from MSB to LSB) via
//             `CreateFlattenedConcat` (so nested `Concat` trees in selector
//             pieces are flattened immediately) to form the new selector.
//
// 2.  **Merging `PrioritySelect` Operations**:
//     *   **Selector Inversion for 1-Bit `PrioritySelect`s**: If a 1-bit
//         `PrioritySelect` has a single-use `PrioritySelect` as `cases[0]` and
//         its `default_value` is *not* a single-use `PrioritySelect`, the pass
//         first negates the 1-bit selector (`not`) and swaps `cases[0]` with
//         `default_value`. Merging an inner `PrioritySelect` from the
//         `default_value` position is simpler because its default value
//         directly becomes the merged `default_value` without needing an
//         explicit `inner_selector == 0` fallback condition.
//     *   **Case Merging**: For any case `i` that is a single-use
//         `PrioritySelect`, bit `i` of the outer selector is sign-extended and
//         `and`-ed with the inner selector to guard the inner cases, followed
//         by an additional case for the inner `default_value` guarded by
//         `and(outer_selector[i], eq(inner_selector, 0))`.
//     *   **Default Value Merging**: If the outer `default_value` is a
//         single-use `PrioritySelect`, its selector and cases are appended at
//         the lowest-priority end of the merged `PrioritySelect`, and its
//         `default_value` becomes the new outer `default_value`.
//     *   All selector pieces are concatenated via `CreateFlattenedConcat` to
//         form the merged selector.
//
// **Key Conditions for Merging**:
//
// *   **Single Use**: An inner select is only merged if `users().size() == 1`,
//     preventing logic duplication.
// *   **Matching Select Types**: `OneHotSelect` nodes are only merged into
//     `OneHotSelect`, and `PrioritySelect` nodes are only merged into
//     `PrioritySelect`.
//
// Example (`OneHotSelect` merging):
//
// ```
// // Original IR snippet
// fn f(p0: bits[2], p1: bits[2], x: bits[32], y: bits[32],
//      z: bits[32]) -> bits[32] {
//   one_hot_sel.1: bits[32] = one_hot_sel(p0, cases=[x, y])
//   ret one_hot_sel.2: bits[32] = one_hot_sel(p1, cases=[one_hot_sel.1, z])
// }
// ```
//
// Because `one_hot_sel.1` has only one user (`one_hot_sel.2`),
// `SelectMergingPass` merges them into a single 3-case `one_hot_sel`:
//
// ```
// // Optimized IR
// fn f(p0: bits[2], p1: bits[2], x: bits[32], y: bits[32],
//      z: bits[32]) -> bits[32] {
//   bit_slice.3: bits[1] = bit_slice(p1, start=0, width=1)
//   sign_ext.4: bits[2] = sign_ext(bit_slice.3, new_bit_count=2)
//   and.5: bits[2] = and(sign_ext.4, p0)
//   bit_slice.6: bits[1] = bit_slice(p1, start=1, width=1)
//   new_selector: bits[3] = concat(bit_slice.6, and.5)
//   ret one_hot_sel.7: bits[32] = one_hot_sel(new_selector, cases=[x, y, z])
// }
// ```
class SelectMergingPass : public OptimizationFunctionBasePass {
 public:
  static constexpr std::string_view kName = "select_merge";
  explicit SelectMergingPass()
      : OptimizationFunctionBasePass(kName, "Select Merging") {}
  ~SelectMergingPass() override = default;

  RedundancyGuard GetRedundancyGuard(
      const OptimizationPassOptions& options,
      OptimizationContext& context) const override {
    return RedundancyGuard::CanSkip();
  }

 protected:
  absl::StatusOr<bool> RunOnFunctionBaseInternal(
      FunctionBase* f, const OptimizationPassOptions& options,
      PassResults* results, OptimizationContext& context) const override;
};

}  // namespace xls

#endif  // XLS_PASSES_SELECT_MERGING_PASS_H_
