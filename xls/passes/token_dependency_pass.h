namespace xls {

// Pass which turns data dependencies between certain effectful operations into
// token dependencies. In particular, transitive data dependencies between
// receives and other effectful ops are turned into token dependencies whenever
// no such token dependency already exists.
//
// Note: What follows was generated by the Gemini LLM. Not human verified.
//
// The `TokenDependencyPass` ensures that ordering constraints implied by data
// dependencies between `receive` operations and downstream side-effecting
// token-consuming operations (such as `send`, `receive`, or `assert`) are
// explicitly captured in the token dependency graph.
//
// For example, if a `send` operation consumes a value derived from a `receive`
// operation's payload, but subsequent algebraic optimizations prove that the
// expression is independent of the received value (e.g., multiplied by zero or
// masked off), later passes could eliminate the data dependency. Without an
// explicit token path from the `receive` to the `send`, the scheduler could
// reorder the two I/O operations and violate program semantics.
//
// **How it Works**:
//
// 1.  **Token Provenance & Transitive Closure**: The pass runs
//     `TokenProvenanceAnalysis` on the `FunctionBase` to build the direct token
//     dependency graph over side-effecting operations and `after_all` nodes,
//     and computes its `TransitiveClosure`.
// 2.  **Data Dependency Search**: For each `receive` operation `a`, the pass
//     performs a depth-first search over the data dependency graph to find all
//     downstream side-effecting token operations `b` that are not already
//     reachable from `a` in the token transitive closure.
// 3.  **Transitive Pruning**: If operation `c` is token-dependent on operation
//     `b`, and both `b` and `c` are data-dependent on `receive` `a`, the pass
//     prunes `a` from `c`'s required set (`minimal_io_to_data_supplying_io`),
//     since adding a token edge from `a` to `b` transitively orders `a` before
//     `c`.
// 4.  **Token Rewiring**: For each remaining pair `(io, supplying_receive)`,
//     the pass extracts the token output of `supplying_receive` via
//     `tuple_index(supplying_receive, index=0)` and combines it with `io`'s
//     existing token operand using a new `after_all` node.
//
// **Example**:
//
// ```
// // Original IR
// chan test_channel(
//   bits[32], id=0, kind=streaming, ops=send_receive,
//   flow_control=ready_valid)
//
// top proc main(__state: (), init={()}) {
//   __token: token = literal(value=token, id=1000)
//   receive.1: (token, bits[32]) = receive(__token, channel=test_channel)
//   tuple_index.2: token = tuple_index(receive.1, index=0)
//   tuple_index.3: bits[32] = tuple_index(receive.1, index=1)
//   send.4: token = send(__token, tuple_index.3, channel=test_channel)
//   after_all.5: token = after_all(send.4, tuple_index.2)
//   tuple.6: () = tuple()
//   next (tuple.6)
// }
//
// // Optimized IR
// top proc main(__state: (), init={()}) {
//   __token: token = literal(value=token, id=1000)
//   receive.1: (token, bits[32]) = receive(__token, channel=test_channel)
//   tuple_index.2: token = tuple_index(receive.1, index=0)
//   tuple_index.3: bits[32] = tuple_index(receive.1, index=1)
//   tuple_index.7: token = tuple_index(receive.1, index=0)
//   after_all.8: token = after_all(tuple_index.7, __token)
//   send.4: token = send(after_all.8, tuple_index.3, channel=test_channel)
//   after_all.5: token = after_all(send.4, tuple_index.2)
//   tuple.6: () = tuple()
//   next (tuple.6)
// }
// ```
class TokenDependencyPass : public OptimizationFunctionBasePass {
 public:
  static constexpr std::string_view kName = "token_dependency";
  TokenDependencyPass()
      : OptimizationFunctionBasePass(kName,
                                     "Convert data dependencies between "
                                     "effectful operations into token "
                                     "dependencies") {}
  ~TokenDependencyPass() override = default;

  bool IsIdempotent() const override { return true; }

  RedundancyGuard GetRedundancyGuard(
      const OptimizationPassOptions& options,
      OptimizationContext& context) const override {
    return RedundancyGuard::CanSkip();
  }

 protected:
  absl::StatusOr<bool> RunOnFunctionBaseInternal(
      FunctionBase* f, const OptimizationPassOptions& options,
      PassResults* results, OptimizationContext& context) const override;
};

}  // namespace xls

#endif  // XLS_PASSES_TOKEN_DEPENDENCY_PASS_H_
