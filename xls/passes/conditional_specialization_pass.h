#ifndef XLS_PASSES_CONDITIONAL_SPECIALIZATION_PASS_H_
#define XLS_PASSES_CONDITIONAL_SPECIALIZATION_PASS_H_

#include <string_view>

#include "absl/status/statusor.h"
#include "xls/ir/function_base.h"
#include "xls/passes/optimization_pass.h"
#include "xls/passes/pass_base.h"

namespace xls {

// Pass which specializes arms of select operations based on their selector
// value. When analyzing a particular arm of a `sel`, the value of the
// selector is known. This knowledge can be used to simplify the expression
// within the arm.
//
// Note: What follows was generated by the Gemini LLM. Not human verified.
//
// The `ConditionalSpecializationPass` propagates contextual value constraints
// (`ConditionSet`, storing up to 64 `Condition{Node*, PartialInformation}`
// entries combining ternary bit vectors and `IntervalSet` ranges) backward
// through the IR graph in reverse topological order and uses those assumptions
// to specialize operands and state reads.
//
// **How it Works**:
//
// 1.  **No-Op `next_value` Removal (`EliminateNoopNext`)**:
//     When `options.eliminate_noop_next` is true, any `next_value` operation
//     whose value is a `state_read` of the exact same `StateElement` is
//     replaced with `()` and removed before analysis begins.
//
// 2.  **Query Engine Configuration (`use_bdd`)**:
//     The pass uses a `UnionQueryEngine` containing a `StatelessQueryEngine`
//     and, when `use_bdd` is enabled (`cond_spec(Bdd)` / `cond_spec(true)`),
//     the shared `BddQueryEngine` for stronger Boolean implication analysis.
//
// 3.  **Seeding and Propagating Conditions (`ConditionMap`,
//     `ImpliedConditionCache`)**:
//     *   **Edge Conditions**: Contextual assumptions are seeded on specific
//         operand edges:
//         *   `sel`: Along `case[i]`, assumes `selector == i`.
//         *   `one_hot_sel`: Along `case[i]`, assumes bit `i` of `selector` is
//             `1`.
//         *   `priority_sel`: Along `case[i]`, assumes bit `i` of `selector` is
//             `1` and bits `0..i-1` are `0`; along `default`, assumes
//             `selector == 0`.
//         *   `array_update`: Along the `update_value` edge, assumes each
//             non-literal index is in bounds `[0, array_size)`.
//         *   Conditional `send` and `next_value`: Along the `data` / `value`
//             edge, assumes `predicate == 1`.
//         *   `and`, `nand`, `or`, `nor`: When analyzing one operand edge,
//             assumes all other operands are not equal to the absorbing value
//             (`0` for `and`/`nand`, all-ones for `or`/`nor`).
//     *   **Implied Conditions**: Each seeded `Condition` is expanded via
//         `ImpliedConditionCache` by lifting known bits and ranges backward
//         through `not`, `and`, `or`, `nand`, `nor`, `eq`, and `ne`.
//     *   **Intersection Across Users**: For a node without implicit uses
//         (excluding `invoke`, side-effecting ops other than `state_read`, and
//         nodes used as a `state_read` predicate), its node `ConditionSet` is
//         the intersection (`MeetWith`) of the edge condition sets across all
//         of its users. For a `state_read`, its conditions are further
//         intersected with the intersection of conditions across the
//         `next_value` nodes for that state element.
//
// 4.  **Specializing Nodes and Operands**:
//     *   **Predicating Unconditional `state_read`s**: When
//         `options.optimize_for_best_case_throughput` is enabled, if an
//         unconditional `state_read` has a non-empty `ConditionSet` (meaning it
//         is only needed when those conditions hold), the pass synthesizes a
//         matching predicate (`CheckMatch`) from non-dependent conditions and
//         attaches it via `SetPredicate`.
//     *   **Folding Implied Constant Operands**: Using a query engine
//         specialized with the edge's `ConditionSet` (`SpecializeGiven`), if an
//         operand's value is uniquely implied (`ImpliedNodeValue`), the operand
//         is replaced with a `literal` (or the entire `and`/`nand`/`or`/`nor`
//         node is replaced with a constant if the implied operand value is
//         absorbing).
//     *   **Bypassing Ancestor Selects and Bitwise Operations**: If an operand
//         is a `sel`, `priority_sel`, `one_hot_sel`, `and`, `or`, or `xor`, the
//         pass walks up the operand chain as long as the edge conditions imply
//         which branch of a select is active or imply that all but one operand
//         of a bitwise op equal the identity element (`~0` for `and`, `0` for
//         `or`/`xor`), rewiring the user directly to the active branch or
//         non-identity input.
//
// Example:
//
// ```
// fn f(a: bits[1], b: bits[31], z: bits[32]) -> bits[32] {
//   concat.1: bits[32] = concat(a, b)
//   ret sel.2: bits[32] = sel(a, cases=[z, concat.1])
// }
// ```
//
// Along the `case[1]` edge of `sel.2`, `a` is known to be `1`. If `concat.1`
// has no other users, the condition `a == 1` propagates to `concat.1` and
// specializes its first operand to a literal `1`:
//
// ```
// fn f(a: bits[1], b: bits[31], z: bits[32]) -> bits[32] {
//   lit_1: bits[1] = literal(value=1)
//   concat.1: bits[32] = concat(lit_1, b)
//   ret sel.2: bits[32] = sel(a, cases=[z, concat.1])
// }
// ```
class ConditionalSpecializationPass : public OptimizationFunctionBasePass {
 public:
  static constexpr std::string_view kName = "cond_spec";
  // If `use_bdd` is true, then binary decision diagrams (BDDs) are used for
  // stronger analysis at the cost of slower transformation.
  explicit ConditionalSpecializationPass(bool use_bdd)
      : OptimizationFunctionBasePass(ConfiguredName(use_bdd),
                                     "Conditional specialization"),
        use_bdd_(use_bdd) {}

  RedundancyGuard GetRedundancyGuard(
      const OptimizationPassOptions& options,
      OptimizationContext& context) const override;

  ~ConditionalSpecializationPass() override = default;

 protected:
  bool use_bdd_;
  absl::StatusOr<bool> RunOnFunctionBaseInternal(
      FunctionBase* f, const OptimizationPassOptions& options,
      PassResults* results, OptimizationContext& context) const override;

 private:
  static std::string_view ConfiguredName(bool use_bdd) {
    if (use_bdd) {
      return "cond_spec(Bdd)";
    }
    return "cond_spec(noBdd)";
  }
};

}  // namespace xls

#endif  // XLS_PASSES_CONDITIONAL_SPECIALIZATION_PASS_H_
