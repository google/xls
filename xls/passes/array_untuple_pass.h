#ifndef XLS_PASSES_ARRAY_UNTUPLE_PASS_H_
#define XLS_PASSES_ARRAY_UNTUPLE_PASS_H_

#include <string_view>

#include "absl/status/statusor.h"
#include "xls/ir/function_base.h"
#include "xls/passes/optimization_pass.h"
#include "xls/passes/pass_base.h"

namespace xls {

// Pass which changes any (non-external) array-of-tuple into a tuple-of-arrays.
// We can see through tuples quite well but can't see through arrays to anywhere
// near the same extent. Therefore the struct-of-array representation is
// always superior.
//
// Note that this pass makes no attempt to unpack or repack arrays which escape
// the function-base. This means that anything which comes in through a function
// param, or a procs recv or escapes through a function return or a proc send is
// not untuple'd.
//
// TODO(allight): We could do this at the cost of a significant number of ir
// nodes. We should experiment to see if this is worth doing.
//
// Note: What follows was generated by the Gemini LLM. Not human verified.
//
// The `ArrayUntuplePass` transforms internal arrays of tuples
// (`Array<Tuple<A, B, ...>>`) into conceptual tuples of component arrays
// (`Array<A>, Array<B>, ...`) within functions and procs (blocks are skipped).
// This struct-of-arrays (SoA) transformation separates independent tuple fields
// into distinct arrays so that subsequent passes (such as
// `DataflowSimplificationPass`, `ArraySimplificationPass`, and
// `DeadCodeEliminationPass`) can optimize or eliminate unused fields
// independently.
//
// **How it Works**:
//
// 1.  **Grouping Connected Array Operations (`FindUntupleGroups`)**:
//     Uses a `UnionFind<Node*>` structure to group nodes that must be
//     transformed together. Connected operations that union their array
//     operands and results into the same equivalence class include
//     `array_update`, `array_slice`, `array_concat`, `eq`, `ne`, `sel`,
//     `priority_sel`, `one_hot_sel`, `gate`, and all `state_read`s and
//     `next_value` `value` operands associated with the same proc
//     `StateElement`.
//
// 2.  **Excluding Externally Visible or Unhandled Groups
//     (`FindExternalGroups`)**:
//     Identifies equivalence groups that cannot be untupled without repacking:
//     *   Function parameters (`param`) and function return values of array
//         type.
//     *   Proc `send` data operands of array type.
//     *   Proc `StateElement`s whose `state_read`s are only used in no-op
//         self-updates (`IsNoOpNext`).
//     *   Arrays of empty tuples (`()[N]`).
//     *   Nested arrays of arrays of tuples (`(A, B)[M][N]`).
//     *   The `update_value` operand of an `array_update`.
//     *   Arrays of tuples produced or consumed by any other unhandled
//         operation (such as `tuple_index` extracting an array from a `receive`
//         token/data tuple).
//
// 3.  **Rewriting Eligible Groups (`UntupleVisitor`)**:
//     Traverses the graph in topological order and splits each eligible
//     `Array<Tuple<T_0, ..., T_{k-1}>>` node into `k` component arrays
//     `Array<T_0>, ..., Array<T_{k-1}>`:
//     *   **`Literal`**: Splits an array-of-tuples literal into `k` separate
//         array `literal`s, one for each tuple element.
//     *   **`StateRead` and `Next`**: Splits an array-of-tuples proc
//         `StateElement` into `k` new state elements (`<name>_tuple_element_i`)
//         with corresponding `state_read` and `next_value` nodes, detaching the
//         original state element into a dead no-op update.
//     *   **`Array`**: Extracts tuple elements from each operand via
//         `tuple_index` and constructs `k` separate `array` nodes.
//     *   **`ArrayIndex`**: Replaces `array_index(arr, indices)` with a `tuple`
//         of `k` `array_index` nodes indexing into each component array.
//     *   **`ArrayUpdate`, `ArraySlice`, `ArrayConcat`, `Gate`, and Selects
//         (`Sel`, `PrioritySel`, `OneHotSel`)**: Distributes the operation
//         across each of the `k` component arrays.
//     *   **`Eq` and `Ne`**: Compares each pair of component arrays
//         individually and combines the boolean results with `and` (for `eq`)
//         or `or` (for `ne`).
//
// **Example**:
//
// ```
// // Original IR
// fn read_second_field(t0: (bits[32], bits[16]),
//                      t1: (bits[32], bits[16]),
//                      idx: bits[1]) -> bits[16] {
//   arr: (bits[32], bits[16])[2] = array(t0, t1)
//   elem: (bits[32], bits[16]) = array_index(arr, indices=[idx])
//   ret res: bits[16] = tuple_index(elem, index=1)
// }
//
// // After ArrayUntuplePass (and subsequent tuple/dead-code cleanup)
// fn read_second_field(t0: (bits[32], bits[16]),
//                      t1: (bits[32], bits[16]),
//                      idx: bits[1]) -> bits[16] {
//   t0_f1: bits[16] = tuple_index(t0, index=1)
//   t1_f1: bits[16] = tuple_index(t1, index=1)
//   arr_tuple_idx_1: bits[16][2] = array(t0_f1, t1_f1)
//   ret elem_tuple_idx_1: bits[16] = array_index(arr_tuple_idx_1,
//                                                indices=[idx])
// }
// ```
class ArrayUntuplePass : public OptimizationFunctionBasePass {
 public:
  static constexpr std::string_view kName = "array_untuple";
  explicit ArrayUntuplePass()
      : OptimizationFunctionBasePass(kName, "Array UnTuple") {}
  ~ArrayUntuplePass() override = default;

  RedundancyGuard GetRedundancyGuard(
      const OptimizationPassOptions& options,
      OptimizationContext& context) const override {
    return RedundancyGuard::CanSkip();
  }

 protected:
  absl::StatusOr<bool> RunOnFunctionBaseInternal(
      FunctionBase* f, const OptimizationPassOptions& options,
      PassResults* results, OptimizationContext& context) const override;
};
}  // namespace xls

#endif  // XLS_PASSES_ARRAY_UNTUPLE_PASS_H_
