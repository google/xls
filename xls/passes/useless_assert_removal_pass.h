#ifndef XLS_PASSES_USELESS_ASSERT_REMOVAL_PASS_H_
#define XLS_PASSES_USELESS_ASSERT_REMOVAL_PASS_H_

#include <string_view>

#include "absl/status/statusor.h"
#include "xls/ir/function_base.h"
#include "xls/passes/optimization_pass.h"
#include "xls/passes/pass_base.h"

namespace xls {

// Pass which removes asserts that have a literal 1 as the condition, meaning
// they are never triggered. Rewires tokens to ensure nothing breaks.
//
// Note: What follows was generated by the Gemini LLM. Not human verified.
//
// The `UselessAssertRemovalPass` eliminates `assert` operations whose condition
// is statically known to be true (`1`), since such assertions can never fail
// at runtime or in simulation.
//
// **How it Works**:
//
// 1.  **Condition Analysis**: The pass traverses the IR in topological order
//     and queries a `StatelessQueryEngine` (`KnownValueAsBits`) on each
//     `assert` node's `condition` operand.
// 2.  **Token Rewiring and Removal**: If the `condition` is known to be `1`
//     (`IsOne()`), all uses of the `assert` node's output token are replaced
//     directly with the `assert`'s input `token` operand, and the `assert`
//     node is removed from the `FunctionBase`.
//
// **Example**:
//
// ```
// // Original IR
// fn f(tkn: token) -> token {
//   literal.1: bits[1] = literal(value=1)
//   ret assert.2: token = assert(tkn, literal.1, message="always passes")
// }
//
// // Optimized IR
// fn f(tkn: token) -> token {
//   ret tkn
// }
// ```
class UselessAssertRemovalPass : public OptimizationFunctionBasePass {
 public:
  static constexpr std::string_view kName = "useless_assert_remove";
  UselessAssertRemovalPass()
      : OptimizationFunctionBasePass(kName,
                                     "Remove useless (always true) asserts") {}
  ~UselessAssertRemovalPass() override = default;

  bool IsIdempotent() const override { return true; }

  RedundancyGuard GetRedundancyGuard(
      const OptimizationPassOptions& options,
      OptimizationContext& context) const override {
    return RedundancyGuard::CanSkip();
  }

 protected:
  absl::StatusOr<bool> RunOnFunctionBaseInternal(
      FunctionBase* f, const OptimizationPassOptions& options,
      PassResults* results, OptimizationContext& context) const override;
};

}  // namespace xls

#endif  // XLS_PASSES_USELESS_ASSERT_REMOVAL_PASS_H_
