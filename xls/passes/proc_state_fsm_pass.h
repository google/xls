namespace xls {

// Pass which tries to minimize the size and total number of elements of the
// proc state by optimizing implicit state-machines in the state elements.
//
// Note: What follows was generated by the Gemini LLM. Not human verified.
//
// `ProcStateFSMPass` compresses state elements whose values evolve through a
// known finite sequence of constants into a compact binary-encoded saturating
// counter (state machine).
//
// ### How It Works
//
// 1. **Query Engine Setup**: Combines `StatelessQueryEngine` and a shared
//    `LazyTernaryQueryEngine` via `UnionQueryEngine` to identify `next_value`
//    expressions that evaluate to known constants (`IsFullyKnown`).
//
// 2. **Detecting Constant Chains (`ConvertConstantChainsToStateMachines`)**:
//    In general, `ConstantChainToStateMachine` is designed to compress a shift
//    chain of `k` state elements `c[0..k-1]` where `next[c[0]]` is an
//    unconditional constant and `next[c[i+1]] == state_read[c[i]]` into a
//    single binary counter of width `CeilOfLog2(k) + 1` bits (avoiding a
//    `k`-bit one-hot encoding). Currently,
//    `ConvertConstantChainsToStateMachines` detects chains of length `k = 1`:
//    any state element (of arbitrary width or compound type) that has a single
//    unconditional `next_value` (`predicate == std::nullopt`) whose `value` is
//    fully known by the query engine.
//
// 3. **State Machine Replacement (`ConstantChainToStateMachine`)**:
//    * Appends a new state element `state_machine_<names>` of type
//      `bits[CeilOfLog2(k) + 1]` initialized to `0` (marked `non_synthesizable`
//      if any element in the chain was non-synthesizable).
//    * Updates the state machine each tick using a saturating increment:
//      `sel(ugt(state, k - 1), cases=[add(state, 1), state])`.
//    * Replaces each original `StateRead` at chain index `j` with a `sel`
//      indexed by `state_machine` whose `cases` are the reversed initial
//      values `[init[j], ..., init[0]]` and whose `default` is the known
//      constant `chain_literal`. For `k = 1`, this selects `init[0]` on tick 0
//      (when `state_machine == 0`) and `chain_literal` on all subsequent ticks
//      (when `state_machine == 1`).
//    * Removes the original state elements and their `Next` nodes, and
//      repopulates the query engine.
//
// ### Example
//
// Suppose a 32-bit state element `s` starts at `0x1234_5678` on the first
// activation and unconditionally transitions to `0xDEAD_BEEF` thereafter:
//
// ```
// // Before
// proc my_proc(s: bits[32], init={0x1234_5678}) {
//   s_read: bits[32] = state_read(state_element=s)
//   c: bits[32] = literal(value=0xdead_beef)
//   next_value(param=s, value=c)
// }
// ```
//
// `ProcStateFSMPass` replaces the 32-bit register `s` with a 1-bit saturating
// counter `state_machine_s`:
//
// ```
// // After
// proc my_proc(state_machine_s: bits[1], init={0}) {
//   state_machine_s_read: bits[1] = state_read(state_element=state_machine_s)
//   one: bits[1] = literal(value=1)
//   max: bits[1] = literal(value=0)
//   plus_one: bits[1] = add(state_machine_s_read, one)
//   too_large: bits[1] = ugt(state_machine_s_read, max)
//   next_sm: bits[1] = sel(too_large, cases=[plus_one, state_machine_s_read])
//   next_value(param=state_machine_s, value=next_sm)
//
//   init_lit: bits[32] = literal(value=0x1234_5678)
//   chain_lit: bits[32] = literal(value=0xdead_beef)
//   s_read: bits[32] = sel(state_machine_s_read, cases=[init_lit],
//                          default=chain_lit)
// }
// ```
class ProcStateFSMPass : public OptimizationProcPass {
 public:
  static constexpr std::string_view kName = "proc_state_fsm";
  ProcStateFSMPass()
      : OptimizationProcPass(kName,
                             "Proc State Finite state machine Optimization") {}
  ~ProcStateFSMPass() override = default;

  RedundancyGuard GetRedundancyGuard(
      const OptimizationPassOptions& options,
      OptimizationContext& context) const override {
    return RedundancyGuard::CanSkip();
  }

 protected:
  absl::StatusOr<bool> RunOnProcInternal(
      Proc* proc, const OptimizationPassOptions& options, PassResults* results,
      OptimizationContext& context) const override;
};

}  // namespace xls

#endif  // XLS_PASSES_PROC_STATE_FSM_PASS_H_
