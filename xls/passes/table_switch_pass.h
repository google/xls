namespace xls {

// TableSwitchPass converts chains of Select/PrioritySelect nodes into
// ArrayIndex ops. These chains have the form:
// sel.(N)(eq.X, literal.A, literal.B)
// sel.(N+1)(eq.Y, sel.(N), literal.C)
// sel.(N+2)(eq.Z, sel.(N+1), literal.D)
// And so on. In these chains, eq.X, eq.Y, and eq.Z must all be `eq` or `ne`
// comparisons of the same value against constant keys.
//
// Current limitations:
//  - Chains must contain at least 3 links.
//  - Keys must fit in `uint64_t`, and matched values (plus the final
//    fall-through value if the index space is not fully covered) must be
//    literals.
//  - Matched keys must cover either the entire index space or more than half
//    of `[0, min(2^width, max_key + 2))`.
//  - `Select` ops must be binary, and `PrioritySelect` selectors must be 1-bit
//    or a `Concat` of 1-bit selectors.
//
// Note: What follows was generated by the Gemini LLM. Not human verified.
//
// The `TableSwitchPass` is an optimization pass in XLS that transforms cascaded
// chains of `select` and `priority_select` nodes into direct `array_index`
// table lookups on an array literal. Replacing a chain of conditional branches
// comparing a common index against constant keys with a single constant-array
// lookup simplifies control logic and improves hardware area and delay.
//
// **How it Works**:
//
// 1.  **Chain Matching (`MatchLinks`)**:
//     *   The pass traverses nodes in reverse topological order (`Use`-before-
//         `Def`, via `context.ReverseTopoSort(f)`) using a
//         `StatelessQueryEngine` to identify the root of a lookup chain and
//         avoid re-processing interior links of a chain already transformed.
//     *   Each link in the chain is either:
//         *   A binary `sel` or 1-bit `priority_sel` whose selector compares a
//             common `index` node against a constant `uint64_t` `key` using
//             `eq` or `ne`, selecting a `literal` value on match and forwarding
//             to the `next` node on mismatch, or
//         *   A multi-case `priority_sel` whose selector is a `concat` of 1-bit
//             `eq`/`ne` comparisons against the same `index` node, which
//             contributes multiple consecutive links to the chain. If only a
//             suffix of a `priority_sel`'s cases starts the chain (at
//             `first_case > 0`), the prefix cases are preserved in a truncated
//             `priority_sel` whose default value becomes the new `array_index`.
//     *   Chains with 2 or fewer links (`links.size() <= 2`) are skipped as too
//         short to benefit from table conversion.
//
// 2.  **Table Construction (`LinksToTable`)**:
//     *   The pass walks the chain from outermost to innermost link, recording
//         the first `Literal` value associated with each `uint64_t` key (later
//         duplicate keys in the chain are unreachable and ignored).
//     *   **Full Index Space Coverage**: If the index width is `< 63` bits and
//         the matched keys cover all `2^width` possible index values, the final
//         fall-through (`else`) value is dead and need not be a literal; the
//         pass emits an array literal of size `2^width`.
//     *   **Partial / Sparse Coverage with Saturation**: Otherwise, the final
//         fall-through node must be a `Literal` (`else_value`). Leveraging XLS
//         `array_index` out-of-bounds saturation semantics (where any index
//         `>= size - 1` clamps to the last element), the pass bounds the table
//         size to `min(2^width, max_key + 2)`. If more than half of the entries
//         in `[0, table_size)` are explicitly matched (`map.size() * 2 >
//         table_size`), any missing indices (gaps) and the saturating final
//         slot are filled with `else_value`.
//
// 3.  **Replacement**:
//     The pass creates a `literal` array containing the table entries and
//     replaces the root of the chain with `array_index(array_literal,
//     indices=[index])`.
//
// **Example**:
//
// ```
// // Original IR
// fn main(index: bits[32]) -> bits[32] {
//   literal.0: bits[32] = literal(value=0)
//   literal.1: bits[32] = literal(value=1)
//   literal.2: bits[32] = literal(value=2)
//   literal.10: bits[32] = literal(value=10)
//   literal.20: bits[32] = literal(value=20)
//   literal.30: bits[32] = literal(value=30)
//   literal.99: bits[32] = literal(value=99)
//   eq.4: bits[1] = eq(index, literal.0)
//   eq.5: bits[1] = eq(index, literal.1)
//   eq.6: bits[1] = eq(index, literal.2)
//   sel.7: bits[32] = sel(eq.4, cases=[literal.99, literal.10])
//   sel.8: bits[32] = sel(eq.5, cases=[sel.7, literal.20])
//   ret sel.9: bits[32] = sel(eq.6, cases=[sel.8, literal.30])
// }
//
// // Optimized IR
// fn main(index: bits[32]) -> bits[32] {
//   array_literal: bits[32][4] = literal(value=[10, 20, 30, 99])
//   ret array_index.10: bits[32] = array_index(array_literal, indices=[index])
// }
// ```
class TableSwitchPass : public OptimizationFunctionBasePass {
 public:
  static constexpr std::string_view kName = "table_switch";
  TableSwitchPass()
      : OptimizationFunctionBasePass(kName, "Table switch conversion") {}

  RedundancyGuard GetRedundancyGuard(
      const OptimizationPassOptions& options,
      OptimizationContext& context) const override {
    return RedundancyGuard::CanSkip();
  }

 protected:
  absl::StatusOr<bool> RunOnFunctionBaseInternal(
      FunctionBase* f, const OptimizationPassOptions& options,
      PassResults* results, OptimizationContext& context) const override;
};

}  // namespace xls

#endif  // XLS_PASSES_TABLE_SWITCH_PASS_H_
