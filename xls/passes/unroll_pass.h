namespace xls {

// Note: What follows was generated by the Gemini LLM. Not human verified.
//
// The `UnrollPass` unrolls `counted_for` loops within a function or proc by
// expanding each iteration into an explicit `invoke` of the loop's body
// function.
//
// **How it Works**:
//
// 1.  **Loop Discovery**: The pass searches the `FunctionBase` for any
//     effectively used `counted_for` node (a node that has users or is the
//     function return value).
// 2.  **Iterative Expansion**: For a `counted_for` with `trip_count` iterations
//     and step `stride`, the pass initializes the loop-carried accumulator
//     `loop_carry` to `initial_value`. For each trip `0 <= trip < trip_count`
//     (with induction variable `iv = trip * stride`), it:
//     *   Creates a `literal` node for `iv` matching the bit-width of the body
//         function's first parameter.
//     *   Emits an `invoke` node calling `body` with arguments
//         `[iv, loop_carry, invariant_args...]` and updates `loop_carry` to the
//         result of the `invoke`.
// 3.  **Replacement**: All uses of the `counted_for` node are replaced with the
//     final `loop_carry` node (or `initial_value` if `trip_count == 0`), and
//     the `counted_for` node is removed. This repeats until no used
//     `counted_for` nodes remain.
//
// **Example**:
//
// ```
// // Original IR
// fn body(i: bits[4], accum: bits[32], zero: bits[32]) -> bits[32] {
//   zero_ext.3: bits[32] = zero_ext(i, new_bit_count=32)
//   add.4: bits[32] = add(zero_ext.3, accum)
//   ret add.5: bits[32] = add(add.4, zero)
// }
//
// fn unrollable() -> bits[32] {
//   literal.1: bits[32] = literal(value=0)
//   ret counted_for.2: bits[32] = counted_for(literal.1, trip_count=2,
//       stride=2, body=body, invariant_args=[literal.1])
// }
//
// // Optimized IR
// fn unrollable() -> bits[32] {
//   literal.1: bits[32] = literal(value=0)
//   literal.6: bits[4] = literal(value=0)
//   invoke.7: bits[32] = invoke(literal.6, literal.1, literal.1, to_apply=body)
//   literal.8: bits[4] = literal(value=2)
//   ret invoke.9: bits[32] = invoke(literal.8, invoke.7, literal.1,
//       to_apply=body)
// }
// ```
class UnrollPass : public OptimizationFunctionBasePass {
 public:
  static constexpr std::string_view kName = "loop_unroll";
  UnrollPass() : OptimizationFunctionBasePass(kName, "Unroll counted loops") {}

  bool IsIdempotent() const override { return true; }

  RedundancyGuard GetRedundancyGuard(
      const OptimizationPassOptions& options,
      OptimizationContext& context) const override {
    return RedundancyGuard::CanSkip();
  }

 protected:
  absl::StatusOr<bool> RunOnFunctionBaseInternal(
      FunctionBase* f, const OptimizationPassOptions& options,
      PassResults* results, OptimizationContext& context) const override;
};

}  // namespace xls

#endif  // XLS_PASSES_UNROLL_PASS_H_
