#ifndef XLS_PASSES_USELESS_IO_REMOVAL_PASS_H_
#define XLS_PASSES_USELESS_IO_REMOVAL_PASS_H_

#include <string_view>

#include "absl/status/statusor.h"
#include "xls/ir/package.h"
#include "xls/passes/optimization_pass.h"
#include "xls/passes/pass_base.h"

namespace xls {

// Pass which removes sends/receives that have literal false as their condition.
// Also removes the condition from sends/receives that have literal true as
// their condition.
//
// Note: What follows was generated by the Gemini LLM. Not human verified.
//
// The `UselessIORemovalPass` simplifies predicated `send` and `receive`
// operations across all procs in a `Package` when their `predicate` operand is
// statically known to be `0` (false) or `1` (true) according to a
// `StatelessQueryEngine`.
//
// First, the pass builds a package-wide map (`ComputeChannelMaps`) tracking
// all `send` and `receive` operations associated with each `ChannelRef`. It
// then traverses each proc in topological order and applies the following
// transformations to predicated I/O nodes:
//
// 1.  **Removal or Simplification of False-Predicated I/O (`predicate == 0`)**:
//     *   **`send` with `predicate == 0`**:
//         *   If there is at least one other `send` remaining on the same
//             channel, the disabled `send` is removed and its uses are replaced
//             with its input `token` operand.
//         *   If it is the **last** `send` on that channel, removing it would
//             leave the channel without a sender. Instead, the `send` is kept
//             and its `data` operand is replaced with a zero literal
//             (`ZeroOfType`) so dead upstream data computation can be removed.
//     *   **`receive` with `predicate == 0`**:
//         *   If there is at least one other `receive` remaining on the same
//             channel, the disabled `receive` is removed and replaced with a
//             `tuple` containing `(token, zero_data)` for blocking receives, or
//             `(token, zero_data, 0)` (with a `0` valid bit) for non-blocking
//             receives.
//
//     ```
//     // Original IR (assuming another send exists on my_chan)
//     literal.1: bits[1] = literal(value=0)
//     send.2: token = send(tkn, data, predicate=literal.1, channel=my_chan)
//
//     // Optimized IR
//     // Uses of send.2 are replaced directly with tkn.
//     ```
//
// 2.  **Simplification of True-Predicated I/O (`predicate == 1`)**:
//     If a `send` or `receive` has a predicate known to be `1`, the redundant
//     `predicate` operand is stripped, converting the operation into an
//     unpredicated `send` or `receive` on the same channel.
//
//     ```
//     // Original IR
//     literal.1: bits[1] = literal(value=1)
//     receive.2: (token, bits[32]) = receive(tkn, predicate=literal.1,
//         channel=my_chan)
//
//     // Optimized IR
//     receive.3: (token, bits[32]) = receive(tkn, channel=my_chan)
//     ```
class UselessIORemovalPass : public OptimizationPass {
 public:
  static constexpr std::string_view kName = "useless_io_remove";
  UselessIORemovalPass()
      : OptimizationPass(kName, "Remove useless send/receive") {}
  ~UselessIORemovalPass() override = default;

  RedundancyGuard GetRedundancyGuard(
      const OptimizationPassOptions& options,
      OptimizationContext& context) const override {
    return RedundancyGuard::CanSkip();
  }

 protected:
  absl::StatusOr<bool> RunInternal(Package* p,
                                   const OptimizationPassOptions& options,
                                   PassResults* results,
                                   OptimizationContext& context) const override;
};

}  // namespace xls

#endif  // XLS_PASSES_USELESS_IO_REMOVAL_PASS_H_
