#ifndef XLS_PASSES_INVALIDATE_CACHED_PROC_STATE_INFO_PASS_H_
#define XLS_PASSES_INVALIDATE_CACHED_PROC_STATE_INFO_PASS_H_

#include <string_view>

#include "absl/status/statusor.h"
#include "xls/ir/function_base.h"
#include "xls/passes/optimization_pass.h"
#include "xls/passes/pass_base.h"

namespace xls {

// Helper fake class that invalidates cached proc-state information in the
// query engines.
//
// This invalidates the givens in PartialInfoQueryEngine and
// LazyTernaryQueryEngine.
//
// Note: What follows was generated by the Gemini LLM. Not human verified.
//
// `InvalidateCachedProcStateInfoPass` is a bookkeeping pseudo-pass for `Proc`s
// that clears cached proc state range and ternary invariants ("givens") stored
// in the `OptimizationContext`'s shared query engines, without modifying the
// IR itself.
//
// **Background and Motivation**:
//
// During proc optimization (such as `ProcStateRangeQueryEngine` and
// `ProcStateNarrowingPass`), XLS analyzes how proc state elements evolve across
// ticks and records proven state-element invariants in
// `CachedStateElementQueryEngine` wrappers around `PartialInfoQueryEngine` and
// `LazyTernaryQueryEngine`. Caching these state invariants allows subsequent
// passes to retain narrowed state bounds even after intermediate rewrites make
// the state evolution harder to re-derive from scratch. However, once a group
// of passes finishes or before transformations that might invalidate those
// cached assumptions, the cached state "givens" must be explicitly cleared.
//
// **How it Works**:
//
// When run on a `Proc`, `RunOnProcInternal` retrieves both cached query engines
// from `OptimizationContext` and clears their recorded state-element givens:
// 1.  `CachedStateElementQueryEngine::FromContext<PartialInfoQueryEngine>`
//     `->ClearGivens()`
// 2.  `CachedStateElementQueryEngine::FromContext<LazyTernaryQueryEngine>`
//     `->ClearGivens()`
//
// The pass always returns `false` because it only mutates analysis cache state
// in `OptimizationContext` and never alters the IR graph.
//
// **Example**:
//
// Suppose a proc has a 32-bit state element `st` that `ProcStateNarrowingPass`
// proves is always in `[0, 7]`, caching that range in
// `CachedStateElementQueryEngine`:
//
// ```
// // IR remains unchanged before and after InvalidateCachedProcStateInfoPass;
// // only the cached state-element givens in OptimizationContext are cleared.
// proc counter(st: bits[32], init={0}) {
//   lit1: bits[32] = literal(value=1)
//   sum: bits[32] = add(st, lit1)
//   mask: bits[32] = literal(value=7)
//   next_st: bits[32] = and(sum, mask)
//   next (next_st)
// }
// ```
class InvalidateCachedProcStateInfoPass : public OptimizationProcPass {
 public:
  static constexpr std::string_view kName = "invalidate_cached_proc_state_info";
  InvalidateCachedProcStateInfoPass()
      : OptimizationProcPass(
            kName, "Invalidate proc state cached range information.") {}
  ~InvalidateCachedProcStateInfoPass() override = default;

 protected:
  absl::StatusOr<bool> RunOnProcInternal(
      Proc* proc, const OptimizationPassOptions& options, PassResults* results,
      OptimizationContext& context) const override;
};

}  // namespace xls

#endif  // XLS_PASSES_INVALIDATE_CACHED_PROC_STATE_INFO_PASS_H_
