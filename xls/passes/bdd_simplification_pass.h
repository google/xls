namespace xls {

// Runs BDD-based simplifications on the function.
//
// Note: What follows was generated by the Gemini LLM. Not human verified.
//
// The `BddSimplificationPass` leverages Binary Decision Diagrams (BDDs) via a
// `UnionQueryEngine` (combining `StatelessQueryEngine` and `BddQueryEngine`) to
// perform logic-level simplifications on the IR in topological order.
//
// The pass performs the following transformations:
//
// 1.  **Replacing Statically Known Bits with Literals**:
//     For each non-literal `bits`-typed node, the pass inspects known constant
//     bits at the most-significant end (prefix) and least-significant end
//     (suffix):
//     *   **Fully Known Nodes**: If all bits of the node are statically known,
//         the node is replaced with a `literal` at any optimization level.
//     *   **Known Prefix/Suffix Splitting (when `SplitsEnabled(opt_level)` is
//         true, at `opt_level >= 3`)**: If a contiguous prefix and/or suffix of
//         bits is constant (and not already exposed as a `literal` operand of a
//         `concat`), the node is replaced by a `concat` of the known prefix
//         `literal`, a `bit_slice` of the remaining unknown middle bits, and
//         the known suffix `literal`.
//
// 2.  **Removing Redundant Operands in 1-Bit Boolean Operations**:
//     For 1-bit `and`, `nand`, `or`, and `nor` operations with up to 10
//     operands (`kMaxBooleanFanIn`), the pass checks whether any operand is
//     logically implied by the others (`ImpliedNodeValue`). Specifically, for
//     each operand, it assumes all other non-redundant operands take the
//     non-controlling ("ignorable") value (`1` for `and`/`nand`, `0` for
//     `or`/`nor`). If the target operand is guaranteed to also take that
//     non-controlling value under those assumptions, the operand is replaced
//     with the constant `1` or `0` literal:
//
//     ```
//     // Original IR
//     c: bits[1] = and(a, b)
//     ret res: bits[1] = and(a, b, c)
//
//     // Optimized IR (c is implied to be 1 whenever a == 1 and b == 1)
//     one: bits[1] = literal(value=1)
//     ret res: bits[1] = and(a, b, one)
//     ```
//
// 3.  **Replacing Two-Way `OneHotSelect` with `Select` (when
//     `SplitsEnabled(opt_level)` is true, at `opt_level >= 3`)**:
//     If a `one_hot_sel` has a 2-bit selector that BDD analysis proves is
//     strictly one-hot (`AtLeastOneBitTrue` and `AtMostOneBitTrue`), it is
//     replaced with a 2-way `sel` indexed by `bit_slice(selector, start=0,
//     width=1)` with `cases=[case(1), case(0)]`.
//
// 4.  **Eliminating `OneHot` on Inputs with at Most One Bit Set**:
//     If BDD analysis proves that the operand `x` of a `one_hot` node has at
//     most one bit set (`AtMostOneBitTrue(x)`), the `one_hot` operation is
//     replaced with `concat(eq(x, 0), x)`.
//
// 5.  **Narrowing `PrioritySelect` with Guaranteed Set Bits (when
//     `NarrowingEnabled(opt_level)` is true, at `opt_level >= 2`)**:
//     If BDD analysis proves that at least one bit of a `priority_sel` selector
//     is always set (`AtLeastOneBitTrue`), the pass finds the lowest bit index
//     `last_bit` such that at least one bit in `selector[0..last_bit]` is
//     guaranteed to be true. It then slices the selector to `last_bit` bits,
//     retains `cases[0..last_bit-1]`, and promotes `case(last_bit)` to be the
//     new `default` value, discarding unreachable higher-index cases and the
//     previous default.
class BddSimplificationPass : public OptimizationFunctionBasePass {
 public:
  static constexpr std::string_view kName = "bdd_simp";
  explicit BddSimplificationPass()
      : OptimizationFunctionBasePass(kName, "BDD-based Simplification") {}
  ~BddSimplificationPass() override = default;

  RedundancyGuard GetRedundancyGuard(
      const OptimizationPassOptions& options,
      OptimizationContext& context) const override;

 protected:
  // Run all registered passes in order of registration.
  absl::StatusOr<bool> RunOnFunctionBaseInternal(
      FunctionBase* f, const OptimizationPassOptions& options,
      PassResults* results, OptimizationContext& context) const override;
};

}  // namespace xls

#endif  // XLS_PASSES_BDD_SIMPLIFICATION_PASS_H_
