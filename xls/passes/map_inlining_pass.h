namespace xls {

// A pass to convert map nodes to in-line Invoke nodes. We don't directly lower
// maps to Verilog.
//
// Note: What follows was generated by the Gemini LLM. Not human verified.
//
// The `MapInliningPass` lowers `map` operations (`Op::kMap`) in a
// `FunctionBase` into explicit per-element `array_index` and `invoke`
// operations assembled into an `array`. Because hardware description languages
// like Verilog do not directly represent higher-order `map` operations, this
// pass unrolls them so that subsequent `InliningPass` and optimization passes
// can inline and optimize the applied function across all array elements.
//
// **How it Works**:
//
// 1.  **Collecting `map` Nodes**: The pass scans `function->nodes()` and
//     collects all `Map` nodes.
// 2.  **Unrolling (`ReplaceMap`)**: For each `map` node with input array
//     `map->operand(0)` of size `N` and target function `map->to_apply()`:
//     *   For each element index `i` from `0` to `N - 1`:
//         *   Creates a `Literal` node `index` with value
//             `UBits(i, Bits::MinBitCountUnsigned(N))`.
//         *   Creates an `ArrayIndex` node extracting element `i` from
//             `map->operand(0)`.
//         *   Creates an `Invoke` node applying `map->to_apply()` to that
//             `ArrayIndex` element.
//     *   Replaces all uses of `map` with a new `Array` node containing the `N`
//         `Invoke` results, and removes the original `map` node from the
//         `FunctionBase`.
//
// A static helper `MapInliningPass::InlineOneMap(Map* map)` is also provided
// for testing and `ir_minimizer` use.
//
// **Example**:
//
// Consider a `map` operation that applies `map_fn` to a 4-element array `a`:
//
// ```
// fn map_fn(x: bits[32]) -> bits[16] {
//   ret bit_slice.1: bits[16] = bit_slice(x, start=0, width=16)
// }
//
// fn main(a: bits[32][4]) -> bits[16][4] {
//   ret result: bits[16][4] = map(a, to_apply=map_fn)
// }
// ```
//
// After `MapInliningPass`, the `map` node is replaced by an `array` of four
// `invoke` operations:
//
// ```
// fn map_fn(x: bits[32]) -> bits[16] {
//   ret bit_slice.1: bits[16] = bit_slice(x, start=0, width=16)
// }
//
// fn main(a: bits[32][4]) -> bits[16][4] {
//   literal.2: bits[3] = literal(value=0)
//   array_index.3: bits[32] = array_index(a, indices=[literal.2])
//   invoke.4: bits[16] = invoke(array_index.3, to_apply=map_fn)
//   literal.5: bits[3] = literal(value=1)
//   array_index.6: bits[32] = array_index(a, indices=[literal.5])
//   invoke.7: bits[16] = invoke(array_index.6, to_apply=map_fn)
//   literal.8: bits[3] = literal(value=2)
//   array_index.9: bits[32] = array_index(a, indices=[literal.8])
//   invoke.10: bits[16] = invoke(array_index.9, to_apply=map_fn)
//   literal.11: bits[3] = literal(value=3)
//   array_index.12: bits[32] = array_index(a, indices=[literal.11])
//   invoke.13: bits[16] = invoke(array_index.12, to_apply=map_fn)
//   ret array.14: bits[16][4] =
//       array(invoke.4, invoke.7, invoke.10, invoke.13)
// }
// ```
class MapInliningPass : public OptimizationFunctionBasePass {
 public:
  static constexpr std::string_view kName = "map_inlining";
  MapInliningPass();

  RedundancyGuard GetRedundancyGuard(
      const OptimizationPassOptions& options,
      OptimizationContext& context) const override {
    return RedundancyGuard::CanSkip();
  }

  // Inline a single Map instruction. Provided for test and utility
  // (ir_minimizer) use.
  static absl::Status InlineOneMap(Map* map);

 protected:
  absl::StatusOr<bool> RunOnFunctionBaseInternal(
      FunctionBase* function, const OptimizationPassOptions& options,
      PassResults* results, OptimizationContext& context) const override;

  // Replaces a single Map node with a CountedFor operation.
  absl::Status ReplaceMap(Map* map) const;
};

}  // namespace xls

#endif  // XLS_PASSES_MAP_INLINING_PASS_H_
