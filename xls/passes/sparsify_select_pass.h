namespace xls {

// The SparsifySelectPass is a type of range analysis-informed dead code
// elimination that removes cases from selects when range analysis proves that
// they can never occur. It does this by splitting a select into many selects,
// each of which covers a single interval from the selector interval set.
//
// Note: What follows was generated by the Gemini LLM. Not human verified.
//
// The `SparsifySelectPass` uses range analysis to eliminate unreachable cases
// from `select` operations. When the set of possible values that a `select`'s
// selector can take covers fewer points than the number of cases in the
// `select`, this pass replaces the original `select` with a smaller `select`
// (or a chain of `select`s, one per reachable interval) that only indexes into
// the reachable cases.
//
// Here is a detailed breakdown of its operation:
//
// 1.  **Range Analysis**: The pass populates a `PartialInfoQueryEngine` and
//     queries `GetIntervals(select->selector()).Get({})` to obtain the
//     `IntervalSet` of possible values for the selector of each `Select` node.
//
// 2.  **Sparsity Check**: If the total number of values in the `IntervalSet`
//     (`selector_intervals.Size()`) is strictly less than
//     `select->cases().size()`, then at least one case in the `select` is
//     provably unreachable.
//
// 3.  **Splitting into Per-Interval Selects (`SparsifySelect`)**:
//     *   `IntervalsSortedBySize` sorts the convex intervals in
//         `selector_intervals` from smallest to largest (breaking ties by
//         interval order).
//     *   For each reachable `Interval` `[lower, upper]`, the pass collects the
//         corresponding slice of cases from the original `select` (using
//         `select->default_value()` for indices `>= select->cases().size()`, or
//         skipping the interval if it lies entirely past the end of `cases()`
//         and no `default_value` is present).
//     *   It constructs an inner `select` for the interval:
//         `if_in_range = sel(sub(selector, lower), cases=cases_in_range,
//         default=0)`.
//     *   For the first interval processed (`is_leaf == true`), `if_in_range`
//         is used directly without a range-check comparator (if the selector
//         falls in no other interval, it must fall in this leaf interval).
//     *   For each subsequent interval (`is_leaf == false`), the pass checks
//         whether `selector` lies in `[lower, upper]` via
//         `and(uge(selector, lower), ule(selector, upper))` and wraps the
//         previously constructed select chain (`other`) in a 2-way `select`:
//         `sel(in_bounds, cases=[other, if_in_range])`.
//
// Example:
// Consider a `select` operation where the selector `add.3` is a `bits[4]`
// value proven by range analysis to lie in the single interval `[8, 11]`:
//
// ```
// // Original IR snippet
// fn func(x: bits[2]) -> bits[4] {
//   zero_ext.1: bits[4] = zero_ext(x, new_bit_count=4)
//   literal.2: bits[4] = literal(value=8)
//   add.3: bits[4] = add(zero_ext.1, literal.2)
//   // 16 cases (literal.4 through literal.19) for selector values 0..15:
//   ret sel.20: bits[4] = sel(add.3, cases=[
//     literal.4, literal.5, literal.6, literal.7, literal.8, literal.9,
//     literal.10, literal.11, literal.12, literal.13, literal.14,
//     literal.15, literal.16, literal.17, literal.18, literal.19
//   ])
// }
// ```
//
// Because `add.3` only takes values in `[8, 11]`, `SparsifySelectPass` replaces
// the 16-way `sel.20` with a 4-case `select` offset by the interval lower bound
// (`8`):
//
// ```
// // Optimized IR snippet
// fn func(x: bits[2]) -> bits[4] {
//   zero_ext.1: bits[4] = zero_ext(x, new_bit_count=4)
//   literal.2: bits[4] = literal(value=8)
//   add.3: bits[4] = add(zero_ext.1, literal.2)
//   lower_bound: bits[4] = literal(value=8)
//   offset: bits[4] = sub(add.3, lower_bound)
//   zero: bits[4] = literal(value=0)
//   ret sel.21: bits[4] = sel(offset,
//       cases=[literal.12, literal.13, literal.14, literal.15],
//       default=zero)
// }
// ```
//
// If the selector's `IntervalSet` contains multiple disjoint intervals, the
// first (smallest) interval forms the leaf `select`, and each subsequent
// interval wraps it in `sel(and(uge(selector, lower), ule(selector, upper)),
// cases=[previous_chain, interval_select])`.
class SparsifySelectPass : public OptimizationFunctionBasePass {
 public:
  static constexpr std::string_view kName = "sparsify_select";
  SparsifySelectPass()
      : OptimizationFunctionBasePass(kName, "Sparsify Select") {}
  ~SparsifySelectPass() override = default;

  RedundancyGuard GetRedundancyGuard(
      const OptimizationPassOptions& options,
      OptimizationContext& context) const override {
    return RedundancyGuard::CanSkip();
  }

 protected:
  // Sparsify selects using range analysis.
  absl::StatusOr<bool> RunOnFunctionBaseInternal(
      FunctionBase* f, const OptimizationPassOptions& options,
      PassResults* results, OptimizationContext& context) const override;
};

}  // namespace xls

#endif  // XLS_PASSES_SPARSIFY_SELECT_PASS_H_
