namespace xls {

// Pass which tries to minimize the size of the proc state by narrowing state
// elements using range analysis.
//
// Note: What follows was generated by the Gemini LLM. Not human verified.
//
// `ProcStateNarrowingPass` reduces the bit width of `bits`-typed
// `StateElement`s in a `Proc` by analyzing how state values evolve across ticks
// using `ProcStateRangeQueryEngine`. Narrowing state elements directly reduces
// the number of flip-flops required in synthesized hardware.
//
// ### How It Works
//
// The pass populates a `ProcStateRangeQueryEngine` on the `Proc` (which tracks
// both per-bit ternary knowledge and value intervals across proc back-edges)
// and inspects each `bits`-typed `StateElement`:
//
// 1. **Removing Known Leading Bits (`RemoveLeadingBits` /
//    `ProcStateConcatNarrowTransform`)**:
//    * Computes the intersection (`ternary_ops::Intersection`) of the ternary
//      vectors across all `StateRead` nodes for the state element.
//    * Counts the number of leading (most significant) bits whose values are
//      known constants (`CountLeadingOnes` on `ToKnownBits`). Note that these
//      known leading bits can be any fixed bit pattern (zeros, ones, or a mix).
//    * If `known_leading > 0`, the state element is narrowed by slicing off the
//      top `known_leading` bits from its `initial_value` and from each
//      `next_value` (`bit_slice(next_val, start=0, width=new_width)`). Each
//      `StateRead` is reconstructed to the original width via
//      `concat(literal(leading_bits), new_state_read)`.
//
//    Example (removing known leading bits):
//
//    ```
//    // Before
//    proc my_proc(foo: bits[32], init={0}) {
//      foo_read: bits[32] = state_read(state_element=foo)
//      low_3: bits[3] = bit_slice(foo_read, start=0, width=3)
//      inc: bits[3] = add(low_3, literal(value=1, bits=3))
//      next_foo: bits[32] = zero_ext(inc, new_bit_count=32)
//      next_value(param=foo, value=next_foo)
//    }
//
//    // After
//    proc my_proc(foo: bits[3], init={0}) {
//      foo_read: bits[3] = state_read(state_element=foo)
//      leading_bits_foo: bits[29] = literal(value=0)
//      extended_foo: bits[32] = concat(leading_bits_foo, foo_read)
//      low_3: bits[3] = bit_slice(extended_foo, start=0, width=3)
//      inc: bits[3] = add(low_3, literal(value=1, bits=3))
//      next_foo: bits[32] = zero_ext(inc, new_bit_count=32)
//      unexpand: bits[3] = bit_slice(next_foo, start=0, width=3)
//      next_value(param=foo, value=unexpand)
//    }
//    ```
//
// 2. **Signed Range Narrowing (`RemoveSignBits` /
//    `ProcStateSignExtendNarrowTransform`)**:
//    * If no leading bits are constant (`known_leading == 0`), the pass queries
//      `qe.GetIntervals(state_read)` for each `StateRead` of the state element
//      and computes `interval_ops::MinimumSignedBitCount` (taking the maximum
//      required signed width `max_signed_bits` across all reads).
//    * If `max_signed_bits` is smaller than the state element's bit width, the
//      state element is narrowed to `max_signed_bits` bits: its `initial_value`
//      and `next_value` operands are truncated with `bit_slice(..., start=0,
//      width=max_signed_bits)`, and each `StateRead` is reconstructed to the
//      original width via `sign_ext(new_state_read, new_bit_count=old_width)`.
//
//    Example (signed range narrowing for a state element bounded in `[-8, 7]`):
//
//    ```
//    // Before
//    proc my_proc(bar: bits[32], init={0}) {
//      bar_read: bits[32] = state_read(state_element=bar)
//      // ... next_bar proven by ProcStateRangeQueryEngine to stay in [-8, 7]
//      next_value(param=bar, value=next_bar)
//    }
//
//    // After
//    proc my_proc(bar: bits[4], init={0}) {
//      bar_read: bits[4] = state_read(state_element=bar)
//      extended_bar: bits[32] = sign_ext(bar_read, new_bit_count=32)
//      // ... next_bar computed using extended_bar ...
//      unexpand: bits[4] = bit_slice(next_bar, start=0, width=4)
//      next_value(param=bar, value=unexpand)
//    }
//    ```
class ProcStateNarrowingPass : public OptimizationProcPass {
 public:
  static constexpr std::string_view kName = "proc_state_narrow";
  ProcStateNarrowingPass()
      : OptimizationProcPass(kName, "Proc State Narrowing") {}
  ~ProcStateNarrowingPass() override = default;

  RedundancyGuard GetRedundancyGuard(
      const OptimizationPassOptions& options,
      OptimizationContext& context) const override {
    return RedundancyGuard::CanSkip();
  }

 protected:
  absl::StatusOr<bool> RunOnProcInternal(
      Proc* proc, const OptimizationPassOptions& options, PassResults* results,
      OptimizationContext& context) const override;
};

}  // namespace xls

#endif  // XLS_PASSES_PROC_STATE_NARROWING_PASS_H_
