#ifndef XLS_PASSES_DCE_PASS_H_
#define XLS_PASSES_DCE_PASS_H_

#include <string_view>

#include "absl/status/statusor.h"
#include "xls/ir/function_base.h"
#include "xls/passes/optimization_pass.h"
#include "xls/passes/pass_base.h"

namespace xls {

// class DeadCodeEliminationPass removes dead nodes from a FunctionBase by
// starting from unused deletable nodes and iteratively removing them and any
// operands that become unused.
//
// Note: What follows was generated by the Gemini LLM. Not human verified.
//
// The `DeadCodeEliminationPass` (DCE) is a fundamental optimization pass in XLS
// that removes "dead" or unused nodes from a `FunctionBase` (a function, proc,
// or block). Dead code refers to any operation whose result has no consumers
// and is not required for its observable outputs or side effects. Removing
// dead code simplifies the IR graph, reduces synthesized hardware area, and
// speeds up subsequent optimization passes.
//
// **How it Works**:
//
// Rather than marking live nodes from roots, the pass uses a bottom-up
// worklist algorithm starting from nodes that already have zero users:
//
// 1.  **Deletability Criterion (`is_deletable`)**: A node `n` is eligible for
//     deletion if all of the following hold:
//     *   **No Implicit Uses**: `!n->function_base()->HasImplicitUse(n)` (for
//         example, a function's return value node or a legacy proc's next-state
//         node has an implicit use and cannot be deleted).
//     *   **Not an `invoke`**: `!n->Is<Invoke>()`. Invoked functions are
//         conservatively preserved by DCE because they may contain
//         side-effecting operations; `InliningPass` is responsible for
//         eliminating `invoke` nodes.
//     *   **Not Side-Effecting (Except `gate`)**:
//         `!OpIsSideEffecting(n->op()) || n->Is<Gate>()`. Side-effecting nodes
//         such as `assert`, `cover`, `trace`, `send`, `receive`, `next_value`,
//         `register_write`, `instantiation_input`, `output_port`, and `param`
//         are preserved even when they have no explicit users. `gate` is
//         specially exempted so unused gated values can be eliminated. (Gate is
//         considered side-effecting so it can force itself into the verilog
//         output.)
//
// 2.  **Worklist Initialization**: The pass scans `f->nodes()` and seeds a FIFO
//     worklist (`std::deque<Node*>`) with every node `n` where
//     `n->users().empty()` and `is_deletable(n)` is true.
//
// 3.  **Iterative Removal**: While the worklist is non-empty, the pass pops a
//     node from the front of the queue:
//     *   It inspects each unique operand of the node (using `ForEachUnique` so
//         an operand referenced multiple times by the same node is only checked
//         once). If an operand is only used by this node
//         (`HasSingleUse(operand)`) and satisfies `is_deletable(operand)`, that
//         operand will become userless once the current node is removed, so it
//         is pushed onto the worklist.
//     *   The current node is removed from the `FunctionBase` via
//         `f->RemoveNode(node)`.
//
// 4.  **Optimization Context Garbage Collection**: If any nodes were removed
//     during the pass, `context.CollectGarbage()` is called to clean up cached
//     query engine and analysis state associated with the deleted nodes.
//
// **Example**:
//
// Consider a function with dead intermediate operations:
//
// ```
// // Original IR snippet
// fn some_dead_code(x: bits[42], y: bits[42]) -> bits[42] {
//   neg.1: bits[42] = neg(x)
//   add.2: bits[42] = add(x, y)      // Only used by dead node neg.3
//   neg.3: bits[42] = neg(add.2)     // Dead: zero users
//   ret sub.4: bits[42] = sub(neg.1, y)
// }
// ```
//
// `DeadCodeEliminationPass` executes as follows:
// 1.  Initial scan finds `neg.3` has zero users and is deletable, so the
//     worklist is initialized to `[neg.3]`. (`sub.4` has zero explicit users
//     but is the function return value, so `HasImplicitUse(sub.4)` is true.)
// 2.  `neg.3` is popped. Its unique operand `add.2` has a single use (`neg.3`)
//     and is deletable, so `add.2` is added to the worklist. `neg.3` is
//     removed.
// 3.  `add.2` is popped. Its operands `x` and `y` still have other uses (and
//     are `param` nodes), so neither is added to the worklist. `add.2` is
//     removed.
//
// The resulting IR is:
//
// ```
// // Optimized IR (after DCE)
// fn some_dead_code(x: bits[42], y: bits[42]) -> bits[42] {
//   neg.1: bits[42] = neg(x)
//   ret sub.4: bits[42] = sub(neg.1, y)
// }
// ```
class DeadCodeEliminationPass : public OptimizationFunctionBasePass {
 public:
  static constexpr std::string_view kName = "dce";
  DeadCodeEliminationPass()
      : OptimizationFunctionBasePass(kName, "Dead Code Elimination") {}
  ~DeadCodeEliminationPass() override = default;

  bool IsIdempotent() const override { return true; }

  RedundancyGuard GetRedundancyGuard(
      const OptimizationPassOptions& options,
      OptimizationContext& context) const override {
    return RedundancyGuard::CanSkip();
  }

 protected:
  // Iterate all nodes, mark and eliminate the unvisited nodes.
  absl::StatusOr<bool> RunOnFunctionBaseInternal(
      FunctionBase* f, const OptimizationPassOptions& options,
      PassResults* results, OptimizationContext& context) const override;
};

}  // namespace xls

#endif  // XLS_PASSES_DCE_PASS_H_
