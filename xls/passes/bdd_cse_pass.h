namespace xls {

// Pass which commons equivalent expressions in the graph using binary decision
// diagrams.
//
// Note: What follows was generated by the Gemini LLM. Not human verified.
//
// The `BddCsePass` (BDD-based Common Subexpression Elimination) identifies and
// merges logically equivalent `bits`-typed expressions within a function or
// proc using Binary Decision Diagrams (BDDs). Unlike the purely syntactic
// `CsePass`, `BddCsePass` can detect semantic equivalence across expressions
// with different IR structures by comparing their canonical BDD
// representations.
//
// **How it Works**:
//
// 1.  **Canonical BDD Representation**: The pass queries a shared
//     `BddQueryEngine` to obtain the BDD node index for every bit of each
//     `bits`-typed node in the graph. Because reduced ordered BDDs are
//     canonical for a fixed variable ordering, two nodes compute the same
//     Boolean function on every bit if and only if they have the same bit width
//     and identical BDD node indices for all bit positions.
//
// 2.  **Delay-Aware Topological Ordering (`GetNodeOrder`)**: Before comparing
//     nodes, the pass computes each node's critical-path delay from the graph
//     roots using `GetStandardDelayEstimator()`. Nodes are sorted in
//     monotonically non-decreasing order of critical-path delay, breaking ties
//     by topological sort index. This guarantees a valid topological traversal
//     (preventing cycles) while ensuring that when an earlier node replaces a
//     later node, the replacement never increases the critical-path delay of
//     any path through the graph.
//
// 3.  **Hash Bucketing and Replacement**: The pass iterates through the sorted
//     nodes (skipping non-`bits` nodes and `literal`s) and hashes the vector of
//     per-bit BDD node indices for each node. Nodes with matching hashes are
//     grouped into buckets and compared bit-by-bit (`is_same_value`). When a
//     node matches an earlier candidate in the same bucket, all uses of the
//     node are replaced with the earlier candidate.
//
// **Example**:
// Two syntactically distinct expressions that compute the same Boolean value
// will share the same BDD node and be commoned into a single node:
//
// ```
// // Original IR
// fn compare_twice(x: bits[16]) -> (bits[1], bits[1]) {
//   forty_two: bits[16] = literal(value=42)
//   x_eq_42: bits[1] = eq(x, forty_two)
//   x_ne_42: bits[1] = ne(forty_two, x)
//   not_ne: bits[1] = not(x_ne_42)
//   ret res: (bits[1], bits[1]) = tuple(x_eq_42, not_ne)
// }
//
// // Optimized IR (after BddCsePass and dead code elimination)
// fn compare_twice(x: bits[16]) -> (bits[1], bits[1]) {
//   forty_two: bits[16] = literal(value=42)
//   x_eq_42: bits[1] = eq(x, forty_two)
//   ret res: (bits[1], bits[1]) = tuple(x_eq_42, x_eq_42)
// }
// ```
class BddCsePass : public OptimizationFunctionBasePass {
 public:
  static constexpr std::string_view kName = "bdd_cse";
  explicit BddCsePass()
      : OptimizationFunctionBasePass(
            kName, "BDD-based Common Subexpression Elimination") {}
  ~BddCsePass() override = default;

  RedundancyGuard GetRedundancyGuard(
      const OptimizationPassOptions& options,
      OptimizationContext& context) const override {
    return RedundancyGuard::CanSkip();
  }

 protected:
  absl::StatusOr<bool> RunOnFunctionBaseInternal(
      FunctionBase* f, const OptimizationPassOptions& options,
      PassResults* results, OptimizationContext& context) const override;
};

}  // namespace xls

#endif  // XLS_PASSES_BDD_CSE_PASS_H_
