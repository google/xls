#ifndef XLS_PASSES_PROC_STATE_ARRAY_FLATTENING_PASS_H_
#define XLS_PASSES_PROC_STATE_ARRAY_FLATTENING_PASS_H_

#include <cstdint>
#include <string_view>

#include "absl/status/statusor.h"
#include "xls/ir/proc.h"
#include "xls/passes/optimization_pass.h"
#include "xls/passes/pass_base.h"

namespace xls {

// Pass which flattens array elements of the proc state into their constituent
// elements. Tuples are flattened in a different pass. Flattening improves
// optimizability because each state element can be considered and transformed
// in isolation. Flattening also gives the scheduler more flexibility; without
// flattening, each element in the aggregate must have the same lifetime.
//
// Note: What follows was generated by the Gemini LLM. Not human verified.
//
// `ProcStateArrayFlatteningPass` converts small array-typed `StateElement`s in
// a `Proc` into tuple-typed `StateElement`s of their constituent elements,
// relying on a subsequent `ProcStateTupleFlatteningPass` to decompose those
// tuples into independent state elements.
//
// Breaking array state elements apart allows downstream passes (such as state
// narrowing, constant propagation, and dead state elimination) to optimize each
// array slot independently, and frees the scheduler from forcing all elements
// of the array to share an identical register lifetime.
//
// ### How It Works
//
// 1. **Flattening Heuristic (`ShouldFlattenStateElement`)**: The pass inspects
//    each array-typed `StateElement` owned by the `Proc` and flattens it if its
//    array size is at most 2 (`size() <= 2`). (Although `kMaxArrayFlattenSize`
//    is defined on the class, the current implementation only flattens arrays
//    of length 2 or smaller.)
// 2. **State Element Conversion (`ArrayToTupleStateTransformer`)**: Using
//    `Proc::TransformStateElement`, an array state element of type `T[N]` with
//    initial value `[v_0, ..., v_{N-1}]` is replaced by a tuple state element
//    of type `(T, ..., T)` with initial value `(v_0, ..., v_{N-1})`:
//    * **Transforming `StateRead`s**: Uses of the old array `StateRead` are
//      replaced with an `array` node (`<old_state_read>_as_array`) constructed
//      from `tuple_index(new_state_read, i)` for `i = 0 .. N-1`.
//    * **Transforming `Next` Values**: For each `next_value` targeting the
//      state element, its array-typed `value` operand `v` is converted into a
//      `tuple` node (`<v>_as_tuple`) whose elements are extracted via
//      `array_index(v, indices=[literal(i)])` (using index bit width
//      `max(1, CeilOfLog2(N))`).
// 3. **Cleanup**: The old `next_value` nodes and the original array-typed
//    `StateElement` are removed from the `Proc`.
//
// ### Example
//
// ```
// // Before
// proc my_proc(s: bits[8][2], init={[0, 1]}) {
//   s_read: bits[8][2] = state_read(state_element=s)
//   idx0: bits[1] = literal(value=0)
//   elem0: bits[8] = array_index(s_read, indices=[idx0])
//   next_arr: bits[8][2] = array(elem0, literal(value=2, bits=8))
//   next_value(param=s, value=next_arr)
// }
// ```
//
// After `ProcStateArrayFlatteningPass`:
//
// ```
// // After
// proc my_proc(s: (bits[8], bits[8]), init={(0, 1)}) {
//   s_read: (bits[8], bits[8]) = state_read(state_element=s)
//   e0: bits[8] = tuple_index(s_read, index=0)
//   e1: bits[8] = tuple_index(s_read, index=1)
//   s_read_as_array: bits[8][2] = array(e0, e1)
//   idx0: bits[1] = literal(value=0)
//   elem0: bits[8] = array_index(s_read_as_array, indices=[idx0])
//   next_arr: bits[8][2] = array(elem0, literal(value=2, bits=8))
//   n0: bits[8] = array_index(next_arr, indices=[literal(value=0, bits=1)])
//   n1: bits[8] = array_index(next_arr, indices=[literal(value=1, bits=1)])
//   next_arr_as_tuple: (bits[8], bits[8]) = tuple(n0, n1)
//   next_value(param=s, value=next_arr_as_tuple)
// }
// ```
//
// Subsequent `ArraySimplificationPass`, `TupleSimplificationPass`, and
// `ProcStateTupleFlatteningPass` passes then eliminate the intermediate array
// and tuple reconstructions and split `s` into two scalar `bits[8]` state
// elements.
class ProcStateArrayFlatteningPass : public OptimizationProcPass {
 public:
  static constexpr std::string_view kName = "proc_state_array_flat";

  // Array simplification can flatten proc state arrays into elements. This is
  // the maximum length of an array it will flatten.
  static constexpr int64_t kMaxArrayFlattenSize = 4096;

  ProcStateArrayFlatteningPass()
      : OptimizationProcPass(kName, "Proc State Array Flattening") {}
  ~ProcStateArrayFlatteningPass() override = default;

  RedundancyGuard GetRedundancyGuard(
      const OptimizationPassOptions& options,
      OptimizationContext& context) const override {
    return RedundancyGuard::CanSkip();
  }

 protected:
  absl::StatusOr<bool> RunOnProcInternal(
      Proc* proc, const OptimizationPassOptions& options, PassResults* results,
      OptimizationContext& context) const override;
};

}  // namespace xls

#endif  // XLS_PASSES_PROC_STATE_ARRAY_FLATTENING_PASS_H_
