namespace xls {

// Simplifies logical operations on the results of comparison
// operations. For example:
//
//   eq(x, 0) && ne(x, 1) => eq(x, 0)
//   eq(x, 0) && ne(x, 0) => 0
//   eq(x, 0) || ne(x, 0) => 1
//
// Note: What follows was generated by the Gemini LLM. Not human verified.
//
// The `ComparisonSimplificationPass` simplifies comparisons and Boolean logic
// trees over comparisons across three stages in a topological traversal:
//
// 1.  **Range-Equivalence Simplification (`ComputeRangeEquivalence`)**:
//     *   Using a `StatelessQueryEngine`, the pass maps 1-bit nodes to a
//         `RangeEquivalence{node, IntervalSet}`, indicating that the 1-bit node
//         evaluates to `1` if and only if `node` lies within `IntervalSet`.
//     *   Base intervals are seeded from comparisons against known constants
//         (`eq`, `ne`, `ult`, `ugt`) and propagated through `and`, `or`, `not`,
//         `nand`, and `nor` operations whose operands all constrain the same
//         underlying `node` (using interval intersection, union, and
//         complement).
//     *   Each node with a computed `RangeEquivalence{x, range}` is simplified
//         based on its normalized `IntervalSet` (skipping nodes that are
//         already in minimal comparison form or that are single `not`
//         inversions of multi-use comparisons):
//         *   **Maximal range**: Replaced with `literal(1)`.
//         *   **Empty range**: Replaced with `literal(0)`.
//         *   **Single value `[C, C]`**: Replaced with `eq(x, C)`.
//         *   **Complement of a single value `C`**: Replaced with `ne(x, C)`.
//         *   **Contiguous prefix `[0, C - 1]`**: Replaced with `ult(x, C)`.
//         *   **Contiguous suffix `[C + 1, MAX]`**: Replaced with `ugt(x, C)`.
//
// 2.  **Removing Non-Wrapping Unit Offsets
//     (`SimplifyComparisonWithUnitOffset`)**:
//     *   Rewrites ordered signed and unsigned comparisons (`ult`, `ule`,
//         `ugt`, `uge`, `slt`, `sle`, `sgt`, `sge`) where one operand adds or
//         subtracts `1` (`+ 1` or `- 1`), toggling strictness to eliminate the
//         offset when `PartialInfoQueryEngine` proves the base operand cannot
//         take on the wrapping boundary value (`MAX` for `+ 1`, `MIN` for
//         `- 1`):
//         *   `a < b + 1` => `a <= b`
//         *   `a >= b + 1` => `a > b`
//         *   `a <= b - 1` => `a < b`
//         *   `a > b - 1` => `a >= b`
//
// 3.  **Deduplicating Derived Comparisons (`TransformDerivedComparisons`)**:
//     *   Scans comparisons in topological order and reuses an earlier
//         comparison (`a cmp b`) when a later comparison is:
//         *   **Commuted** (e.g., `ult(b, a)` becomes `ugt(a, b)`).
//         *   **Inverted** (e.g., `ule(a, b)` becomes `not(ugt(a, b))`).
//         *   **Commuted and inverted** (e.g., `uge(b, a)` becomes
//             `not(ugt(a, b))`).
//
// Example (`eq(x, 0) && ne(x, 1)`):
//
// ```
// fn f(x: bits[32]) -> bits[1] {
//   literal.0: bits[32] = literal(value=0)
//   literal.1: bits[32] = literal(value=1)
//   x_eq_0: bits[1] = eq(x, literal.0)
//   x_ne_1: bits[1] = ne(x, literal.1)
//   ret and.final: bits[1] = and(x_eq_0, x_ne_1)
// }
// ```
//
// `ComputeRangeEquivalence` maps `x_eq_0` to `[[0, 0]]` and `x_ne_1` to
// `[[0, 0], [2, MAX]]`. Their intersection at `and.final` is `[[0, 0]]`, so
// `and.final` is replaced with a single equality comparison (shown after dead
// code elimination):
//
// ```
// fn f(x: bits[32]) -> bits[1] {
//   literal.0: bits[32] = literal(value=0)
//   ret eq.final: bits[1] = eq(x, literal.0)
// }
// ```
class ComparisonSimplificationPass : public OptimizationFunctionBasePass {
 public:
  static constexpr std::string_view kName = "comparison_simp";
  ComparisonSimplificationPass()
      : OptimizationFunctionBasePass(kName, "Comparison Simplification") {}
  ~ComparisonSimplificationPass() override = default;

  RedundancyGuard GetRedundancyGuard(
      const OptimizationPassOptions& options,
      OptimizationContext& context) const override {
    return RedundancyGuard::CanSkip();
  }

 protected:
  absl::StatusOr<bool> RunOnFunctionBaseInternal(
      FunctionBase* f, const OptimizationPassOptions& options,
      PassResults* results, OptimizationContext& context) const override;
};

}  // namespace xls

#endif  // XLS_PASSES_COMPARISON_SIMPLIFICATION_PASS_H_
