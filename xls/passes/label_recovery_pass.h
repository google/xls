#ifndef XLS_PASSES_LABEL_RECOVERY_PASS_H_
#define XLS_PASSES_LABEL_RECOVERY_PASS_H_

#include <string_view>

#include "absl/status/statusor.h"
#include "xls/ir/function_base.h"
#include "xls/passes/optimization_pass.h"
#include "xls/passes/pass_base.h"

namespace xls {

// At the end of the pass pipeline (when inlining and optimizations have been
// performed) attempts to recover original names for coverpoints and assertions
// to whatever degree possible so they're more human-readable -- we mangle them
// for inlining to ensure they're unique, but often those names are way
// overqualified.
//
// Note: What follows was generated by the Gemini LLM. Not human verified.
//
// The `LabelRecoveryPass` restores human-readable user-defined labels on
// `cover` and `assert` nodes after function inlining and subsequent
// optimizations have completed. During `InliningPass`, `cover` and `assert`
// labels are prefixed with caller, inline-count, and callee identifiers (e.g.,
// `<caller>_<inline_count>_<callee>_<label>`) while preserving the pre-inlined
// name in the node's `original_label` attribute. This avoids duplicate property
// names in generated Verilog when a function is inlined multiple times, but can
// leave overly verbose labels when only a single instance survives.
//
// **How it Works**:
//
// 1.  **Grouping by `original_label`**: The pass scans all nodes in the
//     `FunctionBase` and collects every `cover` (`Op::kCover`) and `assert`
//     (`Op::kAssert`) node that has an `original_label` attribute into a map
//     keyed by `original_label` (`original_label_to_nodes`). Note that `cover`
//     and `assert` nodes share the same collision map.
//
// 2.  **Collision-Free Restoration**: For each `original_label` in the map:
//     *   **Unique Instance (`nodes.size() == 1`)**: If only a single `cover`
//         or `assert` node in the `FunctionBase` has that `original_label`,
//         restoring it cannot cause a label collision. The pass updates the
//         node's active label via `set_label(original_label)`.
//     *   **Multiple Instances (`nodes.size() > 1`)**: If multiple inlined
//         nodes share the same `original_label`, their mangled labels are kept
//         unchanged so each instance retains a unique identifier.
//
// **Example**:
//
// Consider a `callee` function with a `cover` point that is invoked once by
// `caller`:
//
// ```
// // IR after InliningPass and DCE (before LabelRecoveryPass)
// package p
//
// top fn caller(p: bits[1]) -> () {
//   ret cover.1: () = cover(p, label="caller_0_callee_my_cover_label",
//                              original_label="my_cover_label")
// }
// ```
//
// Because `cover.1` is the only node in `caller` with
// `original_label="my_cover_label"`, `LabelRecoveryPass` restores its label:
//
// ```
// // IR after LabelRecoveryPass
// package p
//
// top fn caller(p: bits[1]) -> () {
//   ret cover.1: () = cover(p, label="my_cover_label",
//                              original_label="my_cover_label")
// }
// ```
class LabelRecoveryPass : public OptimizationFunctionBasePass {
 public:
  static constexpr std::string_view kName = "label-recovery";
  LabelRecoveryPass() : OptimizationFunctionBasePass(kName, "LabelRecovery") {}
  ~LabelRecoveryPass() override = default;

  RedundancyGuard GetRedundancyGuard(
      const OptimizationPassOptions& options,
      OptimizationContext& context) const override {
    return RedundancyGuard::CanSkip();
  }

 protected:
  absl::StatusOr<bool> RunOnFunctionBaseInternal(
      FunctionBase* f, const OptimizationPassOptions& options,
      PassResults* results, OptimizationContext& context) const override;
};

}  // namespace xls

#endif  // XLS_PASSES_LABEL_RECOVERY_PASS_H_
