#ifndef XLS_PASSES_CONCAT_SELECT_REMOVAL_PASS_H_
#define XLS_PASSES_CONCAT_SELECT_REMOVAL_PASS_H_

#include <string_view>

#include "absl/status/statusor.h"
#include "xls/ir/function_base.h"
#include "xls/passes/optimization_pass.h"
#include "xls/passes/pass_base.h"
namespace xls {

// Replaces a concat of selects with the same selectors with a single select of
// concats. This seems to be optimized better by synthesis tools.
//
// For example,
//   (concat (select a b c)  (select a d e))
// would be replaced with
//   (select a (concat b d) (concat c e))
//
// Or
//   (concat X (select a b c) (select a d e) Y)
// would be replaced with
//   (Concat X (select a (concat b d) (concat c e)) Y)
//
// We will not add additional bit-slices to support things like
//   (concat (select a b c) X (select a d e))
// TODO(allight): Should we do this?
//
// Nor will we combine selects with unlike selectors.
//   (concat (select a b c) (select d e f))
//
// Note: What follows was generated by the Gemini LLM. Not human verified.
//
// The `ConcatSelectRemovalPass` hoists select operations (`sel`,
// `priority_sel`, and `one_hot_sel`, represented uniformly via `GenericSelect`)
// above `concat` operations when adjacent operands of a `concat` share the
// same select kind and selector. Combining narrow parallel selects with
// identical control into a single wider select over concatenated data branches
// reduces control fanout and improves synthesis quality.
//
// **How it Works**:
//
// 1.  **Identifying Mergeable Runs (`FindConcatSelects`, `CanMerge`,
//     `PickTransform`)**:
//     *   The pass traverses nodes in topological order and inspects each
//         `concat` operation using a `StatelessQueryEngine`.
//     *   Adjacent `concat` operands that are select operations can be merged
//         (`CanMerge`) if:
//         *   They have the same `GenericSelect` kind (`sel`, `priority_sel`,
//             or `one_hot_sel`).
//         *   Their selectors are provably equal via
//             `NodesKnownUnsignedEquals(a.selector(), b.selector())`.
//         *   In scheduled functions (`IsScheduled()`), both select nodes are
//             staged (`IsStaged()`) and belong to the same pipeline stage
//             (`GetStageIndex`).
//     *   Contiguous runs of 2 or more compatible selects within a `concat`'s
//         operands are grouped for merging, while non-select operands (or
//         single unmerged selects) are preserved in place.
//
// 2.  **Rewriting to Select of Concats (`TransformToSelectOfConcats`,
//     `DoTransform`)**:
//     *   For each mergeable run of selects, the pass determines the maximum
//         number of explicit `cases` (and whether a `default` value is needed)
//         from the select in the run with the most explicit cases.
//     *   For each case index `i` (and for the `default` branch, if present),
//         it collects the `i`-th case from every select in the run (using a
//         select's `default_value` when `i >= select.cases().size()`) and
//         concatenates them into a new `concat` node.
//     *   It creates a single merged select (`CloneSelectLike`) choosing among
//         the per-case `concat` nodes. If the function is scheduled, all new
//         `concat` nodes and the merged select are added to the original stage
//         (`AddNodeToStage`).
//     *   If all operands of the original `concat` were merged into a single
//         select, the `concat` is replaced directly by that select; otherwise,
//         it is replaced by an outer `concat` combining the unmerged operands
//         and the newly merged select(s).
//
// Example:
//
// ```
// fn f(s: bits[1], a: bits[4], b: bits[4],
//      c: bits[8], d: bits[8]) -> bits[12] {
//   sel_hi: bits[4] = sel(s, cases=[a, b])
//   sel_lo: bits[8] = sel(s, cases=[c, d])
//   ret result: bits[12] = concat(sel_hi, sel_lo)
// }
// ```
//
// becomes:
//
// ```
// fn f(s: bits[1], a: bits[4], b: bits[4],
//      c: bits[8], d: bits[8]) -> bits[12] {
//   case_0: bits[12] = concat(a, c)
//   case_1: bits[12] = concat(b, d)
//   ret result: bits[12] = sel(s, cases=[case_0, case_1])
// }
// ```
class ConcatSelectRemovalPass : public OptimizationFunctionBasePass {
 public:
  static constexpr std::string_view kName = "concat_select_removal";
  ConcatSelectRemovalPass()
      : OptimizationFunctionBasePass(kName, "Concat Select Removal") {}
  ~ConcatSelectRemovalPass() override = default;

 protected:
  absl::StatusOr<bool> RunOnFunctionBaseInternal(
      FunctionBase* f, const OptimizationPassOptions& options,
      PassResults* results, OptimizationContext& context) const override;
};

}  // namespace xls

#endif  // XLS_PASSES_CONCAT_SELECT_REMOVAL_PASS_H_
