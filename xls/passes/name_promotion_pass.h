#ifndef XLS_PASSES_NAME_PROMOTION_PASS_H_
#define XLS_PASSES_NAME_PROMOTION_PASS_H_

#include <string_view>

#include "absl/status/statusor.h"
#include "xls/ir/function_base.h"
#include "xls/passes/optimization_pass.h"
#include "xls/passes/pass_base.h"

namespace xls {

// Promotes nodes whose assigned names were uniquified by the `NameUniquer`
// back to their originally requested names if those names have since become
// available (for example, because the colliding node was removed by dead code
// elimination).
//
// Note: What follows was generated by the Gemini LLM. Not human verified.
//
// When multiple nodes in a `FunctionBase` request the same name `foo`, the
// `NameUniquer` assigns `foo` to the first node and uniquified names such as
// `foo__1`, `foo__2`, etc. to subsequent nodes, while recording that their
// originally requested name was `foo`. During optimization, the original node
// named `foo` (or an intermediate node in a collision chain) is often replaced
// or deleted by dead code elimination (`DeadCodeEliminationPass`), releasing
// `foo` in the `FunctionBase`'s `NameUniquer`.
//
// `NamePromotionPass` scans the nodes of a `FunctionBase` and promotes any
// eligible node whose originally requested name is now free back to that
// original name. The pass iterates to a fixed point so that cascading
// promotions (e.g., promoting `foo__1` to `foo` frees `foo__1` for a node that
// originally requested `foo__1` and received `foo__2`) are resolved in a single
// pass invocation. Parameter and port nodes are never renamed.
class NamePromotionPass : public OptimizationFunctionBasePass {
 public:
  static constexpr std::string_view kName = "name_promotion";
  NamePromotionPass() : OptimizationFunctionBasePass(kName, "Name Promotion") {}
  ~NamePromotionPass() override = default;

  bool IsIdempotent() const override { return true; }

  RedundancyGuard GetRedundancyGuard(
      const OptimizationPassOptions& options,
      OptimizationContext& context) const override {
    return RedundancyGuard::CanSkip();
  }

 protected:
  absl::StatusOr<bool> RunOnFunctionBaseInternal(
      FunctionBase* f, const OptimizationPassOptions& options,
      PassResults* results, OptimizationContext& context) const override;
};

}  // namespace xls

#endif  // XLS_PASSES_NAME_PROMOTION_PASS_H_
