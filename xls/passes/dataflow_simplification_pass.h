#ifndef XLS_PASSES_DATAFLOW_SIMPLIFICATION_PASS_H_
#define XLS_PASSES_DATAFLOW_SIMPLIFICATION_PASS_H_

#include <string_view>

#include "absl/status/statusor.h"
#include "xls/ir/function_base.h"
#include "xls/passes/optimization_pass.h"
#include "xls/passes/pass_base.h"

namespace xls {

// An optimization which uses a lattice-based dataflow analysis to find
// equivalent nodes in the graph and replace them with a simpler form. The
// analysis traces through tuples, arrays, and select operations. Optimizations
// which can be performed by this pass:
//
//    tuple_index(tuple(x, y), index=1)  =>  y
//
//    select(selector, {z, z})  =>  z
//
//    array_index(array_update(A, x, index={42}), index={42})  =>  x
//
// Note: What follows was generated by the Gemini LLM. Not human verified.
//
// The `DataflowSimplificationPass` uses a lattice-based dataflow analysis
// (`NodeSourceDataflowVisitor`, built on `DataflowVisitor<NodeSource>`) to
// track the origin of every leaf element (tuple fields, array elements, and
// leaf `bits` or `token` values) through structural and control-flow operations
// (`tuple`, `tuple_index`, `array`, `array_index`, `array_slice`,
// `array_update`, `array_concat`, `identity`, `sel`, `priority_sel`, and
// `one_hot_sel`). Nodes whose leaf elements originate from the exact same
// sources are replaced with earlier equivalent nodes or reconstructed directly
// from existing element nodes.
//
// **How it Works**:
//
// 1.  **Leaf-Level Source Analysis (`NodeSourceDataflowVisitor`)**:
//     *   The pass traverses the function in topological order and computes a
//         `LeafTypeTree<NodeSource>` for every node.
//     *   Each leaf holds a `NodeSource(node, tree_index)` identifying the
//         earliest node and aggregate index path from which that leaf value
//         statically originates.
//     *   When joining branches in select or dynamic array operations
//         (`JoinElements`), if all possible data sources for a leaf element are
//         identical, that common `NodeSource` is preserved; otherwise, the
//         join falls back to the current node (`NodeSource(node, index)`).
//
// 2.  **Replacing Equivalent Nodes via `source_map`**:
//     *   During a topological walk, the pass inserts each node's
//         `LeafTypeTreeView<NodeSource>` into `source_map`.
//     *   If a later node has the exact same `LeafTypeTreeView<NodeSource>` as
//         an earlier node in `source_map` (and is not an empty type with zero
//         flat bits and no tokens, which is skipped via `IsEmptyType` to avoid
//         infinite replacement loops between empty-typed nodes), the later node
//         is replaced directly with the earlier node (`ReplaceUsesWith`).
//     *   This single mechanism handles unboxing (`tuple_index(tuple(x, y), 1)`
//         -> `y`), redundant select elimination (`sel(s, cases=[z, z])` ->
//         `z`), forwarding through array updates, and replacing an `array`
//         reconstructed from ordered `array_index` operations of an existing
//         array `a` back with `a`:
//
//         ```
//         // Original:
//         e0: bits[32] = array_index(a, indices=[zero])
//         e1: bits[32] = array_index(a, indices=[one])
//         ret arr: bits[32][2] = array(e0, e1)
//
//         // After optimization (arr has the same NodeSource tree as 'a'):
//         ret a: bits[32][2] = param(name=a)
//         ```
//
// 3.  **Materializing Arrays from Existing Element Nodes
//     (`MaybeReplaceWithArrayOfExistingNodes`)**:
//     *   If an array-typed node is not already in `source_map` (and is not a
//         `literal`, `array`, `array_index`, or empty type—avoiding `array` and
//         `array_index` prevents infinite loops with
//         `ArraySimplificationPass`), the pass checks whether the `NodeSource`
//         view for every element `0..size-1` of the array is already present as
//         a standalone node in `source_map`.
//     *   If all element sources exist in `source_map`, the operation (such as
//         a chain of `array_update`s, an `array_concat`, or an `array_slice`)
//         is replaced with a direct `array(e_0, e_1, ..., e_{n-1})` node.
class DataflowSimplificationPass : public OptimizationFunctionBasePass {
 public:
  static constexpr std::string_view kName = "dataflow";
  explicit DataflowSimplificationPass()
      : OptimizationFunctionBasePass(kName, "Dataflow Optimization") {}

  ~DataflowSimplificationPass() override = default;

  RedundancyGuard GetRedundancyGuard(
      const OptimizationPassOptions& options,
      OptimizationContext& context) const override {
    return RedundancyGuard::CanSkip();
  }

 protected:
  absl::StatusOr<bool> RunOnFunctionBaseInternal(
      FunctionBase* f, const OptimizationPassOptions& options,
      PassResults* results, OptimizationContext& context) const override;
};

}  // namespace xls

#endif  // XLS_PASSES_DATAFLOW_SIMPLIFICATION_PASS_H_
