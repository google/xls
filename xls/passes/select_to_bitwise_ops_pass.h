namespace xls {

// Converts a binary select whose two arms provably differ by a fully-known
// XOR term (e.g. `sel(p, [x, xor(x, c)])`) into an XOR with an AND-masked
// constant: `xor(x, and(sign_ext(p, W), c))`, with `p` complemented when the
// XOR arm is the on-false case. The arms need not literally form
// `xor(base, c)`: per-piece xor-with-constant differences introduced by
// earlier passes (e.g. `concat_simp`) are also recognized. This is the select
// pattern generated by the per-step of an unrolled CRC/shift loop.
//
// This pass is separate from select simplification (and runs at the very end
// of optimization) by design:
//
//  * The rewrite is value-based: it only fires when the query engine can prove
//    the two arms differ by a fully-known constant, unlike the rest of select
//    simplification which reasons about the shape of the select itself.
//  * It deliberately consumes shapes that `concat_simp` produces (wide xor
//    limbs split into per-slice concats). `concat_simp` runs inside the
//    fixed-point "simp" compound, and running this rewrite in the same
//    fixed point would leave the two transforms repeatedly reshaping the same
//    IR instead of converging.
//  * It converts the select into an `and`-masked xor, which value-based
//    analyses reason through less easily, so it is deferred until after those
//    analyses (e.g. conditional specialization) have already run.
//
// Runs only at optimization levels where split-based rewrites are enabled
// (SplitsEnabled).
//
// Note: What follows was generated by the Gemini LLM. Not human verified.
//
// **How it Works**:
//
// 1.  **Eligibility (`GetBinaryMuxArms`)**:
//     The pass only runs when `options.splits_enabled()` is true. It inspects
//     each `Select` and `PrioritySelect` with a 1-bit selector (`p`) and flat
//     bit-vector type (`W >= 1`) in topological order, extracting its
//     `(on_false, on_true)` arms (`cases[0]` and `cases[1]` for `Select`, or
//     `default_value` and `cases[0]` for `PrioritySelect`). If either arm is
//     already known to be all zeros or all ones (`IsZeroOrOnes`), the select is
//     skipped so standard select simplification handles it.
//
// 2.  **Direct and Recursive XOR Delta Matching**:
//     Using a `UnionQueryEngine` combining `StatelessQueryEngine` and
//     `LazyTernaryQueryEngine`, the pass attempts to prove that the two arms
//     differ by a fully known constant `delta` (`on_true ^ on_false == delta`):
//     *   **Direct Match (`MatchXorCase`)**: Checks whether one arm is a binary
//         `xor(base, c)` (or `xor(c, base)`) where `base` is the other arm and
//         `c` is fully known (`query_engine.IsFullyKnown(c)`).
//     *   **Recursive Structural Match (`TryFoldXorDelta`)**: Performs a
//         memoized, depth-bounded (`kMaxXorFoldDepth = 1000`) structural walk
//         over pairs of nodes `(a, b)` of equal bit-width:
//         *   If `a == b`, the XOR delta is `0`.
//         *   If both `a` and `b` are fully known constants, the delta is
//             `*KnownValue(a) ^ *KnownValue(b)`.
//         *   If `a` (or `b`) is a binary `xor` with a fully known operand `c`
//             and variable operand `x`, recurses on `(x, b)` (or `(a, x)`) and
//             XORs the resulting delta with `c`.
//         *   If `a` (or `b`) is `not(x)`, recurses on `(x, b)` (or `(a, x)`)
//             and bitwise-inverts the resulting delta.
//         *   If both `a` and `b` are `concat` trees whose flattened operands
//             (`FlattenConcats`) have pairwise matching bit-widths, recurses on
//             each operand pair and concatenates the piece deltas.
//
// 3.  **Bitwise Lowering**:
//     Once a `base` arm and a non-zero `delta` (`Bits`) are determined (with
//     condition `cond = p` if `base == on_false`, or `cond = not(p)` if
//     `base == on_true`):
//     *   For 1-bit selects (`W == 1`), `delta` is `1` (`on_true ==
//         not(on_false)`), and the pass avoids `sign_ext`/`and` by emitting
//         `xor(on_false, p)` directly (or `not(xor(on_true, p))` when
//         `on_false` is the `not`/`xor` node and `on_true` is the simpler
//         base).
//     *   For wider selects (`W > 1`), the select is replaced with
//         `xor(base, sign_ext(cond, W))` when `delta` is all-ones, or
//         `xor(base, and(sign_ext(cond, W), literal(delta)))` otherwise.
//
// Example:
//
// ```
// // Original IR
// fn crc_step(p: bits[1], x: bits[8]) -> bits[8] {
//   poly: bits[8] = literal(value=0x07)
//   x_xor_poly: bits[8] = xor(x, poly)
//   ret sel.1: bits[8] = sel(p, cases=[x, x_xor_poly])
// }
//
// // Optimized IR
// fn crc_step(p: bits[1], x: bits[8]) -> bits[8] {
//   mask: bits[8] = sign_ext(p, new_bit_count=8)
//   delta: bits[8] = literal(value=0x07)
//   masked_delta: bits[8] = and(mask, delta)
//   ret xor.2: bits[8] = xor(x, masked_delta)
// }
// ```
class SelectToBitwiseOpsPass : public OptimizationFunctionBasePass {
 public:
  static constexpr std::string_view kName = "select_to_bitwise_ops";
  SelectToBitwiseOpsPass()
      : OptimizationFunctionBasePass(kName, "Select to Bitwise Ops") {}
  ~SelectToBitwiseOpsPass() override = default;

 protected:
  absl::StatusOr<bool> RunOnFunctionBaseInternal(
      FunctionBase* f, const OptimizationPassOptions& options,
      PassResults* results, OptimizationContext& context) const override;
};

}  // namespace xls

#endif  // XLS_PASSES_SELECT_TO_BITWISE_OPS_PASS_H_
