namespace xls {

// Candidates for LUT conversion. Only select nodes are supported currently.
struct LutConversionCandidate {
  Node* node;

  // Represents the set of ancestor nodes that have the smallest sum of unknown
  // bits feeding into this candidate node.
  std::vector<Node*> min_cut;
  std::vector<Node*> candidate_users;
  int64_t min_cut_unknown_bits;
};

// Pass which opportunistically converts nodes to lookup tables (selects) where
// we can prove it's beneficial.
//
// Note: What follows was generated by the Gemini LLM. Not human verified.
//
// The `LutConversionPass` absorbs combinational logic feeding the `selector` of
// one or more `select` operations into the `select` operations themselves,
// converting them into direct lookup tables (LUTs) indexed by a smaller or
// simpler cut of ancestor bits.
//
// The pass is gated on `options.narrowing_enabled()` and uses a
// `UnionQueryEngine` combining `StatelessQueryEngine` and a shared
// `LazyTernaryQueryEngine`.
//
// **How it Works**:
//
// 1.  **Candidate Discovery (`ComputeLutConversionCandidates`)**:
//     The pass traverses nodes in reverse topological order
//     (`context.ReverseTopoSort(func)`), skipping dead nodes. For each node
//     that serves as the `selector()` of at least one `Select` user:
//     *   It computes the maximum number of cases (`max_case_count`, counting
//         `default_value` as an extra case if present) across all `Select`
//         users controlled by this selector, and determines the maximum bit
//         width required to index them:
//         `max_bits_needed = Bits::MinBitCountUnsigned(max_case_count - 1)`.
//         Selectors with `max_bits_needed <= 1` are skipped.
//     *   Using `DataflowGraphAnalysis::GetMinCutFor`, it finds a minimum cut
//         (`min_cut`) of ancestor nodes that completely determine the
//         selector's value with at most `max_bits_needed` total unknown bits
//         (`unknown_bits`) according to the ternary query engine.
//     *   It checks whether the selector is already trivially derived from
//         `min_cut` (`IsTriviallyDerived`, meaning constructed only from
//         `min_cut` nodes and literals via `tuple_index`, `bit_slice`,
//         literal-indexed `array_index`, and `concat`).
//     *   Each controlled `Select` user (requiring `bits_needed` selector bits)
//         is kept as a candidate user if either:
//         *   `unknown_bits < bits_needed` (the LUT conversion strictly narrows
//             the `Select`), or
//         *   `unknown_bits == bits_needed && !selector_is_trivial` (the
//             `Select` stays the same width, but non-trivial combinational
//             selector logic is absorbed into the LUT, reducing delay).
//
// 2.  **Truth-Table Evaluation (`ComputeLutSelectCases`)**:
//     *   An `IrInterpreter` is pre-populated with all statically known node
//         values (`query_engine.KnownValue(n)`) in the cone feeding the
//         selector.
//     *   For each node in `min_cut`, all concrete `Value`s compatible with its
//         `TernaryVector` are enumerated (`ternary_ops::AllValues`).
//     *   `MixedRadixIterate` iterates over all combinations of `min_cut`
//         values (with earlier `min_cut` nodes varying fastest, corresponding
//         to lower-order bits of the new selector) and evaluates the original
//         selector node in the `IrInterpreter` to record the sequence of
//         selected case indices (`new_case_sequence`).
//
// 3.  **Merging into Controlled Selects (`MergeLutIntoSelects`)**:
//     *   **Single-Case Fold**: If every combination in `new_case_sequence`
//         selects the exact same case index, each controlled `Select` is
//         replaced directly by that single case node.
//     *   **New `Select` Construction**: Otherwise, for each node in `min_cut`,
//         the pass extracts its unknown bits using `GatherBits`, reverses the
//         pieces so earlier `min_cut` nodes occupy the least-significant bits,
//         and concatenates them into `new_selector`. Each controlled `Select`
//         is then replaced with a new `Select(new_selector, new_cases,
//         /*default_value=*/std::nullopt)` whose cases are permuted/selected
//         from the original `Select` according to `new_case_sequence`.
//
// **Example**:
//
// Consider a `select` whose selector `doubled_x` is a non-trivial arithmetic
// function (`add(x, x)`) of a 2-bit input `x`:
//
// ```
// // Original IR snippet
// fn simple_select(x: bits[2], a: bits[8], b: bits[8], c: bits[8]) -> bits[8] {
//   doubled_x: bits[2] = add(x, x)
//   ret result: bits[8] = sel(doubled_x, cases=[a, b, c], default=a)
// }
// ```
//
// `DataflowGraphAnalysis` finds `min_cut = {x}` with `unknown_bits = 2`, which
// matches `bits_needed = 2` for the 4-way `sel` while eliminating the `add`
// from the selector path. Evaluating `doubled_x` for `x = 0, 1, 2, 3` yields
// selector values `0, 2, 0, 2`, producing:
//
// ```
// // Optimized IR (after LutConversionPass and DCE)
// fn simple_select(x: bits[2], a: bits[8], b: bits[8], c: bits[8]) -> bits[8] {
//   ret result: bits[8] = sel(x, cases=[a, c, a, c])
// }
// ```
class LutConversionPass : public OptimizationFunctionBasePass {
 public:
  static constexpr std::string_view kName = "lut_conversion";
  explicit LutConversionPass()
      : OptimizationFunctionBasePass(kName, "LUT Conversion") {}
  ~LutConversionPass() override = default;

  // Computes the candidate nodes to convert to LUTs for the given function.
  static absl::StatusOr<std::vector<LutConversionCandidate>>
  ComputeLutConversionCandidates(FunctionBase* func,
                                 const QueryEngine& query_engine,
                                 OptimizationContext& context);

  // Computes the sequence of case values for the new select of the given
  // LUT candidate. When computing case values, earlier `cut_ternaries` elements
  // populate lower-ordered bits of the selector (i.e. each case's index) and
  // later elements populate higher-ordered bits.
  static absl::StatusOr<std::vector<Bits>> ComputeLutSelectCases(
      const LutConversionCandidate& candidate,
      std::vector<SharedLeafTypeTree<TernaryVector>>& cut_ternaries,
      const QueryEngine& query_engine);

  RedundancyGuard GetRedundancyGuard(
      const OptimizationPassOptions& options,
      OptimizationContext& context) const override;

 protected:
  absl::StatusOr<bool> RunOnFunctionBaseInternal(
      FunctionBase* f, const OptimizationPassOptions& options,
      PassResults* results, OptimizationContext& context) const override;
};

}  // namespace xls

#endif  // XLS_PASSES_LUT_CONVERSION_PASS_H_
