#ifndef XLS_PASSES_NON_SYNTH_SEPARATION_PASS_H_
#define XLS_PASSES_NON_SYNTH_SEPARATION_PASS_H_

#include <string_view>

#include "absl/status/statusor.h"
#include "xls/ir/package.h"
#include "xls/passes/optimization_pass.h"
#include "xls/passes/pass_base.h"

namespace xls {

// Separates out non-synthesizable nodes like assert/cover/trace from the main
// function into a cloned function. Every function effectively has two versions,
// one with synthesizable nodes and one without. The synthesizable version
// invokes the non-synthesizable version of its function. This ensures that
// non-synthesizable uses of values do not affect the optimization of the
// synthesizable parts of the function.
//
// Note: What follows was generated by the Gemini LLM. Not human verified.
//
// `NonSynthSeparationPass` isolates non-synthesizable operations (`assert`,
// `cover`, and `trace`) from the synthesizable logic of each function or proc
// in a package. Without this separation, values consumed by verification or
// debugging operations appear live to passes like Dead Code Elimination (DCE)
// or Proc state narrowing/elimination, preventing those passes from optimizing
// the synthesizable hardware path.
//
// ### How It Works
//
// 1. **Identification**: The pass inspects each `FunctionBase` in the package.
//    If a function or proc contains no `assert`, `cover`, or `trace` nodes, it
//    is left unchanged.
//
// 2. **Cloning into a `#[non_synth]` Function**: For each function or proc
//    containing non-synthesizable nodes, a new function named
//    `non_synth_<name>` (uniquified if needed) is created and marked with
//    `set_non_synth(true)`:
//    * **For a `Function`**: The function is cloned directly with the same
//      parameters. Its return value is replaced with an empty tuple `tuple()`,
//      and an `invoke` to `non_synth_<name>` (passing the function's
//      parameters) is inserted into the original function.
//    * **For a `Proc`**: The proc body is cloned into a stateless `Function`
//      via `CloneProcAsFunctionVisitor`, converting proc-specific constructs so
//      they can be passed as arguments to an `invoke` in the proc:
//      * **`Send`**: Bypassed in the cloned function by mapping the `send` node
//        directly to its mapped input token.
//      * **`Receive`**: The token at tuple index 0 is sliced out (`SliceTuple`)
//        in the proc, and the remaining payload elements are passed as an
//        argument to the `invoke` (becoming a `Param` in the cloned function,
//        where the mapped token is spliced back in at index 0).
//      * **`StateRead`**: Pure token state reads are replaced with
//        `literal(token)` in the cloned function. For non-token state elements,
//        the pass appends a duplicate state element `<state>_non_synth` marked
//        `non_synthesizable=true` (with the same initial value) and a
//        corresponding `state_read` in the proc, passing that read into the
//        `invoke`. If the state type contains tokens, token leaf elements are
//        stripped before the `invoke` and replaced with fresh `literal(token)`
//        nodes inside the cloned function.
//      * **`Next`**: Not copied into the cloned function; instead, for each
//        non-token `next_value` in the proc, a matching `next_value` node is
//        added to update the `<state>_non_synth` state element.
//
// 3. **Gate-to-Select Conversion in the Non-Synthesizable Function**: Any
//    `gate(cond, data)` operations inside `non_synth_<name>` are replaced with
//    `sel(cond, cases=[data], default=0)` (`ReplaceGatesWithSelectsVisitor`).
//    Because `gate` nodes are special power-optimization nodes that DCE does
//    not remove, converting them to `sel` prevents unnecessary gate duplication
//    and allows unused logic in the non-synthesizable function to be optimized
//    away.
//
// 4. **Stripping Non-Synthesizable Nodes from the Original Function/Proc**:
//    `RemoveNonSynthNodesVisitor` removes all `assert`, `trace`, and `cover`
//    nodes from the original `FunctionBase` (replacing `assert` and `trace`
//    uses with their input `token` operand and `cover` uses with `tuple()`).
//
// ### Example
//
// ```
// // Before
// fn my_func(x: bits[32]) -> bits[32] {
//   tok: token = literal(value=token)
//   intermediate: bits[32] = add(x, literal(value=1, bits=32))
//   is_zero: bits[1] = eq(intermediate, literal(value=0, bits=32))
//   assert.1: token = assert(tok, is_zero, message="intermediate is zero!")
//   ret result: bits[32] = umul(intermediate, literal(value=2, bits=32))
// }
// ```
//
// After `NonSynthSeparationPass` (and subsequent DCE cleanup):
//
// ```
// // Synthesizable version (original function, modified)
// fn my_func(x: bits[32]) -> bits[32] {
//   intermediate: bits[32] = add(x, literal(value=1, bits=32))
//   invoke.1: () = invoke(x, to_apply=non_synth_my_func)
//   ret result: bits[32] = umul(intermediate, literal(value=2, bits=32))
// }
//
// // Non-synthesizable version (newly created function)
// #[non_synth]
// fn non_synth_my_func(x: bits[32]) -> () {
//   tok: token = literal(value=token)
//   intermediate: bits[32] = add(x, literal(value=1, bits=32))
//   is_zero: bits[1] = eq(intermediate, literal(value=0, bits=32))
//   assert.1: token = assert(tok, is_zero, message="intermediate is zero!")
//   ret tuple.1: () = tuple()
// }
// ```
class NonSynthSeparationPass : public OptimizationPass {
 public:
  static constexpr std::string_view kName = "non_synth_separation";
  explicit NonSynthSeparationPass()
      : OptimizationPass(kName, "Non-Synthesizable Separation") {}
  ~NonSynthSeparationPass() override = default;

  RedundancyGuard GetRedundancyGuard(
      const OptimizationPassOptions& options,
      OptimizationContext& context) const override {
    return RedundancyGuard::CanSkip();
  }

 protected:
  absl::StatusOr<bool> RunInternal(Package* p,
                                   const OptimizationPassOptions& options,
                                   PassResults* results,
                                   OptimizationContext& context) const override;
};

}  // namespace xls

#endif  // XLS_PASSES_NON_SYNTH_SEPARATION_PASS_H_
