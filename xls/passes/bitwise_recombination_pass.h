namespace xls {

// Pass which recombines concats of contiguous bit slices & inverted bit slices
// from a single source node (and constants) into masked bitwise operations.
//
// The pass uses 1D dynamic programming optimal partitioning to balance
// readability:
//   - Identifies localized sub-runs that can be merged into clean 1-gate masks
//     (nibble-aligned or periodic, e.g. x ^ 0x5555).
//   - Naturally peels boundary constants (e.g. address alignment or padding)
//     to form clean hybrid concats like {x[31:8] ^ 24'h555555, 8'b0}.
//   - Preserves coarse struct/bus layouts where non-aligned hex masks would be
//     unreadable.
//   - Recombines dense bit-salad into 2-gate operations when the splinter count
//     is high.
//
// Recombined operations are composed in NOT -> AND -> XOR -> OR order:
//   - all inverted slices                 => not(x)
//   - raw and inverted slices             => (x ^ mask)
//   - raw slices and 0 literals           => (x & mask)
//   - raw slices and 1 literals           => (x | mask)
//   - raw slices, 0s, and 1s (no inv)     => ((x & mask_and) | mask_or)
//   - inverted and 1s (no raw)            => (not(x) | mask_or)
//   - raw, inverted, and 1s               => ((x ^ mask_xor) | mask_or)
//   - inverted and 0s (no raw)            => (not(x) & mask_and)
//   - raw, inverted, and 0s               => ((x & mask_and) ^ mask_xor)
//   - inverted, 0s, and 1s (no raw)       => ((not(x) & mask_and) | mask_or)
//   - all four (raw, inv, 0s, 1s)         => ((x & mask_and) ^ mask_xor)
//
// This is typically run late in the compiler pipeline (e.g. in codegen 1.5
// block cleanup and optimization) to fold un-cancelled bitwise splits back into
// clean, idiomatic hardware operations before Verilog emission.
//
// Note: What follows was generated by the Gemini LLM. Not human verified.
//
// The `BitwiseRecombinationPass` acts as a counterpart to
// `BitwiseSimplificationPass` and is intended to run after bitwise
// simplification has finished. While `BitwiseSimplificationPass` splits
// masked bitwise operations into `concat`s of `bit_slice`s, `literal`s, and
// `not`s to expose bit-level simplification opportunities, any remaining
// un-cancelled splinters can produce verbose bit-slice concatenations.
// `BitwiseRecombinationPass` re-folds contiguous runs of slices and constants
// back into concise, readable bitwise operations.
//
// **How it Works**:
//
// 1.  **Operand Classification (`ClassifyOperand`)**:
//     For each `concat` node, the pass classifies every operand into one of
//     four `SliceElementKind` categories if possible:
//     *   `kRaw`: `bit_slice(x, start, width)` or a full `bits`-typed node `x`
//         (`start = 0`).
//     *   `kInverted`: `not(bit_slice(x, start, width))`,
//         `bit_slice(not(x), start, width)`, or `not(x)`.
//     *   `kZero`: An all-zeros `literal` of width `w`.
//     *   `kOne`: An all-ones `literal` of width `w`.
//
// 2.  **Contiguous Run Formation (`TryFormRun`)**:
//     A candidate sub-span of `concat` operands (ordered MSB-to-LSB) forms a
//     valid contiguous run if all non-literal slices reference the same source
//     node `x` and their bit offsets (with literal widths filling the exact
//     intervening bit ranges) form a contiguous, in-bounds slice of `x`.
//
// 3.  **Cost Model and 1D Dynamic Programming (`SimplifyConcat`)**:
//     To avoid merging coarse bus fields into unreadable hex masks, the pass
//     evaluates candidate runs with `EvaluateSegmentCost`:
//     *   **Mask Periodicity (`GetMaskPeriodicity`)**: Masks that are all
//         zeros, nibble-aligned all ones, or periodically repeating at the
//         largest power-of-two period `p <= 16` with `2 * p <= hex_width` and
//         `2 <= p < width` whose virtual top-nibble continuation bits are all
//         zeros are classified as `kClean` and incur no penalty.
//         Non-nibble-aligned all-ones masks and periodic masks whose virtual
//         top-nibble continuation bits are nonzero are classified as
//         `kAlmostClean` and incur a flat penalty of `1`. Non-periodic
//         (`kUnclean`) masks incur a readability penalty proportional to their
//         bit width (`1` penalty unit per 8 bits).
//     *   **Gate Costs**: Unary `not` costs 1, each binary mask operation costs
//         2 plus its mask periodicity penalty, and using two binary masks
//         incurs an extra penalty of 1.
//     *   **DP Partitioning**: A 1D dynamic program finds the minimum-cost
//         partitioning of the `concat` operands into segments, favoring shorter
//         (unmerged) segments on ties.
//
// 4.  **Recombination Synthesis (`RecombineRun`)**:
//     Each merged segment of length `>= 2` is synthesized over a single base
//     `bit_slice` (or the full source node `x`) using at most two binary
//     bitwise gates in `not -> and -> xor -> or` order. When all four element
//     kinds (`kRaw`, `kInverted`, `kZero`, `kOne`) are present, the `and` mask
//     clears both `kZero` and `kOne` bitfields so the subsequent `xor` mask can
//     simultaneously invert `kInverted` bits and set `kOne` bits without a
//     third gate.
//
// **Example**:
//
// ```
// // Original IR (alternating raw/inverted nibbles with low zero padding)
// slice4: bits[4] = bit_slice(x, start=16, width=4)
// slice3: bits[4] = bit_slice(x, start=12, width=4)
// inv3: bits[4] = not(slice3)
// slice2: bits[4] = bit_slice(x, start=8, width=4)
// slice1: bits[4] = bit_slice(x, start=4, width=4)
// inv1: bits[4] = not(slice1)
// z0: bits[4] = literal(value=0)
// ret res: bits[20] = concat(slice4, inv3, slice2, inv1, z0)
//
// // Optimized IR (after dead code elimination; peels low zero padding and
// // recombines upper 16 bits into periodic XOR)
// hi: bits[16] = bit_slice(x, start=4, width=16)
// mask: bits[16] = literal(value=0x0f0f)
// xored: bits[16] = xor(hi, mask)
// z0: bits[4] = literal(value=0)
// ret res: bits[20] = concat(xored, z0)
// ```
class BitwiseRecombinationPass : public OptimizationFunctionBasePass {
 public:
  static constexpr std::string_view kName = "bitwise_recombine";
  explicit BitwiseRecombinationPass()
      : OptimizationFunctionBasePass(kName, "bitwise recombination") {}
  ~BitwiseRecombinationPass() override = default;

 protected:
  absl::StatusOr<bool> RunOnFunctionBaseInternal(
      FunctionBase* f, const OptimizationPassOptions& options,
      PassResults* results, OptimizationContext& context) const override;
};

}  // namespace xls

#endif  // XLS_PASSES_BITWISE_RECOMBINATION_PASS_H_
