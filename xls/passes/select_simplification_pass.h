// Collapses adjacent duplicate cases in `sel` by merging consecutive cases
// with the same outputs, OR-ing together the relevant bits of the selector.
// Returns the replacement `PrioritySelect` if any duplicate cases were
// collapsed, or nullptr if no adjacent duplicate cases were found.
absl::StatusOr<PrioritySelect*> SimplifyPrioritySelectDuplicateCases(
    PrioritySelect* sel);

// Base class which simplifies selects and one-hot-selects. Example
// optimizations include removing dead arms and eliminating selects with
// constant selectors.
//
// Note: What follows was generated by the Gemini LLM. Not human verified.
//
// `SelectSimplificationPassBase` provides the shared implementation for
// `SelectSimplificationPass` (`select_simp`) and
// `SelectRangeSimplificationPass` (`select_range_simp`). It simplifies
// `select`, `one_hot_select`, `priority_select`, and `one_hot` operations, as
// well as comparison operations consuming selects.
//
// When `with_range_analysis` is `false` (`SelectSimplificationPass`), the pass
// queries a `UnionQueryEngine` of `StatelessQueryEngine` and
// `LazyTernaryQueryEngine`. When `with_range_analysis` is `true`
// (`SelectRangeSimplificationPass`), it queries `StatelessQueryEngine` and
// `PartialInfoQueryEngine` (combining ternary and interval/range analysis). At
// `SplitsEnabled` optimization levels, it also uses `BitProvenanceAnalysis` to
// track bit sources across select arms.
//
// Key optimizations performed by `SelectSimplificationPassBase`:
//
// 1.  **Hoisting Comparisons with Literals
//     (`TryHoistCompareThroughSelectLike`)**:
//     If a comparison (`CompareOp`) compares a literal against a single-use
//     `Select`, `PrioritySelect`, or `OneHotSelect` (with
//     `ExactlyOneBitTrue(selector)`) where at most one arm is non-literal, the
//     comparison is pushed into the select arms so downstream constant folding
//     can fold the literal arms.
//
// 2.  **Constant or Known Selector Patterns**:
//     *   `Select` with a known constant selector is replaced by the selected
//         case (or `default_value` if out of bounds).
//     *   `PrioritySelect` with an all-zero selector is replaced by
//         `default_value`; if the selector has a known `1` at bit `i` and all
//         lower bits `0..i-1` are known `0`, it is replaced by `cases[i]`.
//     *   `OneHotSelect` with a known constant selector is replaced by `0` (if
//         all selector bits are `0`), the single active case (if 1-hot), or an
//         `or` of the active cases (if multi-hot).
//
// 3.  **Three-Way Comparison Simplification**:
//     Recognizes 2-arm `Select` and `PrioritySelect` trees that perform a
//     three-way comparison (`ult` and `ugt`, or `slt` and `sgt` on the same
//     operands) and rewrites the second inequality comparison into an equality
//     check (`eq`).
//
// 4.  **Identical Cases and Unary Selector Reordering**:
//     *   A `Select` whose cases (and `default_value`) are all identical is
//         replaced by that value.
//     *   A multi-bit `OneHotSelect` whose cases are all identical is replaced
//         by `sel(selector != 0, cases=[0, case[0]])`.
//     *   If a `Select` without a `default_value` has a selector that is a
//         unary function (`neg`, `not`, `rev`, `encode`, `one_hot`, or unary
//         slice/concat/arithmetic expression) of a narrower or equal-width
//         `base_selector`, `MaybeReorderSelect` evaluates the selector map via
//         `InterpretNode` and reorders the cases to use `base_selector`
//         directly.
//
// 5.  **Tuple Decomposition**:
//     Decomposes tuple-typed `Select`, `OneHotSelect`, and `PrioritySelect`
//     nodes into a `Tuple` of per-element selects.
//
// 6.  **Merging Equivalent Arms and Absorbing Inverted Selectors**:
//     *   When `NarrowingEnabled`, `OneHotSelect` cases with identical values
//         have their selector bits `or`-reduced into a single arm.
//     *   When `SplitsEnabled`, adjacent identical cases in a `PrioritySelect`
//         have their selector bits `or`-reduced
//         (`SimplifyPrioritySelectDuplicateCases`).
//     *   For 2-way `Select` and 1-bit-selector `PrioritySelect` with `not(p)`
//         as selector, absorbs the `not` and swaps the two arms.
//
// 7.  **Boolean Gate Decomposition and Mask Conversion**:
//     *   When `NarrowingEnabled`, 1-bit `Select` and `PrioritySelect` with a
//         1-bit selector and a known-constant (or selector-equal) arm, as well
//         as 1-bit 1-way `OneHotSelect`, are lowered to `and`/`or`/`not` gates.
//     *   When `SplitsEnabled`, 1-bit 2-way `OneHotSelect` is lowered to
//         `or(and(sel[0], case[0]), and(sel[1], case[1]))`.
//     *   When `SplitsEnabled`, `MaybeConvertSelectToMask` replaces a `Select`,
//         `PrioritySelect`, or `OneHotSelect` having no non-zero arms with `0`,
//         or having a single non-zero `bits`-typed arm with
//         `and(non_zero_arm, sign_ext(cond))` (or a 2-arm `Select` against zero
//         for non-`bits` types with more than two arms).
//
// 8.  **Pruning and Narrowing `OneHotSelect` and `PrioritySelect` Arms**:
//     *   When `NarrowingEnabled`, removes `OneHotSelect` arms whose selector
//         bit is known `0` or whose case value is known `0`.
//     *   When `NarrowingEnabled`, narrows a `PrioritySelect` selector to the
//         shortest prefix where `AtLeastOneTrue` holds (setting `default_value`
//         to the highest reachable case), removes trailing arms matching
//         `default_value`, and removes arms with known-`0` selector bits
//         (pruning interior arms only when `SplitsEnabled`).
//     *   When `SplitsEnabled`, collapses a `PrioritySelect` whose cases and
//         `default_value` take at most two distinct values into a 1-bit
//         `PrioritySelect`.
//
// 9.  **Width Squeezing (`TrySqueezeSelect`)**:
//     When `SplitsEnabled`, slices out common leading/trailing constant bits or
//     unchanged bit slices (via `BitProvenanceAnalysis`) shared across all
//     arms, and (when `with_range_analysis` is `true`) squeezes common
//     sign-extended MSBs using `interval_ops::MinimumSignedBitCount`.
//
// 10. **Collapsing Consecutive 2-Way `Select`s**:
//     Folds cascaded 2-way (1-bit-selector) `Select`s that share a common arm
//     (combining their selectors with `or`/`nand`/`not`) or share the exact
//     same selector.
//
// 11. **`OneHot` Simplifications and Bit-Based Splitting**:
//     *   Replaces `OneHotSelect(OneHot(x))` with an equivalent
//         `PrioritySelect` when the `OneHot` has no non-`OneHotSelect` users.
//     *   Simplifies `OneHot` with a 1-bit input (`NarrowingEnabled`), an
//         `AtMostOneBitTrue` input, or an `ExactlyOneBitUnknown` input.
//     *   When `SplitsEnabled`, `MaybeSplitBitBasedSelect` uses a worklist and
//         `BitProvenanceAnalysis` to split `OneHotSelect` and `PrioritySelect`
//         nodes (up to 64 bits wide) into narrower selects concatenated
//         together along runs of distinct vs. shared-source bits.
class SelectSimplificationPassBase : public OptimizationFunctionBasePass {
 public:
  ~SelectSimplificationPassBase() override = default;

 protected:
  explicit SelectSimplificationPassBase(std::string_view short_name,
                                        std::string_view name,
                                        bool with_range_analysis = false)
      : OptimizationFunctionBasePass(short_name, name),
        range_analysis_(with_range_analysis) {}

  RedundancyGuard GetRedundancyGuard(
      const OptimizationPassOptions& options,
      OptimizationContext& context) const override;

  absl::StatusOr<bool> RunOnFunctionBaseInternal(
      FunctionBase* f, const OptimizationPassOptions& options,
      PassResults* results, OptimizationContext& context) const override;

  bool range_analysis_;
};

// Pass which simplifies selects and one-hot-selects. Example optimizations
// include removing dead arms and eliminating selects with constant selectors.
// Uses ternary analysis to determine possible values.
//
// Note: What follows was generated by the Gemini LLM. Not human verified.
//
// `SelectSimplificationPass` (`select_simp`) simplifies `select`,
// `one_hot_select`, `priority_select`, and `one_hot` operations in a
// `FunctionBase` by running `SelectSimplificationPassBase` with
// `with_range_analysis=false`. It uses a `UnionQueryEngine` combining
// `StatelessQueryEngine` and `LazyTernaryQueryEngine` (plus
// `BitProvenanceAnalysis` when `SplitsEnabled`) to evaluate known bits and bit
// provenance without the overhead of full interval/range analysis.
//
// Key optimizations performed include:
//
// *   **Hoisting Comparisons with Literals**: Pushes comparisons (`CompareOp`)
//     against a literal through a single-use `Select`, `PrioritySelect`, or
//     1-hot `OneHotSelect` when at most one arm is non-literal.
// *   **Constant and Known Selector Elimination**: Replaces `Select`,
//     `PrioritySelect`, and `OneHotSelect` nodes when their selector bits
//     uniquely determine the active case(s) or default value.
// *   **Three-Way Comparison Canonicalization**: Rewrites nested 2-way `Select`
//     and `PrioritySelect` three-way comparisons (`<` and `>`) so the second
//     comparison uses `eq`.
// *   **Identical Arms & Selector Reordering**: Folds selects with identical
//     arms, reduces identical-arm `OneHotSelect`s to a 1-bit `Select` on
//     `selector != 0`, and reorders `Select` cases when the selector is a unary
//     function of a narrower or equal-width base value.
// *   **Tuple Decomposition**: Splits tuple-typed `Select`, `OneHotSelect`, and
//     `PrioritySelect` nodes into per-element selects bundled in a `Tuple`.
// *   **Arm Commoning, Pruning, and Gate Lowering**: Merges duplicate arms in
//     `OneHotSelect` (`NarrowingEnabled`) and adjacent duplicate arms in
//     `PrioritySelect` (`SimplifyPrioritySelectDuplicateCases`), absorbs
//     inverted 1-bit selectors (`not`), lowers 1-bit muxes with
//     constant/selector arms into `and`/`or`/`not` gates, converts
//     single-nonzero-arm selects into `and` masks (`SplitsEnabled`), and prunes
//     dead/zero arms.
// *   **Width Squeezing and Consecutive Select Collapsing**: Slices off common
//     known constant or provenance-shared leading/trailing bits across select
//     arms (`SplitsEnabled`), and collapses consecutive 2-way `Select`s that
//     share a common case or selector.
// *   **`OneHot` Lowering and Bit-Based Select Splitting**: Converts
//     `OneHotSelect(OneHot(x))` into `PrioritySelect`, simplifies `OneHot` on
//     1-bit, mutually exclusive, or single-unknown-bit inputs, and splits
//     `OneHotSelect`/`PrioritySelect` nodes (<= 64 bits) along runs of shared
//     vs. distinct bit sources (`SplitsEnabled`).
class SelectSimplificationPass : public SelectSimplificationPassBase {
 public:
  static constexpr std::string_view kName = "select_simp";
  SelectSimplificationPass()
      : SelectSimplificationPassBase(kName, "Select Simplification",
                                     /*with_range_analysis=*/false) {}
  ~SelectSimplificationPass() override = default;
};

// Pass which simplifies selects and one-hot-selects. Example optimizations
// include removing dead arms and eliminating selects with constant selectors.
// Uses range analysis to determine possible values.
//
// Note: What follows was generated by the Gemini LLM. Not human verified.
//
// `SelectRangeSimplificationPass` (`select_range_simp`) runs the select
// simplification suite (`SelectSimplificationPassBase`) with
// `with_range_analysis=true`. Instead of `LazyTernaryQueryEngine`, it combines
// `StatelessQueryEngine` with `PartialInfoQueryEngine` (wrapped in
// `CachedStateElementQueryEngine` for `Proc`s, plus `BitProvenanceAnalysis`
// when `SplitsEnabled`) to reason over combined ternary and interval/range
// information directly.
//
// Enabling range analysis extends all `SelectSimplificationPass` optimizations
// with interval-aware reasoning:
//
// *   **Range-Proven Selector Constraints**: `PartialInfoQueryEngine` can prove
//     that selector bits are constant, mutually exclusive (`AtMostOneBitTrue`),
//     exhaustive (`AtLeastOneTrue` / `AtLeastOneBitTrue`), or one-hot
//     (`ExactlyOneBitTrue`) based on value intervals (such as bounded loop
//     indices or arithmetic comparisons) that ternary analysis alone cannot
//     resolve. This unlocks additional dead-arm pruning, `PrioritySelect`
//     selector narrowing, mask conversion, and comparison hoisting.
// *   **Sign-Extension Width Squeezing (`TrySqueezeSelect`)**: When
//     `SplitsEnabled` and `with_range_analysis=true`, `TrySqueezeSelect`
//     queries `PartialInfoQueryEngine::GetIntervals` on each select arm and
//     computes `interval_ops::MinimumSignedBitCount` across all cases. If all
//     arms fit in a narrower signed bit-width `W`, the select is narrowed to
//     `W` bits and sign-extended (`sign_ext`) back to the original width.
class SelectRangeSimplificationPass : public SelectSimplificationPassBase {
 public:
  static constexpr std::string_view kName = "select_range_simp";
  SelectRangeSimplificationPass()
      : SelectSimplificationPassBase(kName, "Select Range Simplification",
                                     /*with_range_analysis=*/true) {}
  ~SelectRangeSimplificationPass() override = default;
};

