#ifndef XLS_SOLVERS_SYMEX_SYMBOLIC_PATH_H_
#define XLS_SOLVERS_SYMEX_SYMBOLIC_PATH_H_

#include <cstdint>
#include <optional>
#include <string_view>
#include <vector>

#include "xls/ir/node.h"
#include "xls/ir/nodes.h"
#include "xls/ir/value.h"
#include "z3/src/api/z3.h"  // IWYU pragma: keep
#include "z3/src/api/z3_api.h"

namespace xls::solvers::symex {

// Represents a branch decision made at a multiplexer (`xls::Select`) node
// during symbolic execution.
struct BranchDecision {
  // Multiplexer node where the branch decision was made.
  const Node* mux_node = nullptr;

  // 0-based index of the chosen arm (0..N-1 for cases, or N for default).
  int64_t arm_index = 0;

  // Returns true if this decision chose the default fallback arm of the
  // multiplexer (i.e. arm_index >= number of explicit cases).
  bool is_default() const {
    if (mux_node != nullptr && mux_node->Is<Select>()) {
      return arm_index >= mux_node->As<Select>()->cases().size();
    }
    return false;
  }
};

// Represents a parameter assignment in a generated test vector.
struct ParamAssignment {
  const Param* param = nullptr;
  Value value;
};

// Represents a fully explored symbolic execution path through an XLS function.
struct SymbolicPath {
  // Accumulated conjunction of branch conditions along this path.
  Z3_ast path_condition = nullptr;

  // Symbolic Z3 AST expression for the function's return value.
  Z3_ast return_value = nullptr;

  // Sequence of multiplexer branch decisions taken along this path.
  std::vector<BranchDecision> branch_decisions;

  // Concrete parameter assignments (test vector) generated by the solver
  // to exercise this execution path.
  std::vector<ParamAssignment> generated_test;

  // Returns concrete argument values in parameter declaration order, suitable
  // for direct execution with xls::InterpretFunction.
  std::vector<Value> input_values() const {
    std::vector<Value> values;
    values.reserve(generated_test.size());
    for (const ParamAssignment& assignment : generated_test) {
      values.push_back(assignment.value);
    }
    return values;
  }

  // Returns the assigned value for a parameter by name, or nullopt if not
  // found.
  std::optional<Value> GetParamValue(std::string_view name) const {
    for (const ParamAssignment& assignment : generated_test) {
      if (assignment.param != nullptr && assignment.param->name() == name) {
        return assignment.value;
      }
    }
    return std::nullopt;
  }

  // Returns the assigned value for the given parameter node, or nullopt if not
  // found.
  std::optional<Value> GetParamValue(const Param* param) const {
    for (const ParamAssignment& assignment : generated_test) {
      if (assignment.param == param) {
        return assignment.value;
      }
    }
    return std::nullopt;
  }
};

}  // namespace xls::solvers::symex

#endif  // XLS_SOLVERS_SYMEX_SYMBOLIC_PATH_H_
